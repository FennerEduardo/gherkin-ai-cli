/* ==========================================================================
   `ghk reverse explain` and `ghk reverse review` (PLAN-3.3.0-reverse-plus
   RV-01, RV-03), on the Express brownfield fixture (never generated by ghk).
   ========================================================================== */

import { describe, it, expect, afterEach } from 'vitest';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { execFileSync } from 'child_process';
import { REVERSE_DIR, readCandidates, runAccept, runPropose, runScan } from '../../src/core/reverse';
import { applyDecisions, buildReviewReport, explainOperation, findOperation, readReview, approvedOnly } from '../../src/core/reverse/review';
import { handleReverseCommand } from '../../src/commands/reverse';
import { UsageError } from '../../src/core/errors';
import { clearTsProjects } from '../../src/core/reverse/analyzers/typescript/project';

const FIXTURE = path.join(__dirname, '..', 'fixtures', 'golden', 'brownfield-express');
const dirs: string[] = [];
const git = (cwd: string, ...args: string[]) => execFileSync('git', args, { cwd, stdio: ['ignore', 'pipe', 'pipe'] }).toString();

function copy(): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ghk-review-'));
  fs.cpSync(FIXTURE, dir, { recursive: true });
  fs.writeFileSync(path.join(dir, '.env'), 'API_TOKEN=sk-live-0123456789abcdef0123456789abcdef\n');
  git(dir, 'init', '-q', '-b', 'main');
  git(dir, 'add', '-A');
  git(dir, '-c', 'user.name=t', '-c', 'user.email=t@example.com', 'commit', '-q', '-m', 'existing');
  dirs.push(dir);
  return dir;
}

async function proposed(dir: string) {
  clearTsProjects();
  const scan = await runScan(dir);
  const result = runPropose(dir, scan);
  return { scan, result };
}

afterEach(() => { for (const d of dirs.splice(0)) fs.rmSync(d, { recursive: true, force: true }); });

describe('reverse explain', () => {
  it('explains where the names, the confidence and the evidence of an operation come from', async () => {
    const dir = copy();
    const { scan, result } = await proposed(dir);
    expect(findOperation(result.candidates, 'placeorder')).toHaveLength(1);
    const [byPath] = findOperation(result.candidates, 'POST /orders/:id/cancel');
    expect(byPath.operation.name).toBe('CancelOrder');
    const x = explainOperation(findOperation(result.candidates, 'PlaceOrder')[0], scan.evidence);
    expect(x.endpoint).toBe('POST /orders');
    expect(x.name.origin).toBe('operationId');
    expect(x.aggregateOrigin.origin).toBe('path');
    expect(x.confidence.level).toBe('confirmed');
    expect(x.confidence.reason).toMatch(/OpenAPI|test/);
    const roles = x.chain.map(l => l.role);
    expect(roles[0]).toBe('endpoint');
    expect(roles).toEqual(expect.arrayContaining(['guard', 'input', 'state', 'response']));
    expect(x.chain.every(l => /^src\/|^docs\//.test(l.file) && l.line > 0)).toBe(true);
    const cancel = explainOperation(byPath, scan.evidence);
    expect(cancel.name.origin).toMatch(/operationId|path/);
  });

  it('is a usage error without a target or for an unknown one', async () => {
    const dir = copy();
    await proposed(dir);
    const cwd = process.cwd();
    process.chdir(dir);
    try {
      await expect(handleReverseCommand('explain', {}, [])).rejects.toBeInstanceOf(UsageError);
      await expect(handleReverseCommand('explain', {}, ['ShipRocket'])).rejects.toThrow(/No operation matches/);
    } finally { process.chdir(cwd); }
  });
});

describe('reverse review', () => {
  it('shows each scenario with the code behind it, secrets redacted and nothing written outside .ghe/reverse', async () => {
    const dir = copy();
    const { scan, result } = await proposed(dir);
    const report = buildReviewReport(dir, result.candidates, scan.evidence, readReview(dir, REVERSE_DIR), result.unresolved);
    expect(report.counts.pending).toBeGreaterThan(0);
    const excerpt = report.proposals[0].scenarios[0].steps.flatMap(s => s.evidence).find(e => e.excerpt)!.excerpt!;
    expect(excerpt.lines.length).toBeGreaterThan(1);
    expect(JSON.stringify(report)).not.toContain('sk-live-0123456789abcdef');
    expect(git(dir, 'status', '--porcelain', '--untracked-files=all')).toBe('');
  });

  it('records decisions, accept takes only the approved scenarios, and a code change makes a decision stale', async () => {
    const dir = copy();
    const { scan, result } = await proposed(dir);
    const { review, changed, unmatched } = applyDecisions(readReview(dir, REVERSE_DIR), result.candidates, [
      { decision: 'approve', selector: '@PlaceOrder' },
      { decision: 'reject', selector: '@CancelOrder' },
      { decision: 'approve', selector: 'no such scenario' }
    ], 'checked with the product owner');
    expect(changed.length).toBeGreaterThan(1);
    expect(unmatched).toEqual(['no such scenario']);
    fs.writeFileSync(path.join(dir, REVERSE_DIR, 'review.json'), JSON.stringify(review, null, 2));

    const accepted = runAccept(dir, scan, readCandidates(dir)!, { all: true, write: true });
    expect(accepted.written.map(w => w.file)).toEqual(['features/discovered/order.feature']);
    const text = fs.readFileSync(path.join(dir, 'features/discovered/order.feature'), 'utf8');
    expect(text).toMatch(/@command:PlaceOrder/);
    expect(text).not.toMatch(/@command:CancelOrder/);
    expect(accepted.notApproved!.every(n => n.status === 'rejected')).toBe(true);
    // --ignore-review takes everything.
    const all = runAccept(dir, scan, readCandidates(dir)!, { all: true, write: false, force: true, ignoreReview: true });
    expect(all.notApproved).toBeUndefined();

    // The code under PlaceOrder moves: its decisions no longer apply until reviewed again.
    const file = path.join(dir, 'src/orders.js');
    fs.writeFileSync(file, `// moved\n// down\n${fs.readFileSync(file, 'utf8')}`);
    const again = await proposed(dir);
    const { candidates, left } = approvedOnly(review, again.result.candidates);
    expect(candidates).toHaveLength(0);
    expect(left.some(l => l.status === 'stale')).toBe(true);
  });

  it('records decisions through the command, audited, and rejects a selector that matches nothing', async () => {
    const dir = copy();
    await proposed(dir);
    const cwd = process.cwd();
    process.chdir(dir);
    try {
      await handleReverseCommand('review', { approve: ['all'], json: true }, []);
      const review = readReview(dir, REVERSE_DIR);
      expect(Object.values(review.decisions).every(d => d.decision === 'approve')).toBe(true);
      await expect(handleReverseCommand('review', { reject: ['nothing like this'] }, [])).rejects.toThrow(/No scenario matches/);
      await expect(handleReverseCommand('review', { interactive: true }, [])).rejects.toThrow(/terminal/);
      await expect(handleReverseCommand('review', {}, ['Shipment'])).rejects.toThrow(/No proposal matches/);
    } finally { process.chdir(cwd); }
  });
});
