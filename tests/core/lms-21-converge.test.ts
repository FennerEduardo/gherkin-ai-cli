/* ==========================================================================
   LMS #21 (PLAN-3.3.0): `ghk converge` passed unimplemented scaffolds.

   A project generated by gherkin-ai has a kernel whose own tests pass, so
   without a coverage report Code Coverage was "n/a" and left out of the
   score: a feature whose step definitions were all still the generated
   pending stubs converged. Now that case scores 0 with the reason; once a
   step is implemented (or a coverage report exists) nothing changes.
   ========================================================================== */

import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { calculateConvergence, pendingStepScaffolds } from '../../src/core/convergence-engine';
import { parseGherkinText } from '../../src/core/gherkin-parser';

const FEATURE = 'Feature: Orders\n  As a customer\n  Scenario: Place an order\n    Given a customer\n    When the customer places an order\n    Then the order is placed\n';
const PENDING_STEPS = "import { Given, When, Then } from '@cucumber/cucumber';\nGiven('a customer', function () {\n  return 'pending';\n});\n";
const IMPLEMENTED_STEPS = "import { Given } from '@cucumber/cucumber';\nGiven('a customer', function () {\n  this.customer = { id: 'c-1' };\n});\n";

describe('LMS #21: converge and unimplemented scaffolds', () => {
  let dir: string;
  const put = (rel: string, content: string) => { fs.mkdirSync(path.dirname(path.join(dir, rel)), { recursive: true }); fs.writeFileSync(path.join(dir, rel), content); };
  const coverage = () => calculateConvergence(parseGherkinText(FEATURE), 'features/orders.feature', dir).dimensions.find(d => d.name === 'Code Coverage')!;

  beforeEach(() => {
    dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ghk-lms21-'));
    put('features/orders.feature', FEATURE);
    put('.ghe/inventory.json', JSON.stringify({ version: '2', artifacts: [
      { filePath: 'test/steps/orders.steps.ts', type: 'test', feature: 'features/orders.feature', checksum: 'x' },
      { filePath: 'cucumber.js', type: 'test', feature: 'features/orders.feature', checksum: 'y' }
    ], executions: [] }));
  });
  afterEach(() => fs.rmSync(dir, { recursive: true, force: true }));

  it('scores 0 (not n/a) when every step definition is still the generated pending stub', () => {
    put('test/steps/orders.steps.ts', PENDING_STEPS);
    expect(pendingStepScaffolds(dir, './', 'features/orders.feature')).toEqual({ files: ['test/steps/orders.steps.ts'], total: 1 });
    const dim = coverage();
    expect(dim.applicable).not.toBe(false);
    expect(dim).toMatchObject({ score: 0, status: 'fail' });
    expect(dim.details[0]).toMatch(/Behaviour not implemented/);
  });

  it('stays n/a once the steps are implemented, and outside generated projects', () => {
    put('test/steps/orders.steps.ts', IMPLEMENTED_STEPS);
    expect(coverage().applicable).toBe(false);
    fs.rmSync(path.join(dir, '.ghe'), { recursive: true });
    put('test/steps/orders.steps.ts', PENDING_STEPS);
    expect(coverage().applicable).toBe(false);
  });

  it('a coverage report is always measured as such', () => {
    put('test/steps/orders.steps.ts', PENDING_STEPS);
    put('coverage/coverage-summary.json', JSON.stringify({ total: { lines: { pct: 90 }, statements: { pct: 90 }, functions: { pct: 90 }, branches: { pct: 90 } } }));
    const dim = coverage();
    expect(dim).toMatchObject({ score: 90 });
    // …but the pending stubs are reported, not silent.
    expect(dim.details.some(d => /still the generated pending stubs/.test(d))).toBe(true);
  });

  it('recognises the pending markers of every generated stack', () => {
    for (const [file, text] of [
      ['src/test/java/x/bdd/OrderSteps.java', 'throw new TestAbortedException("Pending step: implement it, then remove this line");'],
      ['tests/Orders.Tests/Steps/OrderSteps.cs', 'throw new PendingStepException();'],
      ['features/step_definitions/orders_steps.rb', "Given('a customer') do\n  pending\nend"],
      ['tests/steps/test_orders_steps.py', 'pytest.skip("pending")'],
      ['features/steps/orders_steps.go', 'return godog.ErrPending']
    ]) {
      put('.ghe/inventory.json', JSON.stringify({ version: '2', artifacts: [{ filePath: file, feature: 'features/orders.feature' }], executions: [] }));
      put(file, text);
      expect(pendingStepScaffolds(dir, './', 'features/orders.feature').files, file).toEqual([file]);
    }
  });
});
