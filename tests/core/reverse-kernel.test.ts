/* ==========================================================================
   `ghk reverse` on code generated by gherkin-ai (PLAN-3.3.0 R-19, §4)

   Generated services expose one dispatcher (`POST <route>/{id}/{command}`);
   the commands and the events they record live in the aggregate. The
   ghk-kernel adapter reads them in every kernel language. The fixture holds
   trimmed TypeScript (Express route table, no per-command comment), Python
   and Go kernels with the features they come from: the round trip must
   recover every aggregate, command and event (F1 = 1).
   ========================================================================== */

import { describe, it, expect, beforeEach } from 'vitest';
import fs from 'fs';
import path from 'path';
import { runPropose, runScan } from '../../src/core/reverse';
import { aggregateCommands, eventFromReference, kernelValidations, pascalOf } from '../../src/core/reverse/analyzers/ghk-kernel/ghk-kernel';
import { expectedModel, foundModel, scoreRoundTrip, scoreSet } from '../../src/core/reverse/roundtrip';
import { clearTsProjects } from '../../src/core/reverse/analyzers/typescript/project';
import { baseForm, isInfrastructureEndpoint } from '../../src/core/reverse/candidates';

const FIXTURE = path.join(__dirname, '..', 'fixtures', 'reverse', 'ghk-kernel');

describe('ghk-kernel helpers', () => {
  it('reads the event a command records in each kernel language', () => {
    expect(eventFromReference('OrderEventType.OrderPlaced')).toBe('OrderPlaced');
    expect(eventFromReference('EventType::OrderPlaced')).toBe('OrderPlaced');
    expect(eventFromReference('ShipmentEventShipmentDispatched', 'Shipment')).toBe('ShipmentDispatched');
    expect(aggregateCommands("  fun placeOrder(command: OrderCommand): OrderDomainEvent {\n    assertValid(command)\n    return record(OrderEventType.OrderPlaced, command.payload)\n  }")).toEqual([{ method: 'placeOrder', event: 'OrderPlaced', line: 1 }]);
    expect(aggregateCommands('  def place_order(command)\n    assert_valid!(command)\n    record("OrderPlaced", command.payload)\n  end')).toEqual([{ method: 'place_order', event: 'OrderPlaced', line: 1 }]);
    expect(aggregateCommands('  def place_order(%__MODULE__{} = aggregate, command), do: execute(aggregate, command, "OrderPlaced")')).toEqual([{ method: 'place_order', event: 'OrderPlaced', line: 1 }]);
    expect(aggregateCommands('    public OrderDomainEvent PlaceOrder(OrderCommand command)\n    {\n        AssertValid(command);\n        return Record(OrderEventTypes.OrderPlaced, command.Payload);\n    }')).toEqual([{ method: 'PlaceOrder', event: 'OrderPlaced', line: 1 }]);
  });

  it('names agree between method, snake and Pascal forms (the generator\'s own splitting)', () => {
    expect(pascalOf('process_nest_js_y_renderizado')).toBe(pascalOf('processNestJsYRenderizado'));
    expect(pascalOf('assert_valid!')).toBe('AssertValid');
  });

  it('takes the literal messages of assertValid, not the interpolated ones', () => {
    const text = fs.readFileSync(path.join(FIXTURE, 'src', 'domain', 'order.aggregate.ts'), 'utf8');
    expect(kernelValidations(text).map(v => v.message)).toEqual(['Command id is required']);
  });

  it('conjugation and infrastructure paths', () => {
    expect([baseForm('processes the order'), baseForm('applies'), baseForm('places an order'), baseForm('cancels')]).toEqual(['process the order', 'apply', 'place an order', 'cancel']);
    expect(['/health', '/api/v1/health/live', '/actuator/health', '/swagger-ui', '/v3/api-docs'].every(isInfrastructureEndpoint)).toBe(true);
    expect(isInfrastructureEndpoint('/api/v1/orders')).toBe(false);
  });
});

describe('ghk reverse on generated kernels (TypeScript, Python, Go)', () => {
  beforeEach(() => clearTsProjects());

  it('recovers every aggregate, command and event of the features (F1 = 1) without writing anything', async () => {
    const before = fs.readdirSync(FIXTURE, { recursive: true }).map(String).sort();
    const scan = await runScan(FIXTURE, { write: false });
    expect(scan.analyzers.map(a => a.id)).toContain('ghk-kernel');
    const result = runPropose(FIXTURE, scan, { write: false });
    const features = fs.readdirSync(path.join(FIXTURE, 'features')).map(f => path.join(FIXTURE, 'features', f));
    const score = scoreRoundTrip(expectedModel(features), foundModel(result.candidates));
    expect(score.commands.missing).toEqual([]);
    expect(score.events.missing).toEqual([]);
    expect(score.aggregates.extra, 'the /health route is not an aggregate').toEqual([]);
    expect(score.f1).toBe(1);
    expect(fs.readdirSync(FIXTURE, { recursive: true }).map(String).sort()).toEqual(before);
  });

  it('turns the dispatcher into one operation per command, with the kernel validation as a negative path', async () => {
    const result = runPropose(FIXTURE, await runScan(FIXTURE, { write: false }), { write: false });
    const ops = result.candidates.map(c => `${c.aggregate}.${c.operation.name} ${c.operation.method} ${c.operation.path}`).sort();
    expect(ops).toEqual([
      'Invoice.PayInvoice POST /api/v1/invoice/{id}/pay_invoice',
      'Order.CancelOrder POST /api/v1/order/{id}/cancel_order',
      'Order.PlaceOrder POST /api/v1/order/{id}/place_order',
      'Shipment.DispatchShipment POST /api/v1/shipment/{id}/dispatch_shipment'
    ]);
    const place = result.candidates.find(c => c.operation.name === 'PlaceOrder')!;
    expect(place.scenarios.map(s => s.name)).toEqual(['Place the order', 'Placing the order is rejected when command id is required']);
    expect(result.proposals.every(p => p.lint.passed && p.roundTrip.ok)).toBe(true);
    // The generic dispatcher itself never becomes an operation.
    expect(result.candidates.some(c => c.operation.path.endsWith('{command}'))).toBe(false);
  });

  it('scores sets with precision, recall and F1', () => {
    expect(scoreSet(['PlaceOrder', 'CancelOrder'], ['placeorder', 'ShipOrder'])).toMatchObject({ matched: 1, precision: 0.5, recall: 0.5, f1: 0.5, missing: ['CancelOrder'], extra: ['ShipOrder'] });
    expect(scoreSet([], [])).toMatchObject({ precision: 1, recall: 1, f1: 1 });
  });
});
