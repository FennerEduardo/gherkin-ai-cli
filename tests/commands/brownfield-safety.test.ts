import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { handleInitCommand, generateGovernanceConfig } from '../../src/commands/init';
import { handleAddCommand } from '../../src/commands/add';
import { findStaleFiles } from '../../src/core/upgrade';
import { readInventoryFile } from '../../src/core/inventory';
import { loadConfig } from '../../src/core/config';

const FEATURE = `Feature: Invoicing
  Scenario: Issue an invoice
    Given a customer with an open order
    When the clerk issues an invoice for the order
    Then the invoice is issued
`;

describe('existing projects are not overwritten', () => {
  const cwd = process.cwd();
  let dir: string;
  const read = (rel: string) => fs.readFileSync(path.join(dir, rel), 'utf8');

  beforeEach(() => {
    dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ghk-brownfield-'));
    process.chdir(dir);
    vi.spyOn(console, 'log').mockImplementation(() => {});
  });
  afterEach(() => {
    process.chdir(cwd);
    vi.restoreAllMocks();
    fs.rmSync(dir, { recursive: true, force: true });
  });

  it('init refuses to replace an existing configuration, unless --force', async () => {
    fs.writeFileSync(path.join(dir, 'gherkin-ai.config.json'), JSON.stringify({ projectName: 'keep-me', stack: { language: 'java', framework: 'quarkus' } }));
    await expect(handleInitCommand({ yes: true, language: 'typescript', framework: 'nestjs' })).rejects.toMatchObject({ exitCode: 2 });
    expect(JSON.parse(read('gherkin-ai.config.json')).projectName).toBe('keep-me');

    await handleInitCommand({ yes: true, force: true, projectName: 'fresh', language: 'typescript', framework: 'nestjs' });
    expect(JSON.parse(read('gherkin-ai.config.json')).projectName).toBe('fresh');
  });

  it('keeps an edited governance policy and writes the new version next to it', () => {
    const config = { projectName: 'billing', stack: { language: 'typescript', framework: 'nestjs' } } as Parameters<typeof generateGovernanceConfig>[0];
    generateGovernanceConfig(config, dir);
    const generated = read('.ghkgovernance.yaml');
    expect(generated).toMatch(/^# Generated by gherkin-ai/);

    // Unedited: regenerated in place, no side file.
    generateGovernanceConfig({ ...config, projectName: 'billing-2' }, dir);
    expect(read('.ghkgovernance.yaml')).toContain('projectName: billing-2');
    expect(fs.existsSync(path.join(dir, '.ghkgovernance.yaml.ghk-new'))).toBe(false);

    // Edited: kept; the new version is a .ghk-new.
    fs.writeFileSync(path.join(dir, '.ghkgovernance.yaml'), read('.ghkgovernance.yaml').replace('maxFilesPerTask: 12', 'maxFilesPerTask: 3'));
    generateGovernanceConfig({ ...config, projectName: 'billing-3' }, dir);
    expect(read('.ghkgovernance.yaml')).toContain('maxFilesPerTask: 3');
    expect(read('.ghkgovernance.yaml.ghk-new')).toContain('projectName: billing-3');

    // A policy from before the checksum header is treated as edited too.
    fs.writeFileSync(path.join(dir, '.ghkgovernance.yaml'), 'version: "1.0"\nmaxFilesPerTask: 5\n');
    generateGovernanceConfig(config, dir);
    expect(read('.ghkgovernance.yaml')).toContain('maxFilesPerTask: 5');
  });

  it('add protects edited files, writes pending tests and records entries upgrade never prunes', async () => {
    fs.mkdirSync(path.join(dir, 'features'));
    fs.writeFileSync(path.join(dir, 'features', 'invoicing.feature'), FEATURE);
    fs.writeFileSync(path.join(dir, 'gherkin-ai.config.json'), JSON.stringify({ projectName: 'billing', outputDir: './generated-specs', stack: { language: 'typescript', framework: 'express' } }));
    const add = () => handleAddCommand({ feature: 'features/invoicing.feature', target: 'src/invoicing', yes: true });

    await add();
    const stub = read('src/invoicing/__tests__/invoicing.stub.spec.ts');
    expect(stub).toContain('it.todo("Given a customer with an open order")');
    expect(stub).not.toMatch(/TODO:|async \(\) =>/);

    fs.writeFileSync(path.join(dir, 'src/invoicing/invoicing.openapi.json'), '{"edited": true}');
    await add();
    expect(read('src/invoicing/invoicing.openapi.json')).toBe('{"edited": true}');
    expect(fs.existsSync(path.join(dir, 'src/invoicing/invoicing.openapi.json.ghk-new'))).toBe(true);

    const entries = readInventoryFile(path.join(dir, '.ghe', 'inventory.json')).artifacts;
    expect(entries.find(e => e.filePath === '../src/invoicing/invoicing.openapi.json')).toMatchObject({ type: 'add' });
    const stale = findStaleFiles({ outputDir: path.join(dir, 'generated-specs'), generated: new Set(), previousInventory: entries, headerFiles: [], prune: true });
    expect(stale.removable).toEqual([]);
  });

  it('add needs --target outside NestJS and writes no TypeScript files for other stacks', async () => {
    fs.mkdirSync(path.join(dir, 'features'));
    fs.writeFileSync(path.join(dir, 'features', 'invoicing.feature'), FEATURE);
    fs.writeFileSync(path.join(dir, 'gherkin-ai.config.json'), JSON.stringify({ projectName: 'billing', stack: { language: 'java', framework: 'quarkus' } }));
    expect(loadConfig().stack.language).toBe('java');

    await expect(handleAddCommand({ feature: 'features/invoicing.feature', yes: true })).rejects.toMatchObject({ exitCode: 2 });
    await handleAddCommand({ feature: 'features/invoicing.feature', target: 'src/main/invoicing', yes: true });
    const written = fs.readdirSync(path.join(dir, 'src/main/invoicing'), { recursive: true }).map(String);
    expect(written).toContain('invoicing.openapi.json');
    expect(written.some(f => f.endsWith('.ts'))).toBe(false);
  });
});
