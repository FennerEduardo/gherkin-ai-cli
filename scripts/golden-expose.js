#!/usr/bin/env node
/* ==========================================================================
   Golden expose-nestjs (PLAN-3.3.0-reverse-plus EX-13, G-E1): the
   conformance of `ghk expose`, independent of any cloud provider.

   A NestJS service generated by ghk, its approved capabilities, the
   generated MCP runtime, a test OIDC issuer and PostgreSQL + RabbitMQ run in
   Docker. A plain JSON-RPC client (no SDK: what any agent sends) checks the
   8 security properties of the design (GPT §9), each against the service's
   database or the runtime's audit log, not only against the answer:

   1. an authorized tool is discovered and runs;
   2. an unauthorized one does not run, even when called directly;
   3. tenants are isolated;
   4. no secret in responses or logs;
   5. a critical operation needs its approval;
   6. an incompatible contract change is flagged;
   7. a retry (a new connection) does not run the operation twice;
   8. every call is traced to its scenario (traceparent + audit).

   Usage: npm run build && node scripts/golden-expose.js [--keep] [--evidence <file.json>]
   ========================================================================== */

'use strict';

const { spawnSync } = require('child_process');
const crypto = require('crypto');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { STACKS } = require('./golden-stacks');
const { startServices, POSTGRES_IMAGE } = require('../dist/core/services');
const { resolveAppRuntimeEnv, resolveHealth } = require('../dist/generators/toolchains');

const ROOT = path.resolve(__dirname, '..');
const CLI = process.env.GHK_CLI ? path.resolve(process.env.GHK_CLI) : path.join(ROOT, 'bin', 'gherkin-ai.js');
const args = process.argv.slice(2);
const keep = args.includes('--keep');
const evidenceIndex = args.indexOf('--evidence');
const evidenceFile = evidenceIndex >= 0 ? path.resolve(args[evidenceIndex + 1]) : undefined;

const JWT_SECRET = 'golden-expose-secret-with-32-chars!!';
const AUDIENCE = 'golden-expose-mcp';
const ISSUER = 'http://issuer:8080';
const stamp = Date.now().toString(36);
const names = { app: `ghk-expose-app-${stamp}`, issuer: `ghk-expose-issuer-${stamp}`, mcp: `ghk-expose-mcp-${stamp}` };
const images = { app: `ghk-expose-app:${stamp}`, mcp: `ghk-expose-mcp:${stamp}` };

function run(cmd, cmdArgs, opts = {}) {
  const res = spawnSync(cmd, cmdArgs, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, ...opts, env: { ...process.env, MSYS_NO_PATHCONV: '1', ...(opts.env || {}) } });
  return { code: res.status ?? 1, out: `${res.stdout || ''}${res.stderr || ''}` };
}
const sleep = ms => new Promise(r => setTimeout(r, ms));
function ghk(dir, ...cmd) {
  return run(process.execPath, [CLI, ...cmd], { cwd: dir, env: { NO_COLOR: '1', GHK_NON_INTERACTIVE: 'true', GHK_TELEMETRY_DISABLED: 'true' } });
}
function must(res, what) {
  if (res.code !== 0) throw new Error(`${what} failed (exit ${res.code}):\n${res.out.slice(-4000)}`);
  return res.out;
}

// ---------------------------------------------------------------------------
// The project: a generated NestJS service and its approved capabilities
// ---------------------------------------------------------------------------

function project() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ghk-golden-expose-'));
  fs.chmodSync(dir, 0o755);
  fs.mkdirSync(path.join(dir, 'features'));
  fs.copyFileSync(path.join(__dirname, 'golden-feature-expose.feature'), path.join(dir, 'features', 'order.feature'));
  fs.writeFileSync(path.join(dir, 'gherkin-ai.config.json'), JSON.stringify({ projectName: 'golden-expose', architecture: 'hexagonal', stack: STACKS.nestjs.stack, rules: {}, outputDir: './' }, null, 2));
  must(ghk(dir, 'generate', '-f', 'features/order.feature', '--yes'), 'ghk generate');
  must(ghk(dir, 'expose', 'discover'), 'ghk expose discover');
  must(ghk(dir, 'expose', 'approve', '--all', '--env', 'dev', '--by', 'golden', '--yes'), 'ghk expose approve');
  must(ghk(dir, 'expose', 'validate'), 'ghk expose validate');
  must(ghk(dir, 'expose', 'generate', '--target', 'mcp-runtime'), 'ghk expose generate');
  return dir;
}

// ---------------------------------------------------------------------------
// Test identity provider: discovery + JWKS over http on the private network
// ---------------------------------------------------------------------------

const keys = crypto.generateKeyPairSync('rsa', { modulusLength: 2048 });
const JWKS = JSON.stringify({ keys: [{ ...keys.publicKey.export({ format: 'jwk' }), kid: 'golden', use: 'sig', alg: 'RS256' }] });
const ISSUER_SERVER = `require('http').createServer((q,s)=>{s.setHeader('content-type','application/json');if(q.url==='/.well-known/openid-configuration')s.end(JSON.stringify({issuer:'${ISSUER}',jwks_uri:'${ISSUER}/jwks'}));else if(q.url==='/jwks')s.end(process.env.JWKS);else{s.statusCode=404;s.end('{}')}}).listen(8080)`;

function token(claims = {}) {
  const now = Math.floor(Date.now() / 1000);
  const head = Buffer.from(JSON.stringify({ alg: 'RS256', kid: 'golden', typ: 'JWT' })).toString('base64url');
  const body = Buffer.from(JSON.stringify({ iss: ISSUER, aud: AUDIENCE, sub: 'agent-user', tenant_id: 'tenant-a', iat: now, exp: now + 600, ...claims })).toString('base64url');
  return `${head}.${body}.${crypto.sign('sha256', Buffer.from(`${head}.${body}`), keys.privateKey).toString('base64url')}`;
}

// ---------------------------------------------------------------------------
// A plain MCP client: Streamable HTTP, JSON responses
// ---------------------------------------------------------------------------

let mcpUrl = '';
const transcript = [];

// MCP 2026-07-28: no session; the version, client info and capabilities travel in each request's _meta, and
// MCP-Protocol-Version, Mcp-Method and Mcp-Name mirror the body. 2025-era clients still use initialize.
const MODERN = '2026-07-28';
const LEGACY = '2025-11-25';
const ENVELOPE = { 'io.modelcontextprotocol/protocolVersion': MODERN, 'io.modelcontextprotocol/clientInfo': { name: 'golden-agent', version: '1.0.0' }, 'io.modelcontextprotocol/clientCapabilities': {} };

/** One JSON-RPC message from a JSON or an event-stream answer (2025-era stateless answers are SSE). */
function parseAnswer(text, contentType) {
  if (!text) return undefined;
  if (!contentType.includes('text/event-stream')) return JSON.parse(text);
  const data = text.split('\n').filter(l => l.startsWith('data:')).map(l => l.slice(5).trim()).filter(Boolean);
  return data.length ? JSON.parse(data[data.length - 1]) : undefined;
}

async function post(bearer, message, headers = {}, era = LEGACY) {
  const modern = era === MODERN && message.id !== undefined;
  const body = modern ? { ...message, params: { ...(message.params ?? {}), _meta: ENVELOPE } } : message;
  const standard = modern
    ? { 'mcp-protocol-version': MODERN, 'mcp-method': message.method, ...(message.params?.name ? { 'mcp-name': message.params.name } : {}) }
    : { 'mcp-protocol-version': LEGACY };
  const res = await fetch(mcpUrl, {
    method: 'POST',
    headers: { 'content-type': 'application/json', accept: 'application/json, text/event-stream', ...standard, ...(bearer ? { authorization: `Bearer ${bearer}` } : {}), ...headers },
    body: JSON.stringify(body)
  });
  const text = await res.text();
  transcript.push(text);
  return { status: res.status, headers: res.headers, body: parseAnswer(text, res.headers.get('content-type') ?? '') };
}

/**
 * A new connection, as an agent that reconnects makes one. MCP 2026-07-28 by default: server/discover, then
 * stateless calls, each with the Mcp-Session-Id that AgentCore Runtime adds (the runtime must accept and ignore it).
 * `era: LEGACY` is a 2025 client: initialize + initialized.
 */
async function connect(bearer, { era = MODERN, platformSession = `agentcore-${crypto.randomBytes(6).toString('hex')}` } = {}) {
  const session = platformSession ? { 'mcp-session-id': platformSession } : {};
  if (era === MODERN) {
    const discover = await post(bearer, { jsonrpc: '2.0', id: 1, method: 'server/discover' }, session, MODERN);
    if (discover.status !== 200 || !discover.body?.result) throw new Error(`server/discover: ${discover.status} ${JSON.stringify(discover.body)}`);
  } else {
    const init = await post(bearer, { jsonrpc: '2.0', id: 1, method: 'initialize', params: { protocolVersion: LEGACY, capabilities: {}, clientInfo: { name: 'golden-agent', version: '1.0.0' } } }, session);
    if (init.status !== 200 || !init.body?.result) throw new Error(`initialize: ${init.status} ${JSON.stringify(init.body)}`);
    await post(bearer, { jsonrpc: '2.0', method: 'notifications/initialized' }, session);
  }
  let id = 2;
  return {
    era,
    list: async () => (await post(bearer, { jsonrpc: '2.0', id: id++, method: 'tools/list' }, session, era)).body.result.tools.map(t => t.name).sort(),
    listRaw: async () => (await post(bearer, { jsonrpc: '2.0', id: id++, method: 'tools/list' }, session, era)).body.result,
    call: async (name, args, headers) => (await post(bearer, { jsonrpc: '2.0', id: id++, method: 'tools/call', params: { name, arguments: args } }, { ...session, ...headers }, era)).body.result
  };
}
const data = result => JSON.parse(result.content[0].text.split('\n')[1] ?? '{}');

// ---------------------------------------------------------------------------

async function main() {
  const results = [];
  const protocol = [];
  const check = (n, title, ok, detail) => {
    results.push({ test: n, title, pass: Boolean(ok), detail });
    process.stdout.write(`  ${ok ? '✔' : '✖'} ${n}. ${title}${detail ? ` — ${detail}` : ''}\n`);
  };
  process.stdout.write('▶ expose-nestjs: generating the service, approving its capabilities, generating the MCP runtime…\n');
  const dir = project();
  const manifest = fs.readFileSync(path.join(dir, '.ghk/capabilities.yaml'), 'utf8');
  process.stdout.write(`  project ${dir}\n`);
  const services = startServices('expose', []);
  const net = ['--network', services.network];
  const psql = sql => run('docker', ['run', '--rm', ...net, POSTGRES_IMAGE, 'psql', services.env.DATABASE_URL.replace(/\/postgres(\?|$)/, '/ghk_expose$1'), '-t', '-A', '-c', sql]).out.trim();
  try {
    // The service
    must(run('docker', ['build', '-q', '-t', images.app, dir]), 'docker build (service)');
    must(run('docker', ['run', '--rm', ...net, POSTGRES_IMAGE, 'psql', services.env.DATABASE_URL, '-c', 'CREATE DATABASE ghk_expose']), 'create database');
    const { port } = resolveAppRuntimeEnv({ stack: STACKS.nestjs.stack });
    const health = resolveHealth({ stack: STACKS.nestjs.stack });
    must(run('docker', ['run', '-d', '--name', names.app, ...net, '--network-alias', 'app',
      '-e', `JWT_SECRET=${JWT_SECRET}`, '-e', `DATABASE_URL=${services.env.DATABASE_URL.replace(/\/postgres(\?|$)/, '/ghk_expose$1')}`, '-e', `AMQP_URL=${services.env.AMQP_URL}`, images.app]), 'docker run (service)');
    // The identity provider and the runtime
    must(run('docker', ['run', '-d', '--name', names.issuer, ...net, '--network-alias', 'issuer', '-e', `JWKS=${JWKS}`, 'node:24-alpine', 'node', '-e', ISSUER_SERVER]), 'docker run (issuer)');
    must(run('docker', ['build', '-q', '-t', images.mcp, path.join(dir, 'expose/mcp-runtime')]), 'docker build (MCP runtime)');
    must(run('docker', ['run', '-d', '--name', names.mcp, ...net, '-p', '127.0.0.1::8000',
      '-e', 'GHK_ENVIRONMENT=dev', '-e', `GHK_UPSTREAM_URL=http://app:${port}`, '-e', 'GHK_UPSTREAM_ALLOW_HTTP=true', '-e', `GHK_UPSTREAM_JWT_SECRET=${JWT_SECRET}`,
      '-e', `GHK_OIDC_ISSUER=${ISSUER}`, '-e', 'GHK_OIDC_ALLOW_INSECURE=true', '-e', `GHK_OIDC_AUDIENCE=${AUDIENCE}`, images.mcp]), 'docker run (MCP runtime)');
    const published = run('docker', ['port', names.mcp, '8000']).out.trim().split('\n')[0];
    mcpUrl = `http://${published.replace('0.0.0.0', '127.0.0.1')}/mcp`;
    const curl = url => run('docker', ['run', '--rm', ...net, 'curlimages/curl:8.11.1', '-s', '-o', '/dev/null', '-w', '%{http_code}', '--max-time', '5', url]).out.trim();
    const deadline = Date.now() + 240_000;
    let ready = false;
    while (Date.now() < deadline && !ready) {
      ready = curl(`http://${names.app}:${port}${health.ready}`) === '200' && (await fetch(mcpUrl.replace('/mcp', '/health')).then(r => r.ok, () => false));
      if (!ready) await sleep(3000);
    }
    if (!ready) throw new Error(`not healthy:\n--- service ---\n${run('docker', ['logs', '--tail', '60', names.app]).out}\n--- runtime ---\n${run('docker', ['logs', '--tail', '60', names.mcp]).out}`);
    process.stdout.write(`  service, issuer and runtime up (${mcpUrl})\n`);
    const schema = psql("SELECT table_schema FROM information_schema.tables WHERE table_name = 'ghk_outbox' LIMIT 1") || 'public';
    const outbox = where => Number(psql(`SELECT count(*) FROM ${schema}.ghk_outbox WHERE ${where}`));

    // 1. An authorized tool is discovered and runs
    const writer = await connect(token({ scope: 'order:read order:write' }));
    const tools = await writer.list();
    const placed = await writer.call('place_order', { id: 'order-1', idempotency_key: 'golden-0001' });
    check(1, 'an authorized tool is discovered and runs', tools.includes('place_order') && !placed.isError && data(placed).data?.status === 'created' && outbox("aggregate_id = 'order-1'") === 1,
      `tools ${tools.join(', ')}; place_order → ${data(placed).status} ${data(placed).data?.status}; outbox rows ${outbox("aggregate_id = 'order-1'")}`);

    // 2. An unauthorized tool does not run, even when called directly (the runtime authorizes again)
    const reader = await connect(token({ scope: 'order:read', sub: 'reader' }));
    const readerTools = await reader.list();
    const denied = await reader.call('place_order', { id: 'order-2', idempotency_key: 'golden-0002' });
    const anonymous = await post(undefined, { jsonrpc: '2.0', id: 9, method: 'tools/call', params: { name: 'place_order', arguments: { id: 'order-2', idempotency_key: 'golden-0002' } } });
    check(2, 'an unauthorized tool does not run, even called directly', !readerTools.includes('place_order') && denied.isError && anonymous.status === 401 && outbox("aggregate_id = 'order-2'") === 0,
      `listed for the reader: ${readerTools.join(', ') || 'none'}; call → "${denied.content[0].text}"; without a token → ${anonymous.status}; outbox rows 0`);

    // 3. Tenants are isolated: the tenant comes from the identity; the same id and key in another tenant is another order
    const other = await connect(token({ scope: 'order:write', sub: 'agent-user', tenant_id: 'tenant-b' }));
    const b = await other.call('place_order', { id: 'order-1', idempotency_key: 'golden-0001' });
    const smuggled = await other.call('place_order', { id: 'order-1', idempotency_key: 'golden-0003', tenant_id: 'tenant-a' });
    const tenants = psql(`SELECT string_agg(DISTINCT tenant_id, ',' ORDER BY tenant_id) FROM ${schema}.ghk_outbox WHERE aggregate_id = 'order-1'`);
    check(3, 'tenants are isolated', data(b).data?.status === 'created' && smuggled.isError && tenants === 'tenant-a,tenant-b' && outbox("aggregate_id = 'order-1' AND tenant_id = 'tenant-a'") === 1,
      `tenant-b on order-1 → ${data(b).data?.status} (not a replay of tenant-a); tenant_id argument → refused; outbox tenants ${tenants}`);

    // 5. A critical operation needs its approval (refund_order is financial-critical)
    const refund = await writer.call('refund_order', { id: 'order-1', idempotency_key: 'golden-0005' });
    check(5, 'a critical operation needs its approval', refund.isError && /needs a person to approve/.test(refund.content[0].text) && outbox("aggregate_id = 'order-1' AND event_type ILIKE '%refund%'") === 0,
      `refund_order → "${refund.content[0].text.slice(0, 90)}…"; no refund event stored`);

    // 7. A retry on a new connection does not run the operation twice (the retry comes from a 2025-era client:
    //    the idempotency key holds across protocol revisions)
    const again = await (await connect(token({ scope: 'order:read order:write' }), { era: LEGACY })).call('place_order', { id: 'order-1', idempotency_key: 'golden-0001' });
    check(7, 'a reconnection does not run the operation twice', data(again).data?.status === 'replayed' && outbox("aggregate_id = 'order-1' AND tenant_id = 'tenant-a'") === 1,
      `same key after reconnecting (first call ${MODERN}, retry ${LEGACY}) → ${data(again).status} ${data(again).data?.status}; tenant-a outbox rows still 1`);

    // 8. Every call is traced to its scenario
    const traceId = crypto.randomBytes(16).toString('hex');
    await writer.call('place_order', { id: 'order-8', idempotency_key: 'golden-0008' }, { traceparent: `00-${traceId}-${crypto.randomBytes(8).toString('hex')}-01` });
    await sleep(500);
    const auditLines = run('docker', ['logs', names.mcp]).out.split('\n').filter(l => l.startsWith('{')).map(l => JSON.parse(l));
    const line = auditLines.find(l => l.action === 'tool:call' && l.traceId === traceId);
    const stored = psql(`SELECT traceparent FROM ${schema}.ghk_outbox WHERE aggregate_id = 'order-8' LIMIT 1`);
    check(8, 'every call is traced to its scenario', line && line.status === 'SUCCESS' && line.scenarios?.includes('The customer places an order') && stored.includes(traceId),
      `audit: ${line ? `${line.resource} ${line.status}, scenarios [${line.scenarios.join('; ')}]` : 'missing'}; outbox traceparent ${stored.includes(traceId) ? 'carries the same trace id' : `= ${stored || 'null'}`}`);

    // 6. An incompatible contract change is flagged (the contract loses the command; the manifest changes an input without a new version)
    fs.writeFileSync(path.join(dir, 'previous.yaml'), manifest);
    const openapi = JSON.parse(fs.readFileSync(path.join(dir, 'openapi.json'), 'utf8'));
    const op = Object.values(openapi.paths).map(p => p.post).find(Boolean);
    op.parameters.find(p => p.name === 'command').schema.enum = ['refund_order'];
    fs.writeFileSync(path.join(dir, 'openapi.json'), JSON.stringify(openapi, null, 2));
    const contract = ghk(dir, 'expose', 'validate', '--against', 'previous.yaml', '--json');
    fs.writeFileSync(path.join(dir, '.ghk/capabilities.yaml'), manifest.replace(/(\n {4}name: place_order\n[\s\S]*?\n {6}required:\n)/, '$1        - note\n'));
    const breaking = ghk(dir, 'expose', 'validate', '--against', 'previous.yaml', '--json');
    const codes = r => { try { return JSON.parse(r.out).issues.map(i => i.code); } catch { return []; } };
    check(6, 'an incompatible contract change is flagged', contract.code === 4 && codes(contract).includes('EXV041') && breaking.code !== 0 && codes(breaking).some(c => c === 'EXV050' || c === 'EXV011'),
      `contract without place_order → exit ${contract.code} [${codes(contract).join(', ')}]; manifest input changed → exit ${breaking.code} [${[...new Set(codes(breaking))].join(', ')}]`);

    // 4. No secret in responses or logs
    const logs = run('docker', ['logs', names.mcp]).out + run('docker', ['logs', names.app]).out;
    const everything = transcript.join('\n') + logs;
    const leaks = [JWT_SECRET, 'eyJ', 'Bearer ', keys.privateKey.export({ format: 'jwk' }).d].filter(s => everything.includes(s));
    check(4, 'no secret in responses or logs', leaks.length === 0, leaks.length ? `found: ${leaks.map(s => s.slice(0, 6)).join(', ')}` : `${transcript.length} responses and ${logs.split('\n').length} log lines checked: no secret, token or key`);

    // MCP protocol conformance (not one of the 8 security properties; reported next to them)
    const bearer = token({ scope: 'order:read' });
    const callBody = { jsonrpc: '2.0', id: 50, method: 'tools/call', params: { name: 'get_order', arguments: { id: 'order-1' }, _meta: ENVELOPE } };
    const raw = async headers => {
      const res = await fetch(mcpUrl, { method: 'POST', headers: { authorization: `Bearer ${bearer}`, 'content-type': 'application/json', accept: 'application/json, text/event-stream', ...headers }, body: JSON.stringify(callBody) });
      return { status: res.status, body: parseAnswer(await res.text(), res.headers.get('content-type') ?? ''), session: res.headers.get('mcp-session-id') };
    };
    const noHeaders = await raw({ 'mcp-protocol-version': MODERN });
    const wrongName = await raw({ 'mcp-protocol-version': MODERN, 'mcp-method': 'tools/call', 'mcp-name': 'place_order' });
    const withSession = await raw({ 'mcp-protocol-version': MODERN, 'mcp-method': 'tools/call', 'mcp-name': 'get_order', 'mcp-session-id': 'agentcore-session-1' });
    const modernList = await (await connect(bearer)).listRaw();
    const legacyTools = await (await connect(token({ scope: 'order:read order:write' }), { era: LEGACY })).list();
    const eras = new Set(run('docker', ['logs', names.mcp]).out.split('\n').filter(l => l.startsWith('{')).map(l => JSON.parse(l)).filter(l => l.action === 'tool:call').map(l => l.protocol));
    protocol.push(
      { check: 'Mcp-Method missing → 400 / -32020', pass: noHeaders.status === 400 && noHeaders.body?.error?.code === -32020 },
      { check: 'Mcp-Name disagrees with the body → 400 / -32020', pass: wrongName.status === 400 && wrongName.body?.error?.code === -32020 },
      { check: 'AgentCore Mcp-Session-Id accepted, ignored, not echoed', pass: withSession.status === 200 && withSession.body?.result?.resultType === 'complete' && !withSession.session },
      { check: '2026-07-28 tools/list carries ttlMs 0 and cacheScope private', pass: modernList.ttlMs === 0 && modernList.cacheScope === 'private' },
      { check: '2025-11-25 client (initialize) served on the same endpoint', pass: legacyTools.includes('place_order') },
      { check: 'audit records the protocol of each call (modern and legacy)', pass: eras.has('modern') && eras.has('legacy') }
    );
    for (const p of protocol) process.stdout.write(`  ${p.pass ? '✔' : '✖'} protocol: ${p.check}\n`);
  } finally {
    if (!keep) {
      run('docker', ['rm', '-f', names.app, names.issuer, names.mcp]);
      run('docker', ['rmi', '-f', images.app, images.mcp]);
      services.stop();
      try { fs.rmSync(dir, { recursive: true, force: true }); } catch { /* files written as root */ }
    }
  }
  results.sort((a, b) => a.test - b.test);
  const passed = results.filter(r => r.pass).length;
  const protocolPassed = protocol.filter(p => p.pass).length;
  process.stdout.write(`\n  expose-nestjs: ${passed}/8; MCP protocol ${protocolPassed}/${protocol.length} (${MODERN} and ${LEGACY})\n`);
  if (evidenceFile) fs.writeFileSync(evidenceFile, `${JSON.stringify({ golden: 'expose-nestjs', date: new Date().toISOString().slice(0, 10), stack: 'typescript/nestjs + PostgreSQL + RabbitMQ', mcp: { revisions: [MODERN, LEGACY], server: '@modelcontextprotocol/server' }, passed, total: 8, results, protocol }, null, 2)}\n`);
  process.exit(passed === 8 && protocol.length > 0 && protocolPassed === protocol.length ? 0 : 1);
}

main().catch(err => {
  process.stdout.write(`  ✖ ${err.message}\n`);
  process.exit(1);
});
