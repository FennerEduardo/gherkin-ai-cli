#!/usr/bin/env node
/* ==========================================================================
   Round-trip score of `ghk reverse` on projects generated by gherkin-ai
   (PLAN-3.3.0 §4): for each project, the model the generator built from
   features/*.feature against the model `reverse` recovers from the code.
   Read-only: the projects are analysed in place without writing anything.

   Usage: npm run build && node scripts/reverse-roundtrip.js [--json out.json] <project-dir...>
   ========================================================================== */

const fs = require('fs');
const path = require('path');

async function main() {
  const args = process.argv.slice(2);
  let jsonOut;
  const dirs = [];
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--json') jsonOut = args[++i];
    else if (args[i].startsWith('-')) { console.error(`Unknown option: ${args[i]}`); process.exit(2); }
    else dirs.push(path.resolve(args[i]));
  }
  if (!dirs.length) { console.error('Usage: node scripts/reverse-roundtrip.js [--json out.json] <project-dir...>'); process.exit(2); }

  const dist = path.join(__dirname, '..', 'dist');
  const { runScan, runPropose } = require(path.join(dist, 'core', 'reverse'));
  const { expectedModel, foundModel, scoreRoundTrip } = require(path.join(dist, 'core', 'reverse', 'roundtrip'));
  const { clearTsProjects } = require(path.join(dist, 'core', 'reverse', 'analyzers', 'typescript', 'project'));

  const rows = [];
  for (const dir of dirs) {
    const featuresDir = path.join(dir, 'features');
    const features = fs.existsSync(featuresDir) ? fs.readdirSync(featuresDir).filter(f => f.endsWith('.feature')).map(f => path.join(featuresDir, f)) : [];
    if (!features.length) { rows.push({ project: path.basename(dir), error: 'no features/*.feature' }); continue; }
    let config = {};
    try { config = JSON.parse(fs.readFileSync(path.join(dir, 'gherkin-ai.config.json'), 'utf8')); } catch { /* none */ }
    clearTsProjects();
    const scan = await runScan(dir, { write: false });
    const result = runPropose(dir, scan, { write: false });
    const score = scoreRoundTrip(expectedModel(features), foundModel(result.candidates));
    rows.push({
      project: path.basename(dir),
      stack: `${config.stack?.language ?? '?'}/${config.stack?.framework ?? '?'}`,
      analyzers: scan.analyzers.map(a => a.id),
      f1: score.f1,
      aggregates: score.aggregates, commands: score.commands, events: score.events,
      proposals: result.proposals.map(p => ({ file: p.file, scenarios: p.scenarios, lint: p.lint.score, roundTrip: p.roundTrip.ok }))
    });
  }

  const pad = (s, n) => String(s).padEnd(n);
  console.log(`${pad('project', 36)}${pad('stack', 24)}${pad('F1', 7)}${pad('agg', 8)}${pad('cmd', 8)}${pad('evt', 8)}lint`);
  for (const r of rows) {
    if (r.error) { console.log(`${pad(r.project, 36)}${r.error}`); continue; }
    const frac = s => `${s.matched}/${s.expected}`;
    console.log(`${pad(r.project, 36)}${pad(r.stack, 24)}${pad(r.f1.toFixed(2), 7)}${pad(frac(r.aggregates), 8)}${pad(frac(r.commands), 8)}${pad(frac(r.events), 8)}${r.proposals.map(p => p.lint).join(',') || '-'}`);
  }
  const scored = rows.filter(r => !r.error);
  const mean = scored.length ? scored.reduce((s, r) => s + r.f1, 0) / scored.length : 0;
  console.log(`\nmean F1 ${mean.toFixed(3)} over ${scored.length} project(s)`);
  if (jsonOut) fs.writeFileSync(jsonOut, `${JSON.stringify({ meanF1: Math.round(mean * 1000) / 1000, projects: rows }, null, 2)}\n`);
}

main().catch(err => { console.error(err); process.exit(1); });
