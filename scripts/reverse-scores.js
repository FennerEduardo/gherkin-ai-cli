#!/usr/bin/env node
/* ==========================================================================
   Snapshot of the `ghk reverse` measurements shown on the golden-build
   dashboard (scripts/build-site.js), written to docs/reverse-scores.json at
   each release:
     --roundtrip  scripts/reverse-roundtrip.js --json on the reference projects
                  (code generated by gherkin-ai: kernel read back, by stack)
     --oss        scripts/reverse-oss.js --json (code gherkin-ai did not write)
     --lms        scripts/reverse-roundtrip.js --json on the LMS (optional)
   The Pages workflow reruns the OSS validation on every build; the round
   trips need repositories CI does not have, so they come from here.

   Usage: node scripts/reverse-scores.js --roundtrip ref.json --oss oss.json [--lms lms.json] [--out docs/reverse-scores.json]
   ========================================================================== */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const args = process.argv.slice(2);
const opt = name => { const i = args.indexOf(`--${name}`); return i >= 0 ? args[i + 1] : undefined; };
const read = file => JSON.parse(fs.readFileSync(path.resolve(file), 'utf8'));

if (!opt('roundtrip') || !opt('oss')) {
  console.error('Usage: node scripts/reverse-scores.js --roundtrip ref.json --oss oss.json [--lms lms.json] [--out docs/reverse-scores.json]');
  process.exit(2);
}
const round = read(opt('roundtrip'));
const byStack = new Map();
for (const p of round.projects.filter(x => typeof x.f1 === 'number')) {
  const row = byStack.get(p.stack) ?? { stack: p.stack, projects: 0, f1: [] };
  row.projects++;
  row.f1.push(p.f1);
  byStack.set(p.stack, row);
}
const lms = opt('lms') ? read(opt('lms')) : undefined;
const snapshot = {
  version: require(path.join(ROOT, 'package.json')).version,
  measured: new Date().toISOString().slice(0, 10),
  roundTrip: {
    description: 'Reference projects generated by gherkin-ai: the model reverse reads back from the code against the model the generator built from the features (aggregates, commands, events).',
    meanF1: round.meanF1,
    stacks: [...byStack.values()].sort((a, b) => a.stack.localeCompare(b.stack))
      .map(r => ({ stack: r.stack, projects: r.projects, f1: Number((r.f1.reduce((s, x) => s + x, 0) / r.f1.length).toFixed(2)) }))
  },
  oss: read(opt('oss')),
  ...(lms ? { lms: {
    description: 'LMS (Spring services written by hand over the kernel), against its own features: a low F1 mostly measures how far the code drifted from the features.',
    meanF1: lms.meanF1,
    services: lms.projects.filter(x => typeof x.f1 === 'number').map(p => ({ service: p.project, f1: p.f1 }))
  } } : {})
};
const out = path.resolve(opt('out') ?? path.join(ROOT, 'docs', 'reverse-scores.json'));
fs.writeFileSync(out, JSON.stringify(snapshot, null, 2) + '\n');
console.log(`${path.relative(ROOT, out)}: ${snapshot.roundTrip.stacks.length} stacks round trip, ${snapshot.oss.results.length} OSS analyzers${lms ? ', LMS' : ''}`);
