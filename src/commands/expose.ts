/* ==========================================================================
   gherkin-ai-cli - 'expose' command: the service's business capabilities as
   MCP tools for agents (PLAN-3.3.0-reverse-plus §3.F)

   ghk expose discover [--contract f] [--from-reverse] [--json]
       proposes the capability manifest in .ghe/expose/ (never approves)
   ghk expose review [id…] [--json]
       each proposed capability, what it does, what it needs, what changed
   ghk expose approve <id…> | --all [--env e]… [--by name] [--note t] [--yes]
       writes the approved capabilities to .ghk/capabilities.yaml (exit 5
       when a policy refuses one; nothing is written then)
   ghk expose revoke <id…> [--yes]
   ghk expose validate [--manifest f] [--against f] [--contract f] [--json]
       exit 5: a write without approval; exit 4: tool poisoning, a
       contract mismatch or an incompatible change without a new version
   ghk expose generate [--target mcp-runtime] [--out expose]
       validates, then writes the MCP runtime of the approved capabilities

   `ghk mcp` stays the development MCP server (features, lint, reverse);
   `ghk expose` builds the one that serves the business to agents.
   ========================================================================== */

import fs from 'fs';
import os from 'os';
import path from 'path';
import { execFileSync } from 'child_process';
import { ExitCode, GhkError, PolicyError, UsageError } from '../core/errors';
import { emitJson } from '../utils/output';
import { logger } from '../utils/logger';
import { parseManifest } from '../core/expose/manifest';

export interface ExposeCommandOptions {
  contract?: string;
  fromReverse?: boolean;
  json?: boolean;
  dryRun?: boolean;
  all?: boolean;
  env?: string[];
  by?: string;
  note?: string;
  yes?: boolean;
  manifest?: string;
  against?: string;
  /** generate, plan, publish */
  image?: string;
  discoveryUrl?: string;
  audience?: string[];
  region?: string;
  /** drift */
  url?: string;
  tokenEnv?: string;
  target?: string;
  out?: string;
}

const SUBCOMMANDS = ['discover', 'review', 'approve', 'revoke', 'validate', 'generate', 'plan', 'publish', 'drift'];

/** Writes generated files under `dir`, replacing a previous generation (marked by .ghk-generated) and nothing else. */
export function writeGenerated(dir: string, files: { path: string; content: string }[]): string[] {
  const marker = path.join(dir, '.ghk-generated');
  if (fs.existsSync(dir) && fs.readdirSync(dir).length && !fs.existsSync(marker)) {
    throw new UsageError(`${dir} exists and was not generated by ghk expose: nothing was written.`, { hint: 'Choose another --out, or move that directory.' });
  }
  if (fs.existsSync(marker)) fs.rmSync(dir, { recursive: true, force: true });
  const written: string[] = [];
  for (const f of files) {
    const target = path.resolve(dir, f.path);
    if (!target.startsWith(path.resolve(dir) + path.sep)) throw new Error(`Refusing to write outside ${dir}: ${f.path}`);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, f.content);
    written.push(f.path);
  }
  fs.writeFileSync(marker, 'Generated by `ghk expose generate`. Do not edit: generate again from .ghk/capabilities.yaml.\n');
  return written;
}

function approver(by?: string): string {
  if (by?.trim()) return by.trim();
  if (process.env.GHK_AUTHOR_NAME) return process.env.GHK_AUTHOR_NAME;
  try {
    const name = execFileSync('git', ['config', 'user.name'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    if (name) return name;
  } catch { /* not a git checkout */ }
  return process.env.USER || process.env.USERNAME || os.userInfo().username || 'unknown';
}

async function confirm(message: string, options: ExposeCommandOptions, what: string): Promise<boolean> {
  if (options.yes) return true;
  if (!process.stdin.isTTY || options.json) throw new UsageError(`${what}. Nothing was written: pass --yes to confirm.`, { hint: 'Run `ghk expose review` first.' });
  const inquirer = (await import('inquirer')).default;
  const { ok } = await inquirer.prompt([{ type: 'confirm', name: 'ok', default: false, message }]);
  return Boolean(ok);
}

/** The manifest of the base revision (`git show HEAD:<file>`), when there is one. */
function previousManifest(root: string, file: string, against?: string) {

  if (against) {
    const p = path.resolve(root, against);
    if (!fs.existsSync(p)) throw new UsageError(`--against: ${against} not found.`);
    return parseManifest(fs.readFileSync(p, 'utf8'), against);
  }
  try {
    const text = execFileSync('git', ['show', `HEAD:${file}`], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
    return parseManifest(text, `HEAD:${file}`);
  } catch {
    return undefined; // first manifest, or not a git checkout
  }
}

export async function handleExposeCommand(subcommand: string | undefined, args: string[], options: ExposeCommandOptions): Promise<void> {
  if (!subcommand || !SUBCOMMANDS.includes(subcommand)) {
    throw new UsageError(subcommand ? `Unknown expose subcommand: ${subcommand}` : 'Missing expose subcommand.', { hint: `Use one of: ${SUBCOMMANDS.join(', ')}.` });
  }
  const root = process.cwd();
  const { discoverCapabilities, readApprovedManifest, writeExposeFile, loadContract } = await import('../core/expose/discover');
  const { EXPOSE_DIR, MANIFEST_FILE, PROPOSAL_FILE, ManifestError, serializeManifest, isWrite, capabilityFingerprint } = await import('../core/expose/manifest');

  const discover = (write: boolean) => {
    try {
      return discoverCapabilities(root, { contract: options.contract, fromReverse: options.fromReverse, write });
    } catch (err) {
      if (/^Contract not found/.test((err as Error).message)) throw new UsageError((err as Error).message, { hint: 'Pass the OpenAPI document of the service with --contract <file>.' });
      throw err;
    }
  };
  const readProposal = () => {
    const file = path.join(root, EXPOSE_DIR, PROPOSAL_FILE);
    if (!fs.existsSync(file)) throw new UsageError('No proposal to review.', { hint: 'Run `ghk expose discover` first.' });
    return parseManifest(fs.readFileSync(file, 'utf8'), `${EXPOSE_DIR}/${PROPOSAL_FILE}`);
  };
  const readApproved = () => {
    try {
      return readApprovedManifest(root);
    } catch (err) {
      if (err instanceof ManifestError) throw new GhkError(`${err.message}:\n  ${err.issues.join('\n  ')}`, ExitCode.GATE_FAILED);
      throw err;
    }
  };

  if (subcommand === 'discover') {
    const result = discover(!options.dryRun);
    if (options.json) {
      emitJson({ ...result, manifest: undefined, capabilities: result.manifest.capabilities.map(c => ({ id: c.id, name: c.name, effect: c.effect, status: c.status, approval: c.execution.approval, handler: c.handler ? `${c.handler.method} ${c.handler.path}` : null, features: c.source.features, reason: c.reason })) });
      return;
    }
    logger.info(`ghk expose discover: ${result.manifest.capabilities.length} capabilities from ${result.features} feature(s)${result.contract ? ` and ${result.contract}` : ''}`);
    for (const c of result.manifest.capabilities) {
      const where = c.handler ? `${c.handler.method} ${c.handler.path}` : 'no handler';
      console.log(`  ${c.status.padEnd(21)} ${c.effect.padEnd(18)} ${c.name}  (${where})${c.execution.approval === 'human' ? '  human approval per call' : ''}`);
      if (c.reason) console.log(`      ${c.reason}`);
    }
    for (const ch of result.changes.filter(x => x.change !== 'unchanged')) console.log(`  ${ch.change} against ${MANIFEST_FILE}: ${ch.id}`);
    for (const w of result.warnings) logger.warn(w);
    if (result.proposal) console.log(`\n  Proposal: ${result.proposal}. Nothing is approved: \`ghk expose review\`, then \`ghk expose approve <id> --env dev\`.`);
    else console.log('\n  --dry-run: nothing written.');
    return;
  }

  if (subcommand === 'review') {
    const proposal = readProposal();
    const approved = readApproved();
    const rows = proposal.capabilities.filter(c => !args.length || args.includes(c.id) || args.includes(c.name)).map(c => {
      const before = approved?.capabilities.find(a => a.id === c.id);
      const change = !approved ? 'new' : !before ? 'new' : before.approval?.fingerprint === capabilityFingerprint(c) ? 'unchanged' : 'changed';
      return {
        id: c.id, name: c.name, status: c.status, effect: c.effect, change, reason: c.reason,
        handler: c.handler ? `${c.handler.method} ${c.handler.path}` : null,
        arguments: Object.keys((c.input.properties as object) ?? {}), required: (c.input.required as string[]) ?? [],
        scopes: c.authorization.scopes, roles: c.authorization.roles, approval: c.execution.approval, idempotency: c.execution.idempotency,
        rateLimitPerMinute: c.execution.rateLimitPerMinute ?? null, pii: c.pii, features: c.source.features, scenarios: c.source.scenarios,
        description: c.description, approvedBy: before?.approval ? `${before.approval.by} (${before.approval.at})` : null
      };
    });
    if (options.json) { emitJson({ capabilities: rows }); return; }
    if (!rows.length) { logger.info('No capability matches.'); return; }
    for (const r of rows) {
      console.log(`\n${r.id}  [${r.status}, ${r.effect}${r.change !== 'unchanged' ? `, ${r.change}` : ''}]`);
      if (r.reason) console.log(`  ${r.reason}`);
      console.log(`  runs        ${r.handler ?? 'nothing (no handler)'}`);
      console.log(`  arguments   ${r.arguments.map(a => (r.required.includes(a) ? `${a}*` : a)).join(', ') || '(none)'}`);
      console.log(`  authorized  scopes ${r.scopes.join(', ') || '-'}; roles ${r.roles.join(', ') || '-'}`);
      console.log(`  per call    ${r.approval === 'human' ? 'a person approves it' : 'no approval'}; idempotency ${r.idempotency}${r.rateLimitPerMinute ? `; ${r.rateLimitPerMinute}/min` : ''}${r.pii ? '; personal data redacted' : ''}`);
      console.log(`  specified   ${r.features.join(', ') || 'by no feature'}${r.scenarios.length ? `: ${r.scenarios.join('; ')}` : ''}`);
      console.log(`  description ${r.description}`);
      if (r.approvedBy) console.log(`  approved    by ${r.approvedBy}`);
    }
    console.log(`\n  Approve with \`ghk expose approve <id> --env <environment>\`; writes need --env, and production writes an explicit policy.`);
    return;
  }

  if (subcommand === 'approve') {
    const { planApproval } = await import('../core/expose/approve');
    const proposal = readProposal();
    const fresh = discover(false).manifest;
    const current = readApproved();
    const plan = planApproval(proposal, fresh, current, {
      ids: args, all: options.all, environments: options.env ?? [], by: approver(options.by), at: new Date().toISOString().slice(0, 10), note: options.note
    });
    if (plan.refused.length) {
      const text = plan.refused.map(r => `  ${r.id}: ${r.reason}`).join('\n');
      if (options.json) emitJson({ approved: [], refused: plan.refused });
      const policy = plan.refused.some(r => r.policy);
      const message = `Nothing was approved:\n${text}`;
      throw policy ? new PolicyError(message) : new UsageError(message);
    }
    if (options.dryRun) {
      if (options.json) emitJson({ approved: plan.approved, dryRun: true });
      else logger.info(`--dry-run: would approve ${plan.approved.join(', ')}.`);
      return;
    }
    const summary = plan.manifest.capabilities.filter(c => plan.approved.includes(c.id)).map(c => `${c.id} (${c.effect}${isWrite(c.effect) ? ` in ${c.approval!.environments.join(', ')}` : ''})`);
    if (!await confirm(`Approve ${summary.length} capability(ies) for agents?\n  ${summary.join('\n  ')}\n`, options, `expose approve would approve ${summary.join(', ')}`)) {
      logger.info('Not approved.');
      return;
    }
    const { AgentFirewall } = await import('../core/governance/agent-firewall');
    const { projectConfig } = await import('../core/plugins/load');
    // A person confirmed: the approval path is granted, a DENY (allow-paths, deny-paths) still stops it.
    AgentFirewall.forWorkspace(root, projectConfig(root) ?? {}).assert({ kind: 'write', target: MANIFEST_FILE, agent: 'cli' }, { approved: true });
    const target = path.join(root, MANIFEST_FILE);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, serializeManifest(plan.manifest, 'Approved capabilities of `ghk expose`. Review changes to this file by PR.\nApprove or revoke with `ghk expose approve` / `ghk expose revoke`; check with `ghk expose validate`.'));
    const { getTelemetry } = await import('../core/telemetry');
    getTelemetry().recordAudit({ action: 'expose:approve', status: 'SUCCESS', resource: plan.approved.join(', '), details: `by ${plan.manifest.capabilities.find(c => plan.approved.includes(c.id))?.approval?.by}; env ${(options.env ?? []).join(',') || '-'}` });
    if (options.json) { emitJson({ approved: plan.approved, refused: [], manifest: MANIFEST_FILE }); return; }
    logger.success(`Approved ${plan.approved.join(', ')} in ${MANIFEST_FILE}. Commit it and have the change reviewed.`);
    return;
  }

  if (subcommand === 'revoke') {
    const { planRevoke } = await import('../core/expose/approve');
    const current = readApproved();
    if (!current) throw new UsageError(`No ${MANIFEST_FILE}: nothing is approved.`);
    if (!args.length) throw new UsageError('Name the capabilities to revoke.');
    const plan = planRevoke(current, args);
    if (plan.unknown.length) throw new UsageError(`Not approved: ${plan.unknown.join(', ')}.`);
    if (options.dryRun) { logger.info(`--dry-run: would revoke ${plan.revoked.join(', ')}.`); return; }
    if (!await confirm(`Revoke ${plan.revoked.join(', ')}?`, options, `expose revoke would revoke ${plan.revoked.join(', ')}`)) return;
    const { AgentFirewall } = await import('../core/governance/agent-firewall');
    const { projectConfig } = await import('../core/plugins/load');
    AgentFirewall.forWorkspace(root, projectConfig(root) ?? {}).assert({ kind: 'write', target: MANIFEST_FILE, agent: 'cli' }, { approved: true });
    fs.writeFileSync(path.join(root, MANIFEST_FILE), serializeManifest(plan.manifest, 'Approved capabilities of `ghk expose`. Review changes to this file by PR.\nApprove or revoke with `ghk expose approve` / `ghk expose revoke`; check with `ghk expose validate`.'));
    const { getTelemetry } = await import('../core/telemetry');
    getTelemetry().recordAudit({ action: 'expose:revoke', status: 'SUCCESS', resource: plan.revoked.join(', ') });
    if (options.json) { emitJson({ revoked: plan.revoked }); return; }
    logger.success(`Revoked ${plan.revoked.join(', ')}. Regenerate the runtime and the gateway so agents lose them.`);
    return;
  }

  /** The approved manifest, refused unless it passes validate (nothing is planned, generated or published from it otherwise). */
  const validApproved = async (what: string) => {
    const { validateManifest, validationExitCode } = await import('../core/expose/validate');
    const manifest = readApproved();
    if (!manifest) throw new UsageError(`No ${MANIFEST_FILE}: nothing is approved.`, { hint: 'Run `ghk expose discover`, review it, then `ghk expose approve <id> --env <environment>`.' });
    const contract = loadContract(root, options.contract ?? manifest.service.contract);
    const issues = validateManifest(manifest, { contract: contract.file ? contract.operations : undefined });
    const exit = validationExitCode(issues);
    if (exit) {
      const text = issues.filter(i => i.severity === 'error').map(i => `  ${i.code} ${i.capability ?? ''} ${i.message}`).join('\n');
      const message = `${MANIFEST_FILE} does not pass \`ghk expose validate\`; nothing was ${what}:\n${text}`;
      throw exit === 5 ? new PolicyError(message) : new GhkError(message, ExitCode.GATE_FAILED);
    }
    return manifest;
  };
  const providerOptions = (manifest: { capabilities: { approval?: { environments: string[] } }[] }) => {
    const environment = options.env?.[0] ?? [...new Set(manifest.capabilities.flatMap(c => c.approval?.environments ?? []))].sort()[0];
    if (!environment) throw new UsageError('Name the environment with --env.');
    return { environment, image: options.image, discoveryUrl: options.discoveryUrl, audiences: options.audience, region: options.region };
  };
  const provider = async (id: string) => {
    const { findProvider, availableProviders } = await import('../core/expose/providers');
    const p = findProvider(root, id);
    if (!p) throw new UsageError(`Unknown --target ${id}.`, { hint: `Use mcp-runtime or a provider: ${availableProviders(root).map(x => x.id).join(', ')}.` });
    return p;
  };

  if (subcommand === 'generate') {
    const target = options.target ?? 'mcp-runtime';
    const gateway = target === 'mcp-runtime' ? undefined : await provider(target);
    const manifest = await validApproved('generated');
    const { generateRuntime } = await import('../core/expose/runtime');
    const outputs: { dir: string; files: { path: string; content: string }[] }[] = [
      // A provider hosts the runtime, so it is generated with it.
      { dir: path.resolve(root, options.out ?? 'expose', 'mcp-runtime'), files: generateRuntime(root, manifest) }
    ];
    if (gateway) {
      const { providerView } = await import('../core/expose/providers');
      outputs.push({ dir: path.resolve(root, options.out ?? 'expose', gateway.id), files: gateway.emit(providerView(manifest), providerOptions(manifest)) });
    }
    if (options.dryRun) {
      if (options.json) emitJson({ target, outputs: outputs.map(o => ({ out: path.relative(root, o.dir), files: o.files.map(f => f.path) })), dryRun: true });
      else for (const o of outputs) logger.info(`--dry-run: would write ${o.files.length} files to ${path.relative(root, o.dir)}/.`);
      return;
    }
    const written = outputs.map(o => ({ out: path.relative(root, o.dir).split(path.sep).join('/'), files: writeGenerated(o.dir, o.files) }));
    const { getTelemetry } = await import('../core/telemetry');
    const tools = manifest.capabilities.filter(c => c.status === 'approved').map(c => c.name);
    getTelemetry().recordAudit({ action: 'expose:generate', status: 'SUCCESS', resource: written.map(w => w.out).join(', '), details: `${target}: ${tools.join(', ')}` });
    if (options.json) { emitJson({ target, outputs: written, out: written[written.length - 1].out, files: written[written.length - 1].files, tools }); return; }
    for (const w of written) logger.success(`${w.out}/: ${w.files.length} files (${tools.length} tool(s): ${tools.join(', ')}).`);
    console.log(`  Runtime image: docker build -t <image> ${written[0].out}  (AgentCore: --platform linux/arm64). Its README lists the variables.`);
    if (gateway) console.log(`  Next: \`ghk expose plan --target ${gateway.id}\` to review, then \`ghk expose publish --target ${gateway.id} --yes\`.`);
    return;
  }

  if (subcommand === 'plan') {
    if (!options.target || options.target === 'mcp-runtime') throw new UsageError('Name the provider with --target.', { hint: 'For example: --target container, or a provider of a plugin (`ghk plugin list`).' });
    const gateway = await provider(options.target);
    const manifest = await validApproved('planned');
    const { providerView, overclaimed, CONTROLS, CONTROL_LABELS } = await import('../core/expose/providers');
    const plan = gateway.plan(providerView(manifest), providerOptions(manifest));
    const over = overclaimed(gateway, plan);
    const capabilities = gateway.capabilities();
    const report = { provider: gateway.id, label: gateway.label, tier: gateway.tier, maturity: gateway.maturity, ...(gateway.plugin ? { plugin: gateway.plugin } : {}), capabilities, plan, tradeOffs: gateway.tradeOffs ?? [], overclaimed: over };
    if (!options.dryRun) writeExposeFile(root, `plan-${gateway.id}.json`, `${JSON.stringify(report, null, 2)}\n`);
    if (over.length) throw new GhkError(`Provider ${gateway.id} claims controls it does not provide (${over.join(', ')}): its plan is not trusted.`, ExitCode.GATE_FAILED);
    if (options.json) { emitJson(report); return; }
    logger.info(`ghk expose plan --target ${gateway.id}: ${gateway.label} (${gateway.tier}, ${gateway.maturity}${gateway.plugin ? `, plugin ${gateway.plugin}` : ''})`);
    console.log('\n  Where each control is enforced:');
    for (const c of CONTROLS) console.log(`    ${capabilities[c].padEnd(12)} ${CONTROL_LABELS[c]}`);
    console.log('\n  Tools:');
    for (const t of plan.tools) console.log(`    ${t.tool.padEnd(28)} ${t.effect.padEnd(18)} scopes ${t.scopes.join(' ') || '-'}${t.approval === 'human' ? '  (a person approves each call: refused by the stateless runtime)' : ''}`);
    console.log('\n  Resources:');
    for (const r of plan.resources) console.log(`    ${r}`);
    if (plan.warnings.length) {
      console.log('\n  What this provider does not guarantee:');
      for (const w of plan.warnings) console.log(`    - ${w}`);
    }
    if (gateway.tradeOffs?.length) {
      console.log('\n  Trade-offs:');
      for (const t of gateway.tradeOffs) console.log(`    - ${t}`);
    }
    return;
  }

  if (subcommand === 'publish') {
    if (!options.target || options.target === 'mcp-runtime') throw new UsageError('Name the provider with --target.');
    const gateway = await provider(options.target);
    await validApproved('published');
    const dir = path.resolve(root, options.out ?? 'expose', gateway.id);
    if (!fs.existsSync(path.join(dir, '.ghk-generated'))) throw new UsageError(`${path.relative(root, dir)}/ was not generated.`, { hint: `Run \`ghk expose generate --target ${gateway.id}\` first, and review it.` });
    if (!gateway.applyCommands?.length) throw new UsageError(`Provider ${gateway.id} has no publish commands: apply ${path.relative(root, dir)}/ with its own tool.`);
    const commands = gateway.applyCommands.map(c => c.join(' '));
    if (!options.yes || options.dryRun) {
      if (options.json) emitJson({ provider: gateway.id, dir: path.relative(root, dir), commands, published: false });
      else {
        logger.info(`ghk expose publish --target ${gateway.id} would run in ${path.relative(root, dir)}/:`);
        for (const c of commands) console.log(`    ${c}`);
        console.log('  Nothing was run: review `ghk expose plan`, then pass --yes.');
      }
      return;
    }
    const { AgentFirewall, BUILTIN_DENY_COMMANDS } = await import('../core/governance/agent-firewall');
    const { projectConfig } = await import('../core/plugins/load');
    const firewall = AgentFirewall.forWorkspace(root, projectConfig(root) ?? {});
    const { getTelemetry } = await import('../core/telemetry');
    for (const command of gateway.applyCommands) {
      const line = command.join(' ');
      const decision = firewall.check({ kind: 'execute', target: line, agent: 'cli' });
      // The built-in deny list keeps agents from deploying; a person running publish --yes is the approval.
      // A command the organization denies in its own policy is refused for everyone.
      const builtin = decision.rule.startsWith('deny-command: ') && BUILTIN_DENY_COMMANDS.map(c => c.trim()).includes(decision.rule.slice('deny-command: '.length));
      if (decision.verdict === 'DENY' && !builtin) throw new PolicyError(`publish refused: ${line} — ${decision.reason}`);
      const { spawnSync } = await import('child_process');
      const r = spawnSync(command[0], command.slice(1), { cwd: dir, stdio: 'inherit' });
      getTelemetry().recordAudit({ action: 'expose:publish', status: r.status === 0 ? 'SUCCESS' : 'FAILED', resource: `${gateway.id}: ${line}`, details: `approved by a person (--yes); firewall ${decision.verdict} (${decision.rule})` });
      if (r.status !== 0) throw new GhkError(`${line} failed (exit ${r.status ?? r.error?.message}).`, ExitCode.GENERIC);
    }
    if (options.json) emitJson({ provider: gateway.id, dir: path.relative(root, dir), commands, published: true });
    else logger.success(`Published ${gateway.id}. Check what agents see with \`ghk expose drift --url <endpoint> --token-env <VAR>\`.`);
    return;
  }

  if (subcommand === 'drift') {
    const { compareTools, generatedRuntimeTools, servedTools } = await import('../core/expose/drift');
    const { providerView } = await import('../core/expose/providers');
    const manifest = readApproved();
    if (!manifest) throw new UsageError(`No ${MANIFEST_FILE}: nothing is approved.`);
    let source: string;
    let served;
    if (options.url) {
      const url = new URL(options.url);
      if (url.protocol !== 'https:' && !['localhost', '127.0.0.1', '[::1]'].includes(url.hostname)) throw new UsageError('--url must be https (or a local runtime).');
      const token = options.tokenEnv ? process.env[options.tokenEnv] : undefined;
      if (options.tokenEnv && !token) throw new UsageError(`${options.tokenEnv} is empty.`, { hint: 'The token comes from an environment variable, never from the command line.' });
      source = url.toString();
      try {
        served = await servedTools(source, token);
      } catch (err) {
        throw new GhkError(`drift: ${(err as Error).message}`, ExitCode.PROVIDER);
      }
    } else {
      const dir = path.resolve(root, options.out ?? 'expose', 'mcp-runtime');
      source = path.relative(root, dir).split(path.sep).join('/');
      try {
        served = generatedRuntimeTools(dir);
      } catch (err) {
        throw new UsageError((err as Error).message);
      }
    }
    const items = compareTools(providerView(manifest), served);
    if (options.json) emitJson({ source, drift: items.length > 0, items });
    else if (!items.length) logger.success(`${source}: the served tools match ${MANIFEST_FILE}.`);
    else {
      logger.warn(`${source}: ${items.length} difference(s) with ${MANIFEST_FILE}:`);
      for (const i of items) console.log(`    ${i.kind.padEnd(12)} ${i.tool}: ${i.detail}`);
      console.log('  Regenerate and publish from the approved manifest, or revoke what should not be served.');
    }
    if (items.length) process.exitCode = ExitCode.DRIFT;
    return;
  }

  if (subcommand === 'validate') {
    const { validateManifest, validationExitCode } = await import('../core/expose/validate');
    const rel = options.manifest ?? MANIFEST_FILE;
    const file = path.resolve(root, rel);
    if (!fs.existsSync(file)) throw new UsageError(`${rel} not found.`, { hint: 'Approve capabilities with `ghk expose approve` first.' });
    let manifest;
    try {
      manifest = parseManifest(fs.readFileSync(file, 'utf8'), rel);
    } catch (err) {
      if (!(err instanceof ManifestError)) throw err;
      if (options.json) emitJson({ valid: false, issues: [{ code: 'EXV000', severity: 'error', exit: 4, message: err.message, details: err.issues }] });
      throw new GhkError(`${err.message}:\n  ${err.issues.join('\n  ')}`, ExitCode.GATE_FAILED);
    }
    const contract = loadContract(root, options.contract ?? manifest.service.contract);
    const previous = previousManifest(root, rel.split(path.sep).join('/'), options.against);
    const issues = validateManifest(manifest, { previous, contract: contract.file ? contract.operations : undefined });
    const exit = validationExitCode(issues);
    if (options.json) emitJson({ valid: exit === 0, manifest: rel, contract: contract.file ?? null, against: options.against ?? (previous ? `HEAD:${rel}` : null), issues });
    else {
      for (const i of issues) {
        const line = `${i.code}${i.capability ? ` ${i.capability}` : ''} ${i.message}`;
        if (i.severity === 'error') logger.error(line);
        else logger.warn(line);
      }
      if (!contract.file) logger.warn('No contract found: handlers were not checked against it (--contract).');
      if (exit === 0) logger.success(`${rel}: ${manifest.capabilities.filter(c => c.status === 'approved').length} approved capability(ies), valid.`);
    }
    if (exit) process.exitCode = exit;
  }
}
