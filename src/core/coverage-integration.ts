import { execSync } from 'child_process';
import path from 'path';
import fs from 'fs';
import { GherkinAIConfig } from './config';

export interface CoverageResult {
  success: boolean;
  coveragePercentage: number;
  targetPercentage: number;
  toolUsed: string;
  reportPath: string;
  errorMessage?: string;
  /** The test + coverage command that was run, and its exit code (0 when it passed). */
  command?: string;
  exitCode?: number;
  /** When the report that was read was written (ISO 8601). */
  reportMtime?: string;
  /** Where the command came from: the stack default, or `coverage.command` in the configuration. */
  commandSource?: 'stack-default' | 'config';
  /** Something the user should fix for the figure to be right (e.g. a chained npm test script). */
  warning?: string;
}

/** The tool whose report format a configured `coverage.report` file has. */
export function coverageToolForReport(report: string): string | undefined {
  const name = path.basename(report).toLowerCase();
  if (name === 'coverage-summary.json') return 'Istanbul/c8 (Jest/Vitest)';
  if (name.endsWith('.csv')) return 'JaCoCo';
  if (name.endsWith('.json')) return 'coverage.py (pytest)';
  if (name.endsWith('.txt')) return 'go tool cover';
  return undefined;
}

/**
 * `npm test -- --coverage` hands the flags to the last command of the script, so with "jest && cucumber-js"
 * cucumber-js gets them and jest measures nothing (LMS P-02).
 */
function chainedNpmTestWarning(projectDir: string): string | undefined {
  try {
    const script: string | undefined = JSON.parse(fs.readFileSync(path.join(projectDir, 'package.json'), 'utf8')).scripts?.test;
    if (script && /&&|\|\||;/.test(script)) {
      return `The "test" script chains commands ("${script}"); npm passes the coverage flags to the last one only. Make the coverage tool run last, or set coverage.command and coverage.report.`;
    }
  } catch {
    // no package.json: nothing to check
  }
  return undefined;
}

export function runCoverage(projectDir: string, config: GherkinAIConfig): CoverageResult {
  const targetPercentage = config.rules.coverageTarget || 85;
  const stack = config.stack;

  let command = '';
  let toolUsed = '';
  let reportPath = '';
  let warning: string | undefined;
  const configured = config.coverage;

  try {
    if (configured?.command || configured?.report) {
      if (!configured.command || !configured.report) {
        return { success: false, coveragePercentage: 0, targetPercentage, toolUsed: 'Configured', reportPath: '', commandSource: 'config',
          errorMessage: 'coverage.command and coverage.report go together: set both in gherkin-ai.config.json.' };
      }
      const tool = coverageToolForReport(configured.report);
      if (!tool) {
        return { success: false, coveragePercentage: 0, targetPercentage, toolUsed: 'Configured', reportPath: configured.report, commandSource: 'config',
          errorMessage: `Unknown coverage report format: ${configured.report}. Use coverage-summary.json, a JaCoCo .csv, coverage.json or a go tool cover .txt.` };
      }
      toolUsed = tool;
      command = configured.command;
      reportPath = path.resolve(projectDir, configured.report);
    } else if (stack.language === 'typescript' || stack.language === 'javascript') {
      warning = chainedNpmTestWarning(projectDir);
      toolUsed = 'Istanbul/c8 (Jest/Vitest)';
      command = 'npm test -- --coverage --coverageReporters="json-summary"';
      reportPath = path.join(projectDir, 'coverage', 'coverage-summary.json');
    } else if ((stack.language === 'java' || stack.language === 'kotlin') && ['build.gradle.kts', 'build.gradle'].some(f => fs.existsSync(path.join(projectDir, f)))) {
      // Gradle builds generated by gherkin-ai finalize `test` with jacocoTestReport.
      toolUsed = 'JaCoCo';
      command = `${fs.existsSync(path.join(projectDir, 'gradlew')) ? './gradlew' : 'gradle'} test jacocoTestReport`;
      reportPath = path.join(projectDir, 'build', 'reports', 'jacoco', 'test', 'jacocoTestReport.csv');
    } else if (stack.language === 'java' || stack.language === 'kotlin') {
      toolUsed = 'JaCoCo';
      command = 'mvn -B test jacoco:report';
      reportPath = path.join(projectDir, 'target', 'site', 'jacoco', 'jacoco.csv');
    } else if (stack.language === 'csharp' || stack.language === 'dotnet') {
      toolUsed = 'coverlet (dotnet test)';
      command = 'dotnet test /p:CollectCoverage=true /p:CoverletOutputFormat=json';
      reportPath = path.join(projectDir, 'coverage.json');
    } else if (stack.language === 'python') {
      toolUsed = 'coverage.py (pytest)';
      command = 'pytest --cov=. --cov-report=json';
      reportPath = path.join(projectDir, 'coverage.json');
    } else if (stack.language === 'go') {
      toolUsed = 'go tool cover';
      command = 'go test -coverprofile=coverage.out ./... && go tool cover -func=coverage.out > coverage-summary.txt';
      reportPath = path.join(projectDir, 'coverage-summary.txt');
    } else {
      return {
        success: false,
        coveragePercentage: 0,
        targetPercentage,
        toolUsed: 'Unsupported',
        reportPath: '',
        errorMessage: `Coverage integration not yet supported for language: ${stack.language}`
      };
    }

    // A report left by an earlier run is never read as this run's result: delete it first. JaCoCo also appends
    // to target/jacoco.exec by default, so the same tests measured after an integration run gave another figure.
    fs.rmSync(reportPath, { force: true });
    if (toolUsed === 'JaCoCo') {
      fs.rmSync(path.join(projectDir, 'target', 'jacoco.exec'), { force: true });
      fs.rmSync(path.join(projectDir, 'build', 'jacoco', 'test.exec'), { force: true });
    }

    const meta = { commandSource: (configured?.command ? 'config' : 'stack-default') as CoverageResult['commandSource'], ...(warning ? { warning } : {}) };
    let exitCode = 0;
    try {
      execSync(command, { cwd: projectDir, stdio: 'pipe' });
    } catch (e: any) {
      exitCode = typeof e.status === 'number' ? e.status : 1;
    }

    if (exitCode !== 0) {
      // Failing tests are never a coverage figure, whatever report they left behind.
      return {
        success: false,
        coveragePercentage: 0,
        targetPercentage,
        toolUsed,
        reportPath,
        command,
        ...meta,
        exitCode,
        errorMessage: `Tests failed: \`${command}\` exited with code ${exitCode}`
      };
    }

    if (!fs.existsSync(reportPath)) {
      return {
        success: false,
        coveragePercentage: 0,
        targetPercentage,
        toolUsed,
        reportPath,
        command,
        ...meta,
        exitCode,
        errorMessage: `Coverage report not found at ${reportPath}. Ensure ${toolUsed} is installed and configured.`
      };
    }

    const coveragePercentage = parseCoverageReport(toolUsed, fs.readFileSync(reportPath, 'utf8'));

    return {
      success: coveragePercentage >= targetPercentage,
      coveragePercentage: Number(coveragePercentage.toFixed(2)),
      targetPercentage,
      toolUsed,
      reportPath,
      command,
      ...meta,
      exitCode,
      reportMtime: fs.statSync(reportPath).mtime.toISOString()
    };
  } catch (err: any) {
    return {
      success: false,
      coveragePercentage: 0,
      targetPercentage,
      toolUsed,
      reportPath,
      errorMessage: err.message
    };
  }
}

/** Coverage percentage from the report a tool writes (see runCoverage for the tool names). */
export function parseCoverageReport(toolUsed: string, raw: string): number {
    let coveragePercentage = 0;

    // Parse the generated report based on the tool
    if (toolUsed === 'Istanbul/c8 (Jest/Vitest)') {
      const summary = JSON.parse(raw);
      coveragePercentage = summary.total?.lines?.pct || 0;
    } else if (toolUsed === 'JaCoCo') {
      const csv = raw;
      const lines = csv.split(/\r?\n/).filter(Boolean);
      let totalMissed = 0;
      let totalCovered = 0;
      // Simple parse of CSV (skip header)
      for (let i = 1; i < lines.length; i++) {
        const parts = lines[i].split(',');
        // INSTRUCTION_MISSED is index 3, INSTRUCTION_COVERED is index 4 typically in JaCoCo CSV
        if (parts.length >= 5) {
          totalMissed += parseInt(parts[3] || '0', 10);
          totalCovered += parseInt(parts[4] || '0', 10);
        }
      }
      const total = totalMissed + totalCovered;
      coveragePercentage = total > 0 ? (totalCovered / total) * 100 : 0;
    } else if (toolUsed === 'coverlet (dotnet test)' || toolUsed === 'coverage.py (pytest)') {
      const summary = JSON.parse(raw);
      // Handle Python coverage.py JSON format
      if (summary.totals && typeof summary.totals.percent_covered !== 'undefined') {
        coveragePercentage = summary.totals.percent_covered;
      } 
      // Handle Coverlet JSON format
      else {
        // Just a basic fallback, Coverlet JSON is complex, but this supports a general extraction if present
        coveragePercentage = summary.total_coverage || 0;
      }
    } else if (toolUsed === 'go tool cover') {
      const txt = raw;
      const match = txt.match(/total:\s+\(statements\)\s+([0-9.]+)%/);
      if (match && match[1]) {
        coveragePercentage = parseFloat(match[1]);
      }
    }

    return coveragePercentage;
}
