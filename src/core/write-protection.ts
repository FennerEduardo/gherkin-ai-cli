/* ==========================================================================
   gherkin-ai-cli - Protection of implemented code during `ghk generate`

   Generated files are meant to be implemented. Regenerating must never wipe
   that work: a file is overwritten only when it is provably what gherkin-ai
   wrote last time (its checksum matches the inventory). Anything else gets
   the new version next to it as `<file>.ghk-new`.

   In a project marked as implemented (.ghk-implemented), only the runtime
   kernel and the contracts are created: the service already has its own
   controllers, wiring and tests (core/artifact-roles.ts). The kernel is
   written as a unit: when one kernel file is kept, the generated code that
   would be created or updated next to it goes to .ghk-new too, so the
   project still compiles until the kernel is merged.
   ========================================================================== */

import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import { firstMatch } from '../utils/glob';
import { ArtifactRole, artifactRole, isSourceCode } from './artifact-roles';
import type { ArtifactEntry } from './inventory';

export const NEW_SUFFIX = '.ghk-new';
export const IMPLEMENTED_MARKER = '.ghk-implemented';
const GENERATED_HEADER = /Generated by gherkin-ai(?: CLI)? v\d+\.\d+\.\d+/;

export type WriteAction =
  | 'create'      // file does not exist
  | 'update'      // file is exactly what gherkin-ai generated last time
  | 'unchanged'   // file already has the new content
  | 'overwrite'   // --force, or a generated file from before checksums were recorded
  | 'side-by-side' // edited or protected: the new version goes to <file>.ghk-new
  | 'skipped';     // not written: generation.exclude, or scaffolding in an implemented project

export interface PlannedWrite {
  /** Path relative to outputDir, as the generator returned it. */
  filePath: string;
  /** Absolute path on disk. */
  fullPath: string;
  /** Where the content is written (fullPath, or fullPath + .ghk-new). */
  target: string;
  action: WriteAction;
  role: ArtifactRole;
  reason?: string;
  /** Held back as .ghk-new because the runtime kernel is pending merge. */
  held?: boolean;
}

export interface WritePlanOptions {
  cwd: string;
  outputDir: string;
  /** Inventory entries from earlier runs (checksums of what was generated). */
  inventory: ArtifactEntry[];
  /** generation.protect globs, relative to the project root. */
  protect?: string[];
  /** generation.exclude globs, relative to the project root: never created, updated or written side by side. */
  exclude?: string[];
  /** Also create scaffolding (controllers, wiring, tests) in a project marked as implemented. */
  includeScaffold?: boolean;
  /** Write only the contracts (`ghk generate --contracts-only`); everything else is skipped. */
  contractsOnly?: boolean;
  /**
   * Overwrite a file without a recorded checksum when it carries the `Generated by gherkin-ai` header.
   * Default: only when an inventory exists. Without one (a fresh clone of a project from before the
   * inventory was versioned) a header proves nothing about edits. `ghk upgrade --apply` passes true: it
   * works on its own branch, and projects from 2.x have headers but no checksums.
   */
  trustHeaders?: boolean;
  force?: boolean;
}

export const sha256 = (content: string | Buffer) => crypto.createHash('sha256').update(content).digest('hex');

/**
 * Whether a file on disk is still what was generated (its recorded checksum). Line endings are
 * ignored: git with core.autocrlf (the Windows default) checks generated LF files out as CRLF.
 */
export function matchesChecksum(content: Buffer, checksum: string): boolean {
  if (sha256(content) === checksum) return true;
  return content.includes('\r\n') && sha256(content.toString('utf8').replace(/\r\n/g, '\n')) === checksum;
}

const posix = (p: string) => p.replace(/\\/g, '/');

/** Decides, per artifact, whether writing it is safe. Nothing is written here. */
export function planWrites(artifacts: { filePath: string; content: string; type?: string }[], opts: WritePlanOptions): PlannedWrite[] {
  const checksums = new Map(opts.inventory.map(e => [posix(e.filePath), e.checksum]));
  const declined = new Map(opts.inventory.filter(e => e.declined).map(e => [posix(e.filePath), e.declined]));
  const implemented = fs.existsSync(path.join(opts.cwd, IMPLEMENTED_MARKER));
  const fromRootGlobs = (globs?: string[]) => (globs ?? []).map(p => posix(p).replace(/^\.\//, ''));
  const protect = fromRootGlobs(opts.protect);
  const exclude = fromRootGlobs(opts.exclude);
  const trustHeaders = opts.trustHeaders ?? opts.inventory.some(e => e.checksum);

  const plans = artifacts.map(a => {
    const fullPath = path.resolve(opts.cwd, opts.outputDir, a.filePath);
    const fromRoot = posix(path.relative(opts.cwd, fullPath));
    const role = artifactRole(fromRoot, a.type);
    const plan = (action: WriteAction, reason?: string): PlannedWrite =>
      ({ filePath: a.filePath, fullPath, target: action === 'side-by-side' ? fullPath + NEW_SUFFIX : fullPath, action, role, reason });

    const excluded = firstMatch(fromRoot, exclude);
    if (excluded) return plan('skipped', `excluded by generation.exclude "${excluded}"`);
    if (opts.contractsOnly && role !== 'contract') return plan('skipped', '--contracts-only');
    if (!fs.existsSync(fullPath)) {
      // Spring and Quarkus read both files: a generated application.properties next to the project's YAML
      // would silently override it.
      if (path.basename(fullPath) === 'application.properties' && !opts.force) {
        const yaml = ['application.yml', 'application.yaml'].find(f => fs.existsSync(path.join(path.dirname(fullPath), f)));
        if (yaml) return plan('skipped', `${yaml} already configures the application`);
      }
      if (implemented && !opts.force && !opts.includeScaffold && (role === 'scaffold' || role === 'wiring')) {
        return plan('skipped', `${IMPLEMENTED_MARKER}: ${role} is not created in an implemented project (--include-scaffold creates it)`);
      }
      return plan('create');
    }
    const current = fs.readFileSync(fullPath);
    if (current.equals(Buffer.from(a.content, 'utf8'))) return plan('unchanged');
    if (opts.force) return plan('overwrite', '--force');

    const rule = firstMatch(fromRoot, protect);
    if (rule) return plan('side-by-side', `protected by generation.protect "${rule}"`);

    // A matching checksum proves the file is exactly what gherkin-ai generated: safe to update even in a
    // project marked as implemented.
    const recorded = checksums.get(posix(a.filePath));
    if (recorded && matchesChecksum(current, recorded)) return plan('update');
    // The user kept their version of exactly this generated content (ghk generate --review): do not offer it again.
    if (declined.get(posix(a.filePath)) === sha256(a.content)) return plan('unchanged', 'generated version declined in review');
    if (implemented) return plan('side-by-side', `${IMPLEMENTED_MARKER} marks this project as implemented`);
    if (recorded) return plan('side-by-side', 'edited since it was generated');
    // No checksum on record (generated before 3.0.1, or never generated by gherkin-ai).
    if (!GENERATED_HEADER.test(current.subarray(0, 4096).toString('utf8'))) return plan('side-by-side', 'not generated by gherkin-ai (no checksum or header)');
    return trustHeaders
      ? plan('overwrite', 'generated file without a recorded checksum')
      : plan('side-by-side', 'no inventory (.ghe/inventory.json) to prove it unedited; --force overwrites it');
  });

  // The generated code targets the new kernel. While a kernel file is kept, writing the rest would leave a
  // project that does not compile (new files calling an API the kept kernel does not have).
  const kept = kernelPendingMerge(plans);
  if (kept.length) {
    for (const p of plans) {
      if ((p.action === 'create' || p.action === 'update' || p.action === 'overwrite') && isSourceCode(p.filePath)) {
        Object.assign(p, { action: 'side-by-side', target: p.fullPath + NEW_SUFFIX, held: true, reason: `held until the runtime kernel is merged (${kept.length} kernel file(s) kept)` });
      }
    }
  }
  return plans;
}

/** Kernel files kept as they are (edited or protected) while the generator has a new version. */
export function kernelPendingMerge(plans: PlannedWrite[]): PlannedWrite[] {
  return plans.filter(p => p.role === 'kernel' && p.action === 'side-by-side' && !p.held);
}

/** Applies a plan; returns the plans that were written. */
export function applyWrites(plans: PlannedWrite[], contents: Map<string, string>, write: (file: string, content: string) => void): PlannedWrite[] {
  const written: PlannedWrite[] = [];
  for (const p of plans) {
    if (p.action === 'unchanged' || p.action === 'skipped') continue;
    fs.mkdirSync(path.dirname(p.target), { recursive: true });
    write(p.target, contents.get(p.filePath) as string);
    written.push(p);
  }
  return written;
}
