/* ==========================================================================
   gherkin-ai-cli - Core gateway provider `container`: the generated MCP
   runtime on any container platform (Docker, Kubernetes, ECS, Cloud Run,
   Container Apps), with no managed gateway in front.

   Every control is the runtime's or nobody's: this provider is the honest
   baseline the cloud providers improve on.
   ========================================================================== */

import type { ControlSupport, ExposeControl, GatewayProvider } from '../provider-types';
import { planTools } from './plan';

const CAPABILITIES: Record<ExposeControl, ControlSupport> = {
  'inbound-auth': 'runtime',
  'per-tool-authz': 'runtime',
  'tenant-isolation': 'runtime',
  'outbound-credentials': 'runtime',
  'rate-limit': 'runtime',
  'human-approval': 'runtime',
  audit: 'runtime',
  'private-network': 'unsupported',
  'tool-discovery': 'unsupported'
};

export const containerProvider: GatewayProvider = {
  id: 'container',
  label: 'MCP runtime on your container platform (no managed gateway)',
  tier: 'core',
  maturity: 'beta',
  capabilities: () => ({ ...CAPABILITIES }),
  plan(manifest, options) {
    return {
      provider: 'container',
      tools: planTools(manifest, CAPABILITIES),
      resources: [
        `one container of the generated MCP runtime (${options.image ?? 'built from expose/mcp-runtime'}) for ${manifest.service} in ${options.environment}`
      ],
      warnings: [
        'No gateway in front: the runtime is the only authorization boundary (it always authorizes, but there is no second one).',
        'Rate limits are counted per runtime instance: with several replicas the effective limit is the limit times the replicas.',
        'Private networking to the service and semantic tool search are not provided: put the runtime and the service on the same private network.'
      ]
    };
  },
  emit(manifest, options) {
    const env = (name: string) => `      ${name}: \${${name}}`;
    const lines = [
      '# The MCP runtime of ' + manifest.service + ' (generated by gherkin-ai: ghk expose generate --target container).',
      '# Values come from your shell or secret manager; none is written here.',
      'services:',
      '  mcp:',
      options.image ? `    image: ${options.image}` : '    build: ../mcp-runtime',
      '    ports:',
      '      - "8000:8000"',
      '    environment:',
      `      GHK_ENVIRONMENT: ${options.environment}`,
      env(manifest.baseUrlEnv ?? 'GHK_UPSTREAM_URL'),
      env('GHK_OIDC_ISSUER'),
      `      GHK_OIDC_AUDIENCE: ${(options.audiences ?? []).join(',') || '${GHK_OIDC_AUDIENCE}'}`,
      env('GHK_UPSTREAM_AUTH'),
      env('GHK_UPSTREAM_JWT_SECRET'),
      '    read_only: true',
      '    restart: unless-stopped',
      ''
    ];
    return [{ path: 'docker-compose.yml', content: lines.join('\n') }];
  },
  applyCommands: [['docker', 'compose', 'up', '-d', '--build']],
  tradeOffs: ['Runs wherever containers run, with no cloud lock-in and no per-request gateway cost; you operate scaling, TLS and networking.']
};
