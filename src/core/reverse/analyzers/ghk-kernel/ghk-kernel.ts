/* ==========================================================================
   gherkin-ai-cli - gherkin-ai runtime kernel adapter for `ghk reverse`
   (PLAN-3.3.0 R-19, beta)

   Code generated by gherkin-ai does not expose one route per command: every
   runtime registers one dispatcher, `POST <route>/{id}/{command}`, and the
   commands and the events they record live in the domain aggregate:
     processOrder(command) { …; return this.record('OrderProcessed', …) }
   The framework adapters see a single route, so this adapter reads the
   generated kernel instead, in every language the kernel is generated in
   (TypeScript, Java, Kotlin, C#, Python, Go, PHP, Ruby, Elixir, Rust):
   - the dispatcher's doc comment `POST <route>/{id}/{command} (a_b, c_d)`
     and the `ghk:implements <Aggregate>` marker give the route and the
     command names (snake case, as the route takes them);
   - each aggregate command method gives the event it records.
   It is the adapter the round-trip goldens run on (16 reference projects),
   and the one that reads projects generated by an older gherkin-ai whose
   features drifted from the code.
   ========================================================================== */

import fs from 'fs';
import { isTestFile } from '../../discovery';
import { makeEvidence, normalisePath, type EndpointMetadata, type SourceEvidence } from '../../evidence';
import type { SourceAnalyzer } from '../../registry';
import { toKebab, toPascal, toSnake } from '../../../../utils/naming';

const ID = 'ghk-kernel';
const CODE_EXT = new Set(['.ts', '.js', '.java', '.kt', '.cs', '.py', '.go', '.php', '.rb', '.ex', '.rs']);
const IMPLEMENTS = /ghk:implements\s+([A-Z][A-Za-z0-9]*)/;
/** `POST /api/v1/orders/{id}/{command} (place_order, cancel_order)` in any comment style. */
const DISPATCHER = /POST\s+(\/[^\s(]*?)\/(?:\{id\}|:id|<id>|\{aggregate_id\})\/(?:\{command\}|:command|<command>)\s*\(([^)]*)\)/;
/** A command method of a generated aggregate: its first parameter is the command. */
const COMMAND_METHOD = /(?:^|[\s.])([A-Za-z_][A-Za-z0-9_]*!?)\s*\(\s*(?:&mut self,\s*|self,\s*|%__MODULE__\{\}\s*=\s*aggregate,\s*)?(?:[A-Z]\w*Command\s+)?\$?(?:command|cmd)\b(?:\s*[:)]|\s+Command\))/;
const NOT_COMMANDS = /^_?(assertValid|assert_valid!?|AssertValid|record|Record|execute|handle|Handle|new|initialize|constructor|restore|apply)$/;
/** The event a command records: `record('X'`, `record(XEventType.X`, `Record(XEventTypes.X`, `record(EventType::X`, `record(PrefixEventX`, `execute(aggregate, command, "X")`. */
const RECORDED = /\b_?[rR]ecord\s*\(\s*(?:['"]([A-Za-z]\w*)['"]|([A-Za-z_][\w.:]*))|execute\(aggregate,\s*command,\s*"([A-Za-z]\w*)"\)/;

/** The generator's own naming (`YRenderizado` → `Y` + `Renderizado`), so method, snake and Pascal forms agree. */
export const pascalOf = (name: string) => toPascal(name.replace(/!$/, ''));

/** `OrderEventType.OrderPlaced` → OrderPlaced; `EventType::OrderPlaced` → OrderPlaced; Go `OrderEventOrderPlaced` → OrderPlaced. */
export function eventFromReference(ref: string, aggregate?: string): string {
  const last = ref.split(/\.|::/).pop()!;
  if (ref.includes('.') || ref.includes('::')) return last;
  const prefix = aggregate ? `${aggregate}Event` : '';
  if (prefix && last.startsWith(prefix) && last.length > prefix.length) return last.slice(prefix.length);
  const m = last.match(/Event([A-Z]\w*)$/);
  return m ? m[1] : last;
}

interface KernelCommand { method: string; event?: string; line: number }

/** Command methods of one aggregate file, with the event each one records. */
export function aggregateCommands(text: string, aggregate?: string): KernelCommand[] {
  const lines = text.split('\n');
  const out: KernelCommand[] = [];
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(COMMAND_METHOD);
    if (!m || NOT_COMMANDS.test(m[1]) || /^\s*(\/\/|#|\*|\/\*|it\(|test|assert|expect)/.test(lines[i]) || /\b(?:if|return|await|throw|new)\s/.test(lines[i].slice(0, lines[i].indexOf(m[1])))) continue;
    // The recorded event is on the signature line (Elixir one-liners) or within the next lines of the body.
    let event: string | undefined;
    for (let j = i; j < Math.min(lines.length, i + 8); j++) {
      if (j > i && COMMAND_METHOD.test(lines[j]) && !NOT_COMMANDS.test(lines[j].match(COMMAND_METHOD)![1])) break;
      const r = lines[j].match(RECORDED);
      if (r) { event = r[1] ?? r[3] ?? (r[2] && !/^(type|type_|t|event_type)$/.test(r[2]) ? eventFromReference(r[2], aggregate) : undefined); if (event) break; }
    }
    if (event) out.push({ method: m[1], event, line: i + 1 });
  }
  return out;
}

/**
 * The checks every command of a generated aggregate goes through (`assertValid` / `assert_valid` /
 * `AssertValid`): their literal messages, which the dispatcher returns as 422. Interpolated messages
 * (`Command targets ${id}`) are left out: their text is not known statically.
 */
export function kernelValidations(text: string): { message: string; line: number }[] {
  const lines = text.split('\n');
  const start = lines.findIndex(l => /\b_?(assertValid|assert_valid!?|AssertValid)\s*\(/.test(l) && /\b(def|fun|func|fn|function|private|void|static)\b/.test(l));
  if (start < 0) return [];
  const out: { message: string; line: number }[] = [];
  for (let i = start + 1; i < Math.min(lines.length, start + 9); i++) {
    if (/\b(def|fun|func|fn|function|private|public)\b/.test(lines[i]) && !/throw|raise|return|Err|error/i.test(lines[i])) break;
    for (const m of lines[i].matchAll(/"([^"$#{}%\\]{6,})"|'([^'$#{}%\\]{6,})'/g)) {
      const message = m[1] ?? m[2];
      if (/\s/.test(message)) out.push({ message, line: i + 1 });
    }
  }
  return out;
}

const ghkKernel: SourceAnalyzer = {
  id: ID,
  language: 'any',
  frameworks: ['gherkin-ai kernel'],
  maturity: 'beta',
  detect(ctx) {
    return ctx.files.some(f => CODE_EXT.has(f.ext) && !isTestFile(f.rel) && (() => { try { return IMPLEMENTS.test(fs.readFileSync(f.abs, 'utf8')); } catch { return false; } })());
  },
  async analyze(ctx) {
    const out: SourceEvidence[] = [];
    const files = ctx.files.filter(f => CODE_EXT.has(f.ext) && !isTestFile(f.rel) && !/(^|\/)(dist|build|target|_build)\//.test(f.rel));
    const texts = new Map<string, string>();
    for (const f of files) {
      try { texts.set(f.rel, fs.readFileSync(f.abs, 'utf8')); } catch { /* unreadable */ }
    }
    // Aggregate classes / modules / structs: <Name>Aggregate.
    const aggregates = new Map<string, { file: string; commands: KernelCommand[]; validations: { message: string; line: number }[] }>();
    for (const [rel, text] of texts) {
      if (!/generated by gherkin-ai|Domain kernel|record\s*\(/i.test(text)) continue;
      // class X Aggregate (TS, Java, Kotlin, C#, Python, PHP, Ruby), struct (Rust), type … struct (Go), defmodule (Elixir).
      const decl = text.match(/\b(?:class|struct|type|defmodule\s+[\w.]*?\.?)\s*([A-Z][A-Za-z0-9]*)Aggregate\b/);
      if (!decl) continue;
      const commands = aggregateCommands(text, decl[1]);
      if (commands.length) aggregates.set(decl[1], { file: rel, commands, validations: kernelValidations(text) });
    }
    // Dispatchers: the route and the snake-case command names, under the ghk:implements marker.
    const covered = new Set<string>();
    const emit = (aggregate: string, base: string, snakes: string[], rel: string, line: number) => {
      covered.add(aggregate);
      const kernel = aggregates.get(aggregate);
      for (const snake of snakes) {
        const command = pascalOf(snake);
        const method = kernel?.commands.find(c => pascalOf(c.method) === command);
        const path = `${base}/{id}/${snake}`;
        const endpoint = makeEvidence({
          kind: 'http-endpoint', extractor: ID, confidence: 'strong', location: { file: rel, startLine: line, endLine: line },
          symbol: command, description: `POST ${path}`, key: `POST ${path}`,
          metadata: { method: 'POST', path, handler: method?.method ?? snake, owner: `${aggregate}Aggregate`, command, aggregate } satisfies EndpointMetadata
        });
        out.push(endpoint);
        if (!method || !kernel) continue;
        const at = { file: kernel.file, startLine: method.line, endLine: method.line };
        out.push(makeEvidence({ kind: 'service-call', extractor: ID, confidence: 'strong', references: [endpoint.id], location: at, symbol: `${aggregate}Aggregate.${method.method}`, description: `runs ${aggregate}Aggregate.${method.method}`, metadata: { target: `${aggregate}Aggregate`, method: method.method } }));
        if (method.event) out.push(makeEvidence({ kind: 'domain-event', extractor: ID, confidence: 'strong', references: [endpoint.id], location: at, symbol: method.event, description: `records ${method.event}`, metadata: { event: method.event } }));
        // The kernel's dispatcher answers 202 for a new command (200 for a replay).
        out.push(makeEvidence({ kind: 'success-response', extractor: ID, confidence: 'inferred', references: [endpoint.id], location: endpoint.location, description: 'responds 202', metadata: { status: 202 } }));
        // Every command is checked by the aggregate before it records anything; the dispatcher answers 422.
        for (const v of kernel.validations) {
          out.push(makeEvidence({ kind: 'validation-rule', extractor: ID, confidence: 'strong', references: [endpoint.id], location: { file: kernel.file, startLine: v.line, endLine: v.line }, description: `${v.message} (422)`, metadata: { status: 422, message: v.message }, key: `${command}|${v.message}` }));
        }
      }
    };
    for (const [rel, text] of texts) {
      const lines = text.split('\n');
      lines.forEach((line, i) => {
        const d = line.match(DISPATCHER);
        if (!d) return;
        const aggregate = lines.slice(Math.max(0, i - 6), i + 6).join('\n').match(IMPLEMENTS)?.[1];
        if (aggregate) emit(aggregate, normalisePath(d[1]), d[2].split(',').map(s => s.trim()).filter(Boolean), rel, i + 1);
      });
    }
    // Multi-feature apps (Express, Go) register one dispatcher over a table of [route, aggregate] pairs with no
    // per-command comment: the route comes from the table (or the generator's default), the commands from the aggregate.
    for (const [rel, text] of texts) {
      for (const m of text.matchAll(new RegExp(IMPLEMENTS.source, 'g'))) {
        const aggregate = m[1];
        const kernel = aggregates.get(aggregate);
        if (covered.has(aggregate) || !kernel) continue;
        const pair = text.match(new RegExp(`['"\`](\\/[^'"\`\\s]+?)(?:\\/\\{id\\}\\/\\{command\\}|\\/:id\\/:command)?['"\`]\\s*[,:]\\s*['"\`]${aggregate}['"\`]`));
        const base = normalisePath(pair?.[1] ?? `/api/v1/${toKebab(aggregate)}`);
        const line = text.slice(0, m.index).split('\n').length;
        emit(aggregate, base, kernel.commands.map(c => toSnake(c.method)), rel, line);
      }
    }
    return out;
  }
};

export default ghkKernel;
