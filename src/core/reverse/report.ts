/* ==========================================================================
   gherkin-ai-cli - Publishable behaviour-coverage reports
   (`reverse coverage --format markdown|html`, PLAN-3.3.0-reverse-plus RV-18)

   Markdown for a pull-request comment in CI; HTML as one static page with
   no external dependency (styles inline, light and dark). Both list the
   share of the code the features specify, by aggregate, and what is left
   unexplained by kind of entry point: HTTP endpoints, message handlers,
   scheduled jobs, GraphQL and gRPC operations. Deterministic: no date.
   ========================================================================== */

import type { DedupReport, OperationMatch } from './dedup';

const KIND_OF: Record<string, string> = { EVENT: 'message handler', SCHEDULE: 'scheduled job', GRAPHQL: 'GraphQL', GRPC: 'gRPC' };
const kindOf = (o: OperationMatch) => KIND_OF[o.method] ?? 'HTTP endpoint';
const label = (o: OperationMatch) => (KIND_OF[o.method] ? `${o.method.toLowerCase()} ${o.path}` : `${o.method} ${o.path}`);

interface AggregateRow { aggregate: string; operations: number; documented: number; renamed: number; undocumented: number; percent: number }

export function coverageByAggregate(report: DedupReport): AggregateRow[] {
  const rows = new Map<string, AggregateRow>();
  for (const o of report.operations) {
    const r = rows.get(o.aggregate) ?? { aggregate: o.aggregate, operations: 0, documented: 0, renamed: 0, undocumented: 0, percent: 0 };
    r.operations++;
    r[o.status]++;
    rows.set(o.aggregate, r);
  }
  return [...rows.values()].map(r => ({ ...r, percent: Math.round(((r.documented + r.renamed) / r.operations) * 100) })).sort((a, b) => a.percent - b.percent || a.aggregate.localeCompare(b.aggregate));
}

export function coverageMarkdown(report: DedupReport, title = 'Behaviour coverage'): string {
  const c = report.coverage;
  const lines = [
    `## ${title}`,
    '',
    `**${c.percent}%** of the ${c.operations} operation(s) in the code are specified by ${report.features} feature(s): ${c.documented} documented, ${c.renamed} renamed, ${c.undocumented} undocumented.`,
    '',
    '| Aggregate | Operations | Documented | Renamed | Undocumented | Coverage |',
    '|---|---:|---:|---:|---:|---:|',
    ...coverageByAggregate(report).map(r => `| ${r.aggregate} | ${r.operations} | ${r.documented} | ${r.renamed} | ${r.undocumented} | ${r.percent}% |`)
  ];
  const undocumented = report.operations.filter(o => o.status === 'undocumented');
  if (undocumented.length) {
    lines.push('', '### Not specified by any feature', '');
    for (const kind of [...new Set(undocumented.map(kindOf))].sort()) {
      lines.push(`**${kind}s**`, '', ...undocumented.filter(o => kindOf(o) === kind).map(o => `- \`${label(o)}\` ${o.operation}`), '');
    }
  }
  const renamed = report.operations.filter(o => o.status === 'renamed');
  if (renamed.length) lines.push('### Specified under another name', '', ...renamed.map(o => `- \`${label(o)}\` ${o.operation}: \`${o.specName}\` in ${o.feature}`), '');
  if (report.specOnly.length) lines.push('### Declared by a feature, not implemented', '', ...report.specOnly.map(s => `- \`${s.command}\` in ${s.feature}`), '');
  lines.push('<sub>Generated by `ghk reverse coverage` (beta). Characterization: it compares what the code does today with what the features say.</sub>', '');
  return lines.join('\n');
}

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export function coverageHtml(report: DedupReport, title = 'Behaviour coverage'): string {
  const c = report.coverage;
  const rows = coverageByAggregate(report).map(r => `<tr><td>${esc(r.aggregate)}</td><td class="n">${r.operations}</td><td class="n">${r.documented}</td><td class="n">${r.renamed}</td><td class="n">${r.undocumented}</td><td class="n"><span class="bar"><span style="width:${r.percent}%"></span></span> ${r.percent}%</td></tr>`).join('\n');
  const undocumented = report.operations.filter(o => o.status === 'undocumented');
  const groups = [...new Set(undocumented.map(kindOf))].sort().map(kind => `<h3>${esc(kind)}s</h3><ul>${undocumented.filter(o => kindOf(o) === kind).map(o => `<li><code>${esc(label(o))}</code> ${esc(o.operation)}</li>`).join('')}</ul>`).join('\n');
  const renamed = report.operations.filter(o => o.status === 'renamed').map(o => `<li><code>${esc(label(o))}</code> ${esc(o.operation)}: <code>${esc(o.specName ?? '')}</code> in ${esc(o.feature ?? '')}</li>`).join('');
  const specOnly = report.specOnly.map(s => `<li><code>${esc(s.command)}</code> in ${esc(s.feature)}</li>`).join('');
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<style>
:root { --bg: #ffffff; --fg: #1d1f23; --muted: #5d6470; --line: #e3e6ea; --accent: #2f6fdd; --track: #eef1f5; }
@media (prefers-color-scheme: dark) { :root { --bg: #15171b; --fg: #e8eaed; --muted: #a0a7b2; --line: #2c3037; --accent: #6ea0ff; --track: #23272e; } }
body { margin: 0; background: var(--bg); color: var(--fg); font: 15px/1.5 system-ui, -apple-system, "Segoe UI", sans-serif; }
main { max-width: 960px; margin: 0 auto; padding: 24px 16px 48px; }
h1 { font-size: 1.5rem; margin: 0 0 4px; } h2 { font-size: 1.1rem; margin-top: 32px; } h3 { font-size: 1rem; margin: 20px 0 6px; }
.lead { color: var(--muted); margin: 0 0 20px; } .big { font-size: 2.4rem; font-weight: 700; color: var(--accent); }
table { width: 100%; border-collapse: collapse; } th, td { text-align: left; padding: 8px 6px; border-bottom: 1px solid var(--line); } td.n, th.n { text-align: right; white-space: nowrap; }
.bar { display: inline-block; width: 80px; height: 8px; background: var(--track); border-radius: 4px; vertical-align: middle; overflow: hidden; } .bar span { display: block; height: 100%; background: var(--accent); }
code { font: 0.9em ui-monospace, SFMono-Regular, Menlo, monospace; } ul { padding-left: 20px; } footer { color: var(--muted); font-size: 0.85rem; margin-top: 40px; }
.wrap { overflow-x: auto; }
</style>
</head>
<body>
<main>
<h1>${esc(title)}</h1>
<p class="lead">${report.features} feature(s) against the code, read by <code>ghk reverse</code> (beta).</p>
<p><span class="big">${c.percent}%</span> of ${c.operations} operation(s) specified: ${c.documented} documented, ${c.renamed} renamed, ${c.undocumented} undocumented.</p>
<h2>By aggregate</h2>
<div class="wrap"><table><thead><tr><th>Aggregate</th><th class="n">Operations</th><th class="n">Documented</th><th class="n">Renamed</th><th class="n">Undocumented</th><th class="n">Coverage</th></tr></thead><tbody>
${rows}
</tbody></table></div>
${undocumented.length ? `<h2>Not specified by any feature</h2>\n${groups}` : ''}
${renamed ? `<h2>Specified under another name</h2><ul>${renamed}</ul>` : ''}
${specOnly ? `<h2>Declared by a feature, not implemented</h2><ul>${specOnly}</ul>` : ''}
<footer>Characterization: this compares what the code does today with what the features say. It is not a statement that the code is correct.</footer>
</main>
</body>
</html>
`;
}
