export interface InventoryEntry { filePath: string; checksum?: string }

export function readInventory(cwd: string): InventoryEntry[] {
  try {
    const json = JSON.parse(fs.readFileSync(path.join(cwd, '.ghe', 'inventory.json'), 'utf8'));
    return Array.isArray(json?.artifacts) ? json.artifacts.filter((a: any) => typeof a?.filePath === 'string') : [];
  } catch {
    return [];
  }
}

export const sha256 = (content: string | Buffer) => crypto.createHash('sha256').update(content).digest('hex');

export interface StaleFiles {
  /** Previously generated, no longer generated, unchanged since: safe to delete. */
  removable: string[];
  /** Previously generated, no longer generated, but edited (or unverifiable): left in place. */
  kept: string[];
}

/**
 * Files under outputDir that an earlier generation produced and the new one did not.
 * Only a checksum in the previous .ghe/inventory.json proves a file is untouched; files
 * that merely carry a "Generated by gherkin-ai" header, or that git tracks inside a
 * dedicated outputDir, are listed as kept unless `prune` is set (the upgrade runs on
 * its own branch, so a pruned file is one `git checkout` away).
 */
export function findStaleFiles(opts: {
  outputDir: string;
  generated: Set<string>;
  previousInventory: InventoryEntry[];
  headerFiles: string[];
  /** Other files in a dedicated outputDir (e.g. `git ls-files`), relative to it. */
  trackedFiles?: string[];
  prune?: boolean;
}): StaleFiles {
  const removable: string[] = [];
  const kept: string[] = [];
  const candidates = new Map<string, string | undefined>();
  for (const entry of opts.previousInventory) candidates.set(entry.filePath.replace(/\\/g, '/'), entry.checksum);
  for (const file of [...opts.headerFiles, ...(opts.trackedFiles ?? [])]) if (!candidates.has(file)) candidates.set(file, undefined);

  for (const [rel, checksum] of candidates) {
    if (opts.generated.has(rel)) continue;
    const full = path.join(opts.outputDir, rel);
    if (!fs.existsSync(full)) continue;
    if (checksum ? sha256(fs.readFileSync(full)) === checksum : opts.prune) removable.push(rel);
    else kept.push(rel);
  }
  return { removable: removable.sort(), kept: kept.sort() };
}
