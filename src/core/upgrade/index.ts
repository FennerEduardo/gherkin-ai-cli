const MCP_CONFIGS = ['.mcp.json', '.cursor/mcp.json', '.vscode/mcp.json', '.windsurf/mcp.json'];

export function scanMcpConfigs(cwd: string, cliVersion: string): UpgradeFinding[] {
  const findings: UpgradeFinding[] = [];
  for (const rel of MCP_CONFIGS) {
    const file = path.join(cwd, rel);
    if (!fs.existsSync(file)) continue;
    let json: any;
    try { json = JSON.parse(fs.readFileSync(file, 'utf8')); } catch { continue; }
    const servers = json?.mcpServers ?? json?.servers ?? {};
    for (const [name, entry] of Object.entries<any>(servers)) {
      const cmdline = [entry?.command, ...(entry?.args ?? [])].filter(Boolean).join(' ');
      if (!/gherkin-ai|ghk\b|gherkin-cli/.test(cmdline)) continue;
      const pinned = /gherkin-ai@(\d[\w.-]*)/.exec(cmdline)?.[1];
      if (/bin[\\/]gherkin-ai\.js/.test(cmdline) && !path.isAbsolute(String(entry?.args?.[0] ?? ''))) {
        findings.push({ id: 'mcp.relative-bin', area: 'mcp', severity: 'required', fix: 'manual', file: rel, message: `MCP server "${name}" runs bin/gherkin-ai.js through a relative path, which only works from the CLI's own checkout.`, hint: 'Run `ghk mcp install` to write a pinned `npx gherkin-ai@<version> mcp` entry.' });
      } else if (!pinned || compareVersions(pinned, cliVersion) !== 0) {
        findings.push({ id: 'mcp.unpinned', area: 'mcp', severity: 'recommended', fix: 'manual', file: rel, message: `MCP server "${name}" ${pinned ? `pins v${pinned}` : 'is not pinned to a version'}.`, hint: `Run \`ghk mcp install\` to pin gherkin-ai@${cliVersion}. The v3 server is read-only unless mcp.allowWrite is set.` });
      }
    }
  }
  return findings;
}

