/* ==========================================================================
   gherkin-ai-cli - Project upgrade analysis (`ghk upgrade`)

   Read-only checks over a project directory:
   - which CLI version generated its files (the "Generated by" headers),
   - whether its gherkin-ai.config.json validates and what can be fixed,
   - CI scripts and MCP client configs that use flags or behavior the
     running CLI changed (see docs/MIGRATION-3.0.md),
   - legacy files 3.x no longer reads.
   Applying the result lives in src/commands/upgrade.ts.
   ========================================================================== */

import crypto from 'crypto';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { partialConfigSchema } from '../config/schema';
import { CONFIG_SCHEMA_ID } from '../config/json-schema';

export type FindingSeverity = 'required' | 'recommended' | 'info';
export type FindingArea = 'config' | 'generated' | 'automation' | 'mcp' | 'legacy' | 'cli';

export interface UpgradeFinding {
  id: string;
  area: FindingArea;
  severity: FindingSeverity;
  /** auto: `ghk upgrade --apply` handles it; manual: needs a person; none: informational. */
  fix: 'auto' | 'manual' | 'none';
  message: string;
  hint?: string;
  file?: string;
  line?: number;
}

