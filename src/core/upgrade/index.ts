export function scanLegacyFiles(cwd: string, home = os.homedir()): UpgradeFinding[] {
  const findings: UpgradeFinding[] = [];
  const authFile = path.join(home, '.gherkin-ai', 'auth.json');
  if (fs.existsSync(authFile)) {
    let hasSecret = false;
    try {
      const auth = JSON.parse(fs.readFileSync(authFile, 'utf8'));
      hasSecret = ['apiKey', 'token', 'key', 'secret'].some(k => typeof auth?.[k] === 'string' && auth[k].length > 0);
    } catch { /* unreadable: still worth reporting */ }
    findings.push(hasSecret
      ? { id: 'legacy.auth-json-secret', area: 'legacy', severity: 'recommended', fix: 'manual', file: '~/.gherkin-ai/auth.json', message: 'auth.json contains a credential in plain text; v3 no longer reads keys from it.', hint: 'Move the key to the OS keychain with `ghk login --provider <name>`, then delete the file.' }
      : { id: 'legacy.auth-json', area: 'legacy', severity: 'info', fix: 'none', file: '~/.gherkin-ai/auth.json', message: 'auth.json is only read for a legacy `provider` value; set llm.provider in ~/.gherkin-ai/config.json and delete it.' });
  }
  if (fs.existsSync(path.join(cwd, '.gherkin-ai', 'audit.log'))) {
    findings.push({ id: 'legacy.audit-log', area: 'legacy', severity: 'info', fix: 'none', file: '.gherkin-ai/audit.log', message: 'The plain-text audit log is replaced by .gherkin-ai/audit.jsonl; archive the old file if you need it.', hint: '`ghk audit export --format csv` exports the new trail for a SIEM.' });
  }
  if (fs.existsSync(path.join(cwd, '.ghe', 'logs', 'execution.log.jsonl'))) {
    findings.push({ id: 'legacy.execution-log', area: 'legacy', severity: 'info', fix: 'none', file: '.ghe/logs/execution.log.jsonl', message: 'v3 no longer writes .ghe/logs on every run; the old log can be deleted.', hint: 'Set logging.file to keep a rotated log file.' });
  }
  return findings;
}

