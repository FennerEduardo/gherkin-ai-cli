const AUTOMATION_FILES = [
  '.gitlab-ci.yml', 'azure-pipelines.yml', 'bitbucket-pipelines.yml', 'Jenkinsfile', '.circleci/config.yml',
  'package.json', 'Makefile', 'Taskfile.yml', 'justfile'
];
const AUTOMATION_DIRS = ['.github/workflows', '.gitlab', '.azure-pipelines', 'scripts', 'ci'];

export function listAutomationFiles(cwd: string): string[] {
  const files = AUTOMATION_FILES.map(f => path.join(cwd, f)).filter(f => fs.existsSync(f));
  for (const dir of AUTOMATION_DIRS) {
    const full = path.join(cwd, dir);
    if (!fs.existsSync(full)) continue;
    for (const entry of fs.readdirSync(full, { withFileTypes: true })) {
      if (entry.isFile() && /\.(ya?ml|sh|ps1|groovy)$/i.test(entry.name)) files.push(path.join(full, entry.name));
    }
  }
  return files;
}

interface LineRule {
  id: string;
  severity: FindingSeverity;
  test: (line: string) => boolean;
  message: string;
  hint: string;
}

const CLI_INVOCATION = /\b(ghk|gherkin-ai|gherkin-cli)(@[\w.-]+)?\s/;

const LINE_RULES: LineRule[] = [
  {
    id: 'automation.login-flags',
    severity: 'required',
    test: l => /\blogin\b/.test(l) && /--(apiKey|token|user|endpoint|server)\b/.test(l),
    message: '`ghk login --apiKey/--token/--user/--endpoint/--server` were removed.',
    hint: 'Set the provider variable (OPENAI_API_KEY, AZURE_OPENAI_API_KEY, ...) or pipe the key to `ghk login --provider <name> --api-key-stdin`.'
  },
  {
    id: 'automation.auth-alias',
    severity: 'required',
    test: l => /\s(ghk|gherkin-ai|gherkin-cli)(@[\w.-]+)?\s+auth\b(?!\s+status)/.test(` ${l}`),
    message: '`ghk auth` is no longer an alias of `login`.',
    hint: 'Use `ghk login --provider <name>`, or `ghk auth status` to inspect credentials.'
  },
  {
    id: 'automation.converge-strict',
    severity: 'recommended',
    test: l => /\bconverge\b/.test(l) && /--strict\b/.test(l),
    message: '`converge --strict` is deprecated: the threshold is always enforced.',
    hint: 'Use `ghk converge --threshold <score>` (exit code 7 below it).'
  },
  {
    id: 'automation.unattended-apply',
    severity: 'required',
    test: l => /\b(autopilot|auto|verify|v-loop)\b/.test(l) && /--apply\b/.test(l) && !/--allow-unattended-writes\b/.test(l),
    message: '`--apply` is refused in CI unless unattended writes are allowed.',
    hint: 'Add --allow-unattended-writes (or policy.allowUnattendedWrites), or drop --apply and review the generated .patch files.'
  },
  {
    id: 'automation.autopilot-dry-run',
    severity: 'info',
    test: l => /\b(autopilot|auto)\b/.test(l) && !/--apply\b/.test(l),
    message: '`ghk autopilot` is now a dry run unless --apply is passed.',
    hint: 'Add --apply if this step is expected to write files.'
  },
  {
    id: 'automation.exit-code-1',
    severity: 'recommended',
    test: l => /(\$\?|\$LASTEXITCODE|exitCode|status)\s*(-eq|==|===)\s*1\b/.test(l),
    message: 'This line compares the CLI exit code against 1; v3 uses distinct codes (2 usage, 3 config, 4 gate, 5 policy, 6 provider, 7 drift).',
    hint: 'Check for non-zero, or for the specific code (see docs/ENTERPRISE.md).'
  }
];

const OLD_NODE = /(node-version|node_version|nodejs?[_-]?version)\s*[:=]\s*\[?\s*['"]?(1[4-9]|20|21)(\.[\dx]+)*['"]?|\bimage:\s*['"]?node:(1[4-9]|20|21)\b|\bnode:(1[4-9]|20|21)(-[\w.]+)?\b/;

export function scanAutomation(cwd: string, files = listAutomationFiles(cwd)): UpgradeFinding[] {
  const findings: UpgradeFinding[] = [];
  for (const file of files) {
    let text: string;
    try { text = fs.readFileSync(file, 'utf8'); } catch { continue; }
    if (!/\b(ghk|gherkin-ai|gherkin-cli)\b/.test(text)) continue;
    const rel = path.relative(cwd, file).split(path.sep).join('/');
    const lines = text.split(/\r?\n/);
    lines.forEach((line, i) => {
      if (OLD_NODE.test(line)) {
        findings.push({ id: 'automation.node-version', area: 'automation', severity: 'required', fix: 'manual', file: rel, line: i + 1, message: 'This pipeline runs gherkin-ai on Node.js < 22; v3 requires Node.js 22.12 or later.', hint: 'Use Node 22 or 24 (e.g. actions/setup-node with node-version: 22).' });
      }
      if (!CLI_INVOCATION.test(`${line} `)) return;
      for (const rule of LINE_RULES) {
        if (rule.test(line)) findings.push({ id: rule.id, area: 'automation', severity: rule.severity, fix: 'manual', file: rel, line: i + 1, message: rule.message, hint: rule.hint });
      }
    });
  }
  return findings;
}

