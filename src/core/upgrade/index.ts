export interface ConfigCheck {
  findings: UpgradeFinding[];
  /** The config with automatic fixes applied, when there is anything to fix. */
  fixed?: Record<string, unknown>;
}

export function checkProjectConfig(raw: unknown, file: string): ConfigCheck {
  const findings: UpgradeFinding[] = [];
  if (typeof raw !== 'object' || raw === null || Array.isArray(raw)) {
    findings.push({ id: 'config.invalid-json', area: 'config', severity: 'required', fix: 'manual', file, message: 'gherkin-ai.config.json must contain a JSON object.' });
    return { findings };
  }
  let config = raw as Record<string, unknown>;
  let changed = false;

  if (!('$schema' in config)) {
    // First key, so editors pick it up.
    config = { $schema: CONFIG_SCHEMA_ID, ...config };
    changed = true;
    findings.push({ id: 'config.schema-ref', area: 'config', severity: 'recommended', fix: 'auto', file, message: 'Add "$schema" so editors validate and autocomplete the config.' });
  }

  const known = new Set([...Object.keys(partialConfigSchema.shape), '$schema']);
  for (const key of Object.keys(config)) {
    if (!known.has(key)) {
      findings.push({ id: `config.unknown.${key}`, area: 'config', severity: 'recommended', fix: 'manual', file, message: `Unknown key "${key}" is ignored by v3.`, hint: 'Remove it or move it to the documented key (`ghk config schema`).' });
    }
  }

  const result = partialConfigSchema.safeParse(config);
  if (!result.success) {
    for (const issue of result.error.issues) {
      findings.push({ id: `config.invalid.${issue.path.join('.') || 'root'}`, area: 'config', severity: 'required', fix: 'manual', file, message: `${issue.path.join('.') || '(root)'}: ${issue.message}` });
    }
  }

  const llm = config.llm as Record<string, unknown> | undefined;
  if (typeof llm?.model === 'string' && /^(claude-(instant|2|3)|gpt-3\.5|gpt-4-(0314|0613|32k))/.test(llm.model)) {
    findings.push({ id: 'config.retired-model', area: 'config', severity: 'recommended', fix: 'manual', file, message: `llm.model "${llm.model}" is retired or about to be retired by its provider.`, hint: 'Remove it to use the default for the provider, or pin a current model.' });
  }

  const frontend = config.frontendStack as Record<string, unknown> | undefined;
  if (String(frontend?.framework ?? '').toLowerCase() === 'angular' && /ngrx(?!-?signals)/i.test(String(frontend?.stateManagement ?? ''))) {
    findings.push({ id: 'config.angular-ngrx-store', area: 'config', severity: 'info', fix: 'none', file, message: 'The classic NgRx store mode was removed; Angular projects are generated with NgRx Signals.' });
  }

  if (findings.every(f => f.severity === 'info')) {
    findings.push({ id: 'config.valid', area: 'config', severity: 'info', fix: 'none', file, message: 'The project configuration validates against the v3 schema.' });
  }
  return { findings, fixed: changed ? config : undefined };
}

