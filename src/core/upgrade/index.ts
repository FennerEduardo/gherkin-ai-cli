/** Compares semver strings; a prerelease sorts before its release (3.0.0-beta.1 < 3.0.0). */
export function compareVersions(a: string, b: string): number {
  const parse = (v: string) => {
    const [core, pre] = v.replace(/^v/, '').split('-', 2);
    return { nums: core.split('.').map(n => parseInt(n, 10) || 0), pre };
  };
  const x = parse(a);
  const y = parse(b);
  for (let i = 0; i < 3; i++) {
    const d = (x.nums[i] ?? 0) - (y.nums[i] ?? 0);
    if (d) return Math.sign(d);
  }
  if (x.pre === y.pre) return 0;
  if (!x.pre) return 1;
  if (!y.pre) return -1;
  return x.pre.localeCompare(y.pre, 'en', { numeric: true });
}

const majorOf = (v: string) => parseInt(v.replace(/^v/, ''), 10) || 0;

const GENERATED_HEADER = /Generated by gherkin-ai(?: CLI)? v(\d+\.\d+\.\d+(?:-[0-9A-Za-z.]+)?)/;
const SKIP_DIRS = new Set(['node_modules', '.git', 'dist', 'build', 'bin', 'obj', 'target', '_build', 'deps', 'vendor', '.dart_tool', '.next', 'coverage']);

export interface GeneratedVersionInfo {
  /** Oldest CLI version found in a generated header. */
  oldest?: string;
  newest?: string;
  /** Files carrying a header, relative to the scanned directory (posix separators). */
  files: string[];
}

/** Reads the "Generated by gherkin-ai CLI vX" headers under `dir` (first 4 KB of each file). */
export function detectGeneratedVersion(dir: string, maxFiles = 2000): GeneratedVersionInfo {
  const versions: string[] = [];
  const files: string[] = [];
  let seen = 0;
  const walk = (current: string) => {
    let entries: fs.Dirent[];
    try { entries = fs.readdirSync(current, { withFileTypes: true }); } catch { return; }
    for (const entry of entries) {
      if (seen >= maxFiles) return;
      const full = path.join(current, entry.name);
      if (entry.isDirectory()) {
        if (!SKIP_DIRS.has(entry.name)) walk(full);
        continue;
      }
      if (!entry.isFile()) continue;
      seen++;
      const version = readHeaderVersion(full);
      if (version) {
        versions.push(version);
        files.push(path.relative(dir, full).split(path.sep).join('/'));
      }
    }
  };
  if (fs.existsSync(dir)) walk(dir);
  const sorted = [...new Set(versions)].sort(compareVersions);
  return { oldest: sorted[0], newest: sorted[sorted.length - 1], files };
}

export function readHeaderVersion(file: string): string | undefined {
  let fd: number | undefined;
  try {
    fd = fs.openSync(file, 'r');
    const buf = Buffer.alloc(4096);
    const n = fs.readSync(fd, buf, 0, buf.length, 0);
    return GENERATED_HEADER.exec(buf.subarray(0, n).toString('utf8'))?.[1];
  } catch {
    return undefined;
  } finally {
    if (fd !== undefined) fs.closeSync(fd);
  }
}

export function generatedFindings(info: GeneratedVersionInfo, cliVersion: string, outputDir: string): UpgradeFinding[] {
  if (!info.oldest) {
    return [{ id: 'generated.none', area: 'generated', severity: 'info', fix: 'none', message: `No files generated by gherkin-ai were found in ${outputDir}.` }];
  }
  if (majorOf(info.oldest) < majorOf(cliVersion)) {
    return [{
      id: 'generated.regenerate',
      area: 'generated',
      severity: 'required',
      fix: 'auto',
      message: `${info.files.length} generated file(s) come from v${info.oldest}${info.newest !== info.oldest ? `–v${info.newest}` : ''}; v${cliVersion} generates complete, buildable projects with a different layout.`,
      hint: 'Regenerate on a separate branch and review the diff (`ghk upgrade --apply`).'
    }];
  }
  if (compareVersions(info.oldest, cliVersion) < 0) {
    return [{ id: 'generated.refresh', area: 'generated', severity: 'recommended', fix: 'auto', message: `Generated files come from v${info.oldest}; regenerating picks up fixes from v${cliVersion}.` }];
  }
  return [{ id: 'generated.current', area: 'generated', severity: 'info', fix: 'none', message: `Generated files are up to date (v${info.newest}).` }];
}

