import { ParsedFeature } from '../core/gherkin-parser';
import { GherkinAIConfig } from '../core/config';
import { getArchRule } from '../core/arch-rules';
import { getStackSpec } from '../core/stack-specs';
import { generatePythonContracts } from './contracts-python';
import { generatePhpContracts } from './contracts-php';
import { generateGoContracts } from './contracts-go';
import { generateCsharpContracts } from './contracts-csharp';

export interface GeneratedContractsOutput {
  contractsTs: string;
  adrMd: string;
  openApiJson: string;
  asyncApiJson: string;
  nativeContract?: {
    filename: string;
    content: string;
  };
}

export function generateContracts(parsed: ParsedFeature, config: GherkinAIConfig): GeneratedContractsOutput {
  const arch = getArchRule(config.architecture);
  const spec = getStackSpec(config.stack);
  const isCqrs = config.architecture === 'cqrs';

  const featurePascal = parsed.featureName.replace(/[^a-zA-Z0-9]/g, '');

  const cqrsSection = isCqrs ? `
// --------------------------------------------------------------------------
// CQRS + Event Sourcing Infrastructure Contracts
// --------------------------------------------------------------------------
export interface IAggregateRoot<T> {
  id: string;
  version: number;
  uncommittedEvents: IDomainEvent[];
  apply(event: IDomainEvent): void;
  clearUncommittedEvents(): void;
}

export interface IEventStore {
  saveEvents(aggregateId: string, events: IDomainEvent[], expectedVersion: number): Promise<void>;
  getEventsForAggregate(aggregateId: string): Promise<IDomainEvent[]>;
}

export interface ISnapshotStore<T> {
  getSnapshot(aggregateId: string): Promise<{ version: number; state: T } | null>;
  saveSnapshot(aggregateId: string, version: number, state: T): Promise<void>;
}
` : '';

  const contractsTs = `/* ==========================================================================
   Generated Domain Contracts & DTO Schemas
   Feature: ${parsed.featureName}
   Architecture: ${arch.name}
   Stack: ${config.stack.language} + ${config.stack.framework} + ${config.stack.orm}
   Generated by gherkin-ai CLI v1.5.0
   ========================================================================== */

import { z } from '${spec.validationPackage.split('@')[0]}';

// --------------------------------------------------------------------------
// 1. Domain Event Interfaces
// --------------------------------------------------------------------------
export interface IDomainEvent {
  eventId: string;
  occurredOn: Date;
  eventType: string;
}

${parsed.domainAnalysis.events.map((ev, i) => `export interface Event${i + 1} extends IDomainEvent {
  eventType: '${ev.replace(/[^a-zA-Z0-9]/g, '')}';
  payload: Record<string, unknown>;
}`).join('\n\n')}

// --------------------------------------------------------------------------
// 2. Command DTO Schemas (Zod Validation)
// --------------------------------------------------------------------------
export const ${featurePascal}CommandSchema = z.object({
  requestId: z.string().uuid(),
  timestamp: z.string().datetime(),
  payload: z.object({
${parsed.domainAnalysis.fields.map(f => {
  let zType = f.type === 'number' ? 'z.number()' : 'z.string()';
  f.validations.forEach(v => {
    if (v === '@validate:email') zType += '.email()';
    if (v.startsWith('@range(')) {
       const match = v.match(/@range\((\d+),(\d+)\)/);
       if (match) zType += `.min(${match[1]}).max(${match[2]})`;
    }
  });
  return `    ${f.name}: ${zType}`;
}).join(',\n')}
  })
});

export type ${featurePascal}Command = z.infer<typeof ${featurePascal}CommandSchema>;

// --------------------------------------------------------------------------
// 3. Domain Repository Port (Outbound Interface)
// --------------------------------------------------------------------------
export interface I${featurePascal}Repository {
  findById(id: string): Promise<unknown | null>;
  save(entity: unknown): Promise<void>;
  delete(id: string): Promise<void>;
}

// --------------------------------------------------------------------------
// 4. Application Event Publisher Port
// --------------------------------------------------------------------------
export interface IEventPublisher {
  publish(event: IDomainEvent): Promise<void>;
}
${cqrsSection}`;

  const adrMd = `# ADR 001: Architecture Decisions for ${parsed.featureName}

## Status
Accepted

## Context
Project requiring structured implementation matching Gherkin specification.

## Decisions
- **Architecture Style**: ${arch.name} (${arch.id})
- **Primary Language**: ${config.stack.language}
- **Framework**: ${config.stack.framework} (${spec.frameworkVersion})
- **ORM / Persistence**: ${config.stack.orm} (${spec.ormPackage})
- **Validation**: ${config.stack.validation} (${spec.validationPackage})
- **Authentication**: ${config.stack.auth} (bcrypt cost factor ${spec.bcryptCostFactor}, JWT TTL ${spec.jwtTtlSeconds}s)
- **Testing Framework**: ${config.stack.testing} (${spec.testPackages.join(', ')})

## Prohibited Layer Dependencies
Domain core must NOT import:
${arch.prohibitedImports.map(p => `- \`${p}\``).join('\n')}
`;

  const openApiJson = JSON.stringify({
    openapi: '3.0.3',
    info: {
      title: `${parsed.featureName} API Specification`,
      version: '1.0.0',
      description: `Auto-generated OpenAPI specification for ${parsed.featureName} from Gherkin feature spec.`
    },
    paths: {
      [`/api/v1/${featurePascal.toLowerCase()}`]: {
        post: {
          summary: `Execute ${parsed.featureName} Command`,
          operationId: `execute${featurePascal}`,
          requestBody: {
            required: true,
            content: {
              'application/json': {
                schema: {
                  type: 'object',
                  properties: {
                    requestId: { type: 'string', format: 'uuid' },
                    timestamp: { type: 'string', format: 'date-time' },
                    payload: { type: 'object' }
                  },
                  required: ['requestId', 'timestamp', 'payload']
                }
              }
            }
          },
          responses: {
            '200': { description: 'Successful execution' },
            '400': { description: 'Validation error' },
            '401': { description: 'Unauthorized' }
          }
        }
      }
    }
  }, null, 2);

  const asyncApiJson = JSON.stringify({
    asyncapi: '2.6.0',
    info: {
      title: `${parsed.featureName} AsyncAPI Specification`,
      version: '1.0.0',
      description: `Auto-generated AsyncAPI events for ${parsed.featureName} from Gherkin feature spec.`
    },
    channels: parsed.domainAnalysis.events.reduce((acc, ev) => {
      const eventName = ev.replace(/[^a-zA-Z0-9]/g, '');
      acc[`${featurePascal.toLowerCase()}/events/${eventName.toLowerCase()}`] = {
        publish: {
          summary: `Publish ${eventName} event`,
          message: {
            name: eventName,
            payload: {
              type: 'object',
              properties: {
                eventId: { type: 'string', format: 'uuid' },
                occurredOn: { type: 'string', format: 'date-time' },
                eventType: { type: 'string', enum: [eventName] },
                payload: { type: 'object' }
              }
            }
          }
        }
      };
      return acc;
    }, {} as Record<string, any>)
  }, null, 2);

  // Generate Native Contract file based on target stack language
  let nativeContract: GeneratedContractsOutput['nativeContract'];

  if (config.stack.language === 'python') {
    nativeContract = {
      filename: `${featurePascal.toLowerCase()}.contract.py`,
      content: generatePythonContracts(parsed, config)
    };
  } else if (config.stack.language === 'php') {
    nativeContract = {
      filename: `${featurePascal.toLowerCase()}.contract.php`,
      content: generatePhpContracts(parsed, config)
    };
  } else if (config.stack.language === 'go') {
    nativeContract = {
      filename: `${featurePascal.toLowerCase()}.contract.go`,
      content: generateGoContracts(parsed, config)
    };
  } else if (config.stack.language === 'csharp') {
    nativeContract = {
      filename: `${featurePascal.toLowerCase()}.contract.cs`,
      content: generateCsharpContracts(parsed, config)
    };
  }

  return { contractsTs, adrMd, openApiJson, asyncApiJson, nativeContract };
}
