import { CLI_VERSION } from '../version';
import { ParsedFeature } from '../core/gherkin-parser';
import { GherkinAIConfig } from '../core/config';
import { SpecificationIR } from '../core/semantic-ir';
import { featurePascalName } from '../utils/naming';

export function generateGoContracts(parsed: ParsedFeature, ir: SpecificationIR, config: GherkinAIConfig): string {
  const featurePascal = featurePascalName(parsed);

  return `/* ==========================================================================
   Generated Domain Contracts & Go Structs
   Feature: ${parsed.featureName}
   Stack: Go + ${config.stack.framework} + ${config.stack.orm}
   Generated by gherkin-ai CLI v${CLI_VERSION}
   ========================================================================== */

package contracts

import (
	"context"
	"time"
${ir.events.length ? '\n\t"github.com/google/uuid"\n' : ''})

// The shared ports (IDomainEvent, IEventPublisher) are in ports.go: every feature of the service uses them.

// --------------------------------------------------------------------------
// 1. Domain Events
// --------------------------------------------------------------------------
${ir.events.map((ev, i) => `type ${featurePascal}Event${i + 1} struct {
	EventID    uuid.UUID              \`json:"eventId"\`
	OccurredOn time.Time              \`json:"occurredOn"\`
	EventType  string                 \`json:"eventType"\`
	Payload    map[string]interface{} \`json:"payload"\`
}

func (e ${featurePascal}Event${i + 1}) GetEventID() string       { return e.EventID.String() }
func (e ${featurePascal}Event${i + 1}) GetOccurredOn() time.Time { return e.OccurredOn }
func (e ${featurePascal}Event${i + 1}) GetEventType() string    { return "${ev.name.replace(/[^a-zA-Z0-9]/g, '')}" }`).join('\n\n')}

// --------------------------------------------------------------------------
// 2. Command DTO Struct
// --------------------------------------------------------------------------
type ${featurePascal}Command struct {
	RequestID string                 \`json:"request_id" validate:"required,uuid"\`
	Timestamp time.Time              \`json:"timestamp" validate:"required"\`
	Payload   map[string]interface{} \`json:"payload" validate:"required"\`
}

// --------------------------------------------------------------------------
// 3. Domain Repository Port
// --------------------------------------------------------------------------
type I${featurePascal}Repository interface {
	FindByID(ctx context.Context, id string) (interface{}, error)
	Save(ctx context.Context, entity interface{}) error
	Delete(ctx context.Context, id string) error
}
`;
}

