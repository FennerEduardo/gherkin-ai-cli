/** One route file per feature: the commands it exposes and the upstream that owns them. */
function renderRouteFile(m: DomainModel, upstream: string): string {
  return `// Generated by gherkin-ai: the BFF route of the "${m.feature}" feature.
export const ${m.camel}Route = {
  feature: '${m.kebab}',
  /** bff.upstreams entry that owns these commands (@upstream:<name> on the feature). */
  upstream: '${upstream}',
  commands: [${m.commands.map(c => `'${c.snake}'`).join(', ')}] as readonly string[]
};
`;
}

function renderUpstreamClient(config: GherkinAIConfig): string {
  const upstreams = bffUpstreams(config);
  return `// Generated by gherkin-ai: HTTP client to the domain services (docs: stack.role "bff").
import { randomUUID } from 'node:crypto';

export interface Forwarded {
  status: number;
  body: unknown;
  requestId: string;
}

/** Headers the BFF passes on: the caller's identity, trace context and idempotency. */
const FORWARDED = ['authorization', 'traceparent', 'tracestate', 'idempotency-key', 'x-request-id', 'accept-language'];

export class UpstreamClient {
  constructor(
    readonly name: string,
    private readonly baseUrl: string,
    private readonly timeoutMs = ${bffTimeout(config)},
    private readonly fetchImpl: typeof fetch = fetch
  ) {}

  async post(path: string, body: unknown, incoming: Record<string, string | string[] | undefined>): Promise<Forwarded> {
    const headers: Record<string, string> = { 'content-type': 'application/json', accept: 'application/json' };
    for (const name of FORWARDED) {
      const value = incoming[name];
      if (typeof value === 'string' && value) headers[name] = value;
    }
    const requestId = headers['x-request-id'] ?? randomUUID();
    headers['x-request-id'] = requestId;
    let res: Response;
    try {
      res = await this.fetchImpl(\`\${this.baseUrl.replace(/\\/+$/, '')}\${path}\`, {
        method: 'POST', headers, body: JSON.stringify(body ?? {}), signal: AbortSignal.timeout(this.timeoutMs)
      });
    } catch (err) {
      const timedOut = (err as Error).name === 'TimeoutError' || (err as Error).name === 'AbortError';
      return { status: timedOut ? 504 : 502, body: { detail: \`\${this.name} \${timedOut ? 'did not answer in time' : 'is unavailable'}\` }, requestId };
    }
    const text = await res.text();
    let parsed: unknown = {};
    try { parsed = text ? JSON.parse(text) : {}; } catch { parsed = { detail: text }; }
    // A failure inside the service is not the client's to handle: 502 without its internals.
    if (res.status >= 500) return { status: 502, body: { detail: \`\${this.name} failed (\${res.status})\` }, requestId };
    return { status: res.status, body: parsed, requestId };
  }
}

export type Upstreams = Record<string, UpstreamClient>;

/** One client per bff.upstreams entry, at the URL in its environment variable. */
export function upstreamsFromEnv(env: NodeJS.ProcessEnv = process.env): Upstreams {
  return {
${upstreams.map(u => `    '${u.name}': new UpstreamClient('${u.name}', env.${u.envVar} ?? '${u.url}'),`).join('\n')}
  };
}
`;
}

/** The handler both frameworks call: auth presence, command check, forwarding. */
function renderGateway(ext: string): string {
  return `// Generated by gherkin-ai: one BFF route forwarded to its upstream.
import type { Upstreams } from './upstream-client${ext}';

export interface BffRoute {
  feature: string;
  upstream: string;
  commands: readonly string[];
}

export interface GatewayAnswer {
  status: number;
  body: unknown;
  requestId?: string;
}

export async function forward(route: BffRoute, upstreams: Upstreams, id: string, command: string, body: unknown,
  headers: Record<string, string | string[] | undefined>): Promise<GatewayAnswer> {
  if (!route.commands.includes(command)) return { status: 404, body: { detail: \`Unknown command \${command}\` } };
  // The service validates the token; the BFF never forwards an anonymous call.
  if (typeof headers.authorization !== 'string' || !/^Bearer\\s+\\S+/i.test(headers.authorization)) {
    return { status: 401, body: { detail: 'Missing bearer token' } };
  }
  const client = upstreams[route.upstream];
  if (!client) return { status: 502, body: { detail: \`No upstream "\${route.upstream}" configured\` } };
  return client.post(\`/api/v1/\${route.feature}/\${encodeURIComponent(id)}/\${command}\`, body, headers);
}
`;
}

/** Tests against a stub upstream (a local HTTP server), for any framework that exposes an HTTP server. */
function renderAppSpec(m: DomainModel, appImport: string, makeServer: string, ext: string): string {
  const command = m.commands[0].snake;
  return `// Generated by gherkin-ai: the BFF against a stub upstream.
import http from 'node:http';
import type { AddressInfo } from 'node:net';
import request from 'supertest';
import { UpstreamClient } from './upstream/upstream-client${ext}';
${appImport}

interface Seen { url?: string; headers: http.IncomingHttpHeaders; body: string }

function stubUpstream(status: number, body: unknown, delayMs = 0) {
  const seen: Seen[] = [];
  const server = http.createServer((req, res) => {
    let raw = '';
    req.on('data', c => (raw += c));
    req.on('end', () => {
      seen.push({ url: req.url, headers: req.headers, body: raw });
      setTimeout(() => { res.writeHead(status, { 'content-type': 'application/json' }); res.end(JSON.stringify(body)); }, delayMs);
    });
  });
  return new Promise<{ url: string; seen: Seen[]; close: () => Promise<void> }>(resolve => server.listen(0, '127.0.0.1', () => {
    const { port } = server.address() as AddressInfo;
    resolve({ url: \`http://127.0.0.1:\${port}\`, seen, close: () => new Promise(r => { server.closeAllConnections(); server.close(() => r()); }) });
  }));
}

describe('${m.pascal} BFF', () => {
  const path = '${bffRoute(m)}/agg-1/${command}';

  it('forwards the command to the service with the caller identity and trace context', async () => {
    const upstream = await stubUpstream(202, { aggregateId: 'agg-1', version: 1 });
    try {
      const server = ${makeServer}({ '${'__UPSTREAM__'}': new UpstreamClient('${'__UPSTREAM__'}', upstream.url) });
      const res = await request(server).post(path)
        .set('Authorization', 'Bearer token-1')
        .set('traceparent', '00-0af7651916cd43dd8448eb211c80319c-b7ad6b7169203331-01')
        .set('Idempotency-Key', 'key-1')
        .send({ source: 'bff-test' });
      expect(res.status).toBe(202);
      expect(res.body).toEqual({ aggregateId: 'agg-1', version: 1 });
      expect(upstream.seen[0].url).toBe('${upstreamRoute(m)}/agg-1/${command}');
      expect(upstream.seen[0].headers.authorization).toBe('Bearer token-1');
      expect(upstream.seen[0].headers.traceparent).toBe('00-0af7651916cd43dd8448eb211c80319c-b7ad6b7169203331-01');
      expect(upstream.seen[0].headers['idempotency-key']).toBe('key-1');
      expect(upstream.seen[0].headers['x-request-id']).toBeTruthy();
      expect(JSON.parse(upstream.seen[0].body)).toEqual({ source: 'bff-test' });
    } finally {
      await upstream.close();
    }
  });

  it('refuses a call without a bearer token, before reaching the service', async () => {
    const upstream = await stubUpstream(202, {});
    try {
      const res = await request(${makeServer}({ '__UPSTREAM__': new UpstreamClient('__UPSTREAM__', upstream.url) })).post(path).send({});
      expect(res.status).toBe(401);
      expect(upstream.seen).toHaveLength(0);
    } finally {
      await upstream.close();
    }
  });

  it('answers 404 for a command the feature does not declare', async () => {
    const res = await request(${makeServer}({ '__UPSTREAM__': new UpstreamClient('__UPSTREAM__', 'http://127.0.0.1:9') }))
      .post('${bffRoute(m)}/agg-1/not_a_command').set('Authorization', 'Bearer t').send({});
    expect(res.status).toBe(404);
  });

  it('passes a 4xx through and turns a 5xx into 502', async () => {
    const invalid = await stubUpstream(422, { detail: 'Command id is required' });
    const broken = await stubUpstream(500, { stack: 'internal' });
    try {
      const r422 = await request(${makeServer}({ '__UPSTREAM__': new UpstreamClient('__UPSTREAM__', invalid.url) })).post(path).set('Authorization', 'Bearer t').send({});
      expect(r422.status).toBe(422);
      expect(r422.body).toEqual({ detail: 'Command id is required' });
      const r500 = await request(${makeServer}({ '__UPSTREAM__': new UpstreamClient('__UPSTREAM__', broken.url) })).post(path).set('Authorization', 'Bearer t').send({});
      expect(r500.status).toBe(502);
      expect(JSON.stringify(r500.body)).not.toContain('internal');
    } finally {
      await invalid.close();
      await broken.close();
    }
  });

  it('answers 504 when the service does not answer in time, and 502 when it is down', async () => {
    const slow = await stubUpstream(202, {}, 500);
    try {
      const r504 = await request(${makeServer}({ '__UPSTREAM__': new UpstreamClient('__UPSTREAM__', slow.url, 100) })).post(path).set('Authorization', 'Bearer t').send({});
      expect(r504.status).toBe(504);
    } finally {
      await slow.close();
    }
    const r502 = await request(${makeServer}({ '__UPSTREAM__': new UpstreamClient('__UPSTREAM__', 'http://127.0.0.1:9') })).post(path).set('Authorization', 'Bearer t').send({});
    expect(r502.status).toBe(502);
  });

  it('reports its health without calling the services', async () => {
    const res = await request(${makeServer}({})).get('/health');
    expect(res.status).toBe(200);
  });
});
`;
}

function packageJson(config: GherkinAIConfig, framework: 'express' | 'nestjs', esm: boolean): string {
  const nest = framework === 'nestjs' ? NEST_DEPENDENCIES[resolveNodeProfile(config).nest] : {};
  return JSON.stringify({
    name: (config.projectName || 'bff').toLowerCase().replace(/[^a-z0-9-]/g, '-'),
    private: true,
    version: '0.1.0',
    ...(esm ? { type: 'module' } : {}),
    scripts: {
      start: esm ? 'node dist/src/main.js' : `node dist/src/${framework === 'nestjs' ? 'main' : 'server'}`,
      build: 'tsc -p tsconfig.build.json',
      test: esm ? 'node --experimental-vm-modules node_modules/jest/bin/jest.js' : 'jest'
    },
    dependencies: framework === 'nestjs'
      ? { ...nest, 'reflect-metadata': '^0.2.0', rxjs: '^7.8.0', zod: '^4.1.0' }
      : { express: '^5.1.0', zod: '^4.1.0' },
    devDependencies: TEST_TOOLING
  }, null, 2) + '\n';
}

export function renderTsBff(parsed: ParsedFeature, config: GherkinAIConfig, framework: 'express' | 'nestjs'): File[] {
  const m = buildDomainModel(parsed, { service: config.projectName });
  const upstream = featureUpstream(parsed, config).name;
  const esm = framework === 'nestjs' && resolveNodeProfile(config).esm;
  const ext = esm ? '.js' : '';
  const routeFile = (x: DomainModel) => `src/routes/${x.kebab}.route.ts`;
  const all = [...siblingDomainModels(m, config, routeFile), m].sort((a, b) => a.pascal.localeCompare(b.pascal));
  const spec = (appImport: string, makeServer: string) => renderAppSpec(m, appImport, makeServer, ext).replace(/__UPSTREAM__/g, upstream);

  const common: File[] = [
    { filename: 'package.json', content: packageJson(config, framework, esm) },
    { filename: routeFile(m), content: renderRouteFile(m, upstream) },
    { filename: 'src/upstream/upstream-client.ts', content: renderUpstreamClient(config) },
    { filename: 'src/upstream/gateway.ts', content: renderGateway(ext) },
    { filename: 'jest.config.js', content: renderJestConfig(['<rootDir>/src'], { esm }) },
    ...renderTsConfigs()
  ];
  const routes = all.map(x => `import { ${x.camel}Route } from './routes/${x.kebab}.route${ext}';`).join('\n');

  if (framework === 'express') {
    return [
      ...common,
      {
        filename: 'src/app.ts',
        content: `// Generated by gherkin-ai: the BFF for every feature of the project (stack.role "bff").
import express from 'express';
import { forward } from './upstream/gateway';
import { upstreamsFromEnv, type Upstreams } from './upstream/upstream-client';
${routes}

export const ROUTES = [${all.map(x => `${x.camel}Route`).join(', ')}];

export function createApp(upstreams: Upstreams = upstreamsFromEnv()) {
  const app = express();
  app.use(express.json());
  app.get('/health', (_req, res) => { res.json({ status: 'UP' }); });
  for (const route of ROUTES) {
    app.post(\`/bff/v1/\${route.feature}/:id/:command\`, async (req, res) => {
      const answer = await forward(route, upstreams, req.params.id, req.params.command, req.body, req.headers);
      if (answer.requestId) res.set('x-request-id', answer.requestId);
      res.status(answer.status).json(answer.body);
    });
  }
  return app;
}
`
      },
      {
        filename: 'src/server.ts',
        content: `import { createApp } from './app';

const port = Number(process.env.PORT ?? 3000);
createApp().listen(port, () => console.log(\`BFF listening on \${port}\`));
`
      },
      { filename: 'src/app.spec.ts', content: spec(`import { createApp } from './app';`, 'createApp') }
    ];
  }

  return [
    ...common,
    {
      filename: `src/routes/${m.kebab}.controller.ts`,
      content: `// Generated by gherkin-ai: the BFF controller of the "${m.feature}" feature.
import { Body, Controller, Headers, Inject, Param, Post, Res } from '@nestjs/common';
import type { Response } from 'express';
import { forward } from '../upstream/gateway${ext}';
import type { Upstreams } from '../upstream/upstream-client${ext}';
import { UPSTREAMS } from '../upstream/tokens${ext}';
import { ${m.camel}Route } from './${m.kebab}.route${ext}';

@Controller('${bffRoute(m).slice(1)}')
export class ${m.pascal}BffController {
  constructor(@Inject(UPSTREAMS) private readonly upstreams: Upstreams) {}

  @Post(':id/:command')
  async run(@Param('id') id: string, @Param('command') command: string, @Body() body: unknown,
    @Headers() headers: Record<string, string>, @Res() res: Response): Promise<void> {
    const answer = await forward(${m.camel}Route, this.upstreams, id, command, body, headers);
    if (answer.requestId) res.set('x-request-id', answer.requestId);
    res.status(answer.status).json(answer.body);
  }
}
`
    },
    { filename: 'src/upstream/tokens.ts', content: `export const UPSTREAMS = Symbol('UPSTREAMS');\n` },
    {
      filename: 'src/app.module.ts',
      content: `// Generated by gherkin-ai: the BFF module for every feature of the project (stack.role "bff").
import 'reflect-metadata';
import { Controller, Get, Module, type DynamicModule } from '@nestjs/common';
import { UPSTREAMS } from './upstream/tokens${ext}';
import { upstreamsFromEnv, type Upstreams } from './upstream/upstream-client${ext}';
${all.map(x => `import { ${x.pascal}BffController } from './routes/${x.kebab}.controller${ext}';`).join('\n')}

@Controller('health')
export class HealthController {
  @Get()
  health() { return { status: 'UP' }; }
}

@Module({})
export class AppModule {
  static register(upstreams: Upstreams = upstreamsFromEnv()): DynamicModule {
    return {
      module: AppModule,
      controllers: [HealthController, ${all.map(x => `${x.pascal}BffController`).join(', ')}],
      providers: [{ provide: UPSTREAMS, useValue: upstreams }]
    };
  }
}
`
    },
    {
      filename: 'src/main.ts',
      content: `import 'reflect-metadata';
import { NestFactory } from '@nestjs/core';
import { AppModule } from './app.module${ext}';

async function bootstrap() {
  const app = await NestFactory.create(AppModule.register());
  await app.listen(Number(process.env.PORT ?? 3000));
}
void bootstrap();
`
    },
    {
      filename: 'src/app.spec.ts',
      content: spec(`import { NestFactory } from '@nestjs/core';
import { AppModule } from './app.module${ext}';
import type { Upstreams } from './upstream/upstream-client${ext}';

const servers: { close(): Promise<void> }[] = [];
afterAll(async () => { for (const s of servers) await s.close(); });

/** A Nest application serving the BFF with these upstreams (supertest takes its HTTP server). */
async function nestServer(upstreams: Upstreams) {
  const app = await NestFactory.create(AppModule.register(upstreams), { logger: false });
  await app.init();
  servers.push(app);
  return app.getHttpServer();
}`, 'await nestServer')
    }
  ];
}
