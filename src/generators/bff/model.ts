/* ==========================================================================
   gherkin-ai-cli - Backend-for-frontend (stack.role: "bff")

   A BFF owns no data and publishes no events (LMS limitations 19 and 24):
   no runtime kernel, database, outbox or aggregate. Each feature's commands
   are exposed to the client as
     POST /bff/v1/<feature>/{id}/{command}
   and forwarded to the domain service that owns them, at the route of the
   gherkin-ai runtime kernel
     POST /api/v1/<feature>/{id}/{command}
   The caller's Authorization, W3C trace context, Idempotency-Key and
   X-Request-Id travel with the request; the service validates the token.

     401  no bearer token (never forwarded anonymously)
     404  a command the feature does not declare
     4xx  the service's answer, as it came
     502  the service failed (5xx) or could not be reached
     504  the service did not answer within bff.timeoutMs
   ========================================================================== */

import type { GherkinAIConfig } from '../../core/config';
import { ConfigError } from '../../core/errors';
import type { ParsedFeature } from '../../core/gherkin-parser';
import type { DomainModel } from '../kernel/domain-model';

export interface BffUpstream {
  /** Name used by @upstream:<name> (kebab-case). */
  name: string;
  /** Environment variable that holds its base URL. */
  envVar: string;
  /** URL for docker-compose / .env.example. */
  url: string;
}

export const DEFAULT_UPSTREAM = 'backend';
export const DEFAULT_BFF_TIMEOUT_MS = 10000;

export const isBff = (config?: Pick<GherkinAIConfig, 'stack'>) => config?.stack?.role === 'bff';

export const bffRoute = (m: DomainModel) => `/bff/v1/${m.kebab}`;
export const upstreamRoute = (m: DomainModel) => `/api/v1/${m.kebab}`;

/** The configured upstreams, or one named "backend" (BACKEND_URL) when none is. */
export function bffUpstreams(config?: Pick<GherkinAIConfig, 'bff'>): BffUpstream[] {
  const entries = Object.entries(config?.bff?.upstreams ?? {});
  const list = entries.length ? entries : [[DEFAULT_UPSTREAM, {}] as const];
  return list.map(([name, u]) => {
    const envVar = (u as { urlEnv?: string }).urlEnv ?? `${name.toUpperCase().replace(/-/g, '_')}_URL`;
    return { name, envVar, url: (u as { url?: string }).url ?? `http://${name}:8080` };
  });
}

/** The upstream a feature calls: its @upstream:<name> tag, else the first one. */
export function featureUpstream(parsed: Pick<ParsedFeature, 'tags'>, config?: Pick<GherkinAIConfig, 'bff'>): BffUpstream {
  const upstreams = bffUpstreams(config);
  const tag = (parsed.tags ?? []).map(t => t.replace(/^@/, '')).find(t => t.startsWith('upstream:'))?.slice('upstream:'.length);
  if (!tag) return upstreams[0];
  const found = upstreams.find(u => u.name === tag);
  if (!found) {
    throw new ConfigError(`@upstream:${tag} is not in bff.upstreams.`, { hint: `Declared upstreams: ${upstreams.map(u => u.name).join(', ')}. Add "${tag}" to bff.upstreams in gherkin-ai.config.json.` });
  }
  return found;
}

export const bffTimeout = (config?: Pick<GherkinAIConfig, 'bff'>) => config?.bff?.timeoutMs ?? DEFAULT_BFF_TIMEOUT_MS;

/** The frameworks the BFF role generates code for. */
export function bffFramework(config: Pick<GherkinAIConfig, 'stack'>): 'express' | 'nestjs' | 'spring' | undefined {
  const language = config.stack.language.toLowerCase();
  const framework = (config.stack.framework || '').toLowerCase();
  if ((language === 'typescript' || language === 'javascript') && framework === 'express') return 'express';
  if ((language === 'typescript' || language === 'javascript') && (framework === 'nestjs' || framework === 'nest')) return 'nestjs';
  if (language === 'java' && (framework === '' || framework === 'default' || framework.startsWith('spring'))) return 'spring';
  return undefined;
}

/** docker-compose.yml and .env.example of a BFF: its image and the URLs of the services it calls. */
export function renderBffInfra(config: Pick<GherkinAIConfig, 'projectName' | 'stack' | 'bff'>): { compose: string; env: string } {
  const upstreams = bffUpstreams(config);
  const java = config.stack.language.toLowerCase() === 'java';
  const port = java ? 8080 : 3000;
  const name = (config.projectName || 'bff').toLowerCase().replace(/[^a-z0-9-]/g, '-');
  const vars = [
    ...(java ? [['SERVER_PORT', String(port)]] : [['PORT', String(port)]]),
    ...upstreams.map(u => [u.envVar, u.url]),
    ['OTEL_EXPORTER_OTLP_ENDPOINT', '']
  ];
  const compose = `# Generated by gherkin-ai: the backend-for-frontend (stack.role "bff").
# It owns no data: point the URLs below at the domain services (their compose files run them).
services:
  ${name}:
    build: .
    ports:
      - "${port}:${port}"
    environment:
${vars.map(([k, v]) => `      ${k}: \${${k}:-${v}}`).join('\n')}
`;
  const env = `# Backend-for-frontend (stack.role "bff"): no database or broker.
${vars.map(([k, v]) => `${k}=${v}`).join('\n')}
`;
  return { compose, env };
}
