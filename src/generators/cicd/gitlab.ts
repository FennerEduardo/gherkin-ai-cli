/* ==========================================================================
   gherkin-ai-cli - GitLab CI

   Stages: gates (ghk lint / validate / risk on merge requests / converge
   report), test (build, tests and the runtime integration suite in the
   stack's toolchain image with PostgreSQL and RabbitMQ services), image
   (production image built with Docker-in-Docker and pushed to the project
   registry on the default branch) and scan (Trivy on the dependencies,
   CycloneDX SBOM). Deployment is done by the generated Terraform / Helm
   with your organization's GitLab-to-cloud identity federation.
   Verified by scripts/golden-build.js (ci-gitlab) against the gitlab-ci schema.
   ========================================================================== */

import { CI_INTEGRATION_ENV, CI_SERVICES, DOCKER_IMAGE, PipelineSpec, TRIVY_IMAGE } from './pipeline-spec';

const q = (s: string) => JSON.stringify(s);
const lines = (commands: string[], n: number) => commands.map(c => `${' '.repeat(n)}- ${q(c)}`).join('\n');

export function renderGitLabCi(spec: PipelineSpec): { filename: string; content: string } {
  const t = spec.backend;
  const integration = t?.integration ?? [];
  const env = CI_INTEGRATION_ENV({ postgres: 'postgres', rabbitmq: 'rabbitmq' });
  const cd = spec.workdir === '.' ? [] : [`cd ${spec.workdir}`];

  const backend = t ? `
backend:
  stage: test
  image: ${t.image}${integration.length ? `
  services:
    - name: ${CI_SERVICES.postgres.image}
      alias: postgres
      variables:
        POSTGRES_PASSWORD: ${CI_SERVICES.postgres.env.POSTGRES_PASSWORD}
    - name: ${CI_SERVICES.rabbitmq.image}
      alias: rabbitmq
      variables:
        RABBITMQ_DEFAULT_USER: ${CI_SERVICES.rabbitmq.env.RABBITMQ_DEFAULT_USER}
        RABBITMQ_DEFAULT_PASS: ${CI_SERVICES.rabbitmq.env.RABBITMQ_DEFAULT_PASS}` : ''}${t.env ? `
  variables:
${Object.entries(t.env).map(([k, v]) => `    ${k}: ${q(v)}`).join('\n')}` : ''}
  script:
${lines([...cd, ...t.build, ...t.test], 4)}${integration.length ? `
    # Runtime integration suite (IT1-IT7 and the HTTP API): only this step sees the services.
${lines([...Object.entries(env).map(([k, v]) => `export ${k}=${v}`), ...integration], 4)}` : ''}
` : '';

  const frontend = spec.frontend ? `
frontend:
  stage: test
  image: node:24-bookworm
  script:
${lines([`cd ${spec.frontend.dir}`, 'npm install --no-audit --no-fund --loglevel=error', 'npm run build', 'npm test'], 4)}
` : '';

  const image = spec.image ? `
build-image:
  stage: image
  image: ${DOCKER_IMAGE}
  services:
    - ${DOCKER_IMAGE}-dind
  variables:
    DOCKER_TLS_CERTDIR: "/certs"
    IMAGE: "$CI_REGISTRY_IMAGE/${spec.name}:$CI_COMMIT_SHA"
  script:
    - docker build -t "$IMAGE" ${q(spec.workdir)}
    - |
      if [ "$CI_COMMIT_BRANCH" = "$CI_DEFAULT_BRANCH" ]; then
        echo "$CI_REGISTRY_PASSWORD" | docker login -u "$CI_REGISTRY_USER" --password-stdin "$CI_REGISTRY"
        docker push "$IMAGE"
      fi

scan:
  stage: scan
  image:
    name: ${TRIVY_IMAGE}
    entrypoint: [""]
  script:
    - trivy fs --exit-code 1 --severity HIGH,CRITICAL --ignore-unfixed ${q(spec.workdir)}
    - trivy fs --format cyclonedx --output sbom.cdx.json ${q(spec.workdir)}
  artifacts:
    paths:
      - sbom.cdx.json
` : '';

  const content = `# ${spec.name} CI, generated by gherkin-ai ${spec.ghkVersion}.${spec.deploy ? `
# Deployment code: ${spec.workdir === '.' ? '' : `${spec.workdir}/`}deploy/ (see deploy/README.md); run it from a protected job with your
# GitLab OIDC (id_tokens) federation to ${spec.deploy.cloud}.` : ''}
stages:
  - gates
  - test
  - image
  - scan

variables:
  # Pinned on purpose: a quality gate must not change behavior when a new version is published.
  GHK_VERSION: ${q(spec.ghkVersion)}
  GHK_NON_INTERACTIVE: "true"

workflow:
  rules:
    - if: $CI_PIPELINE_SOURCE == "merge_request_event"
    - if: $CI_COMMIT_BRANCH && $CI_OPEN_MERGE_REQUESTS
      when: never
    - if: $CI_COMMIT_BRANCH

spec-gates:
  stage: gates
  image: node:24-bookworm
  variables:
    GIT_DEPTH: "0"
  script:
    # Lint findings in the merge request Code Quality widget; scores and delivery risk in the job log.
    - |
      if [ -n "$CI_MERGE_REQUEST_TARGET_BRANCH_NAME" ]; then
        git fetch origin "$CI_MERGE_REQUEST_TARGET_BRANCH_NAME"
        npx --yes "gherkin-ai@$GHK_VERSION" report --provider gitlab --base "origin/$CI_MERGE_REQUEST_TARGET_BRANCH_NAME" --fail-on CRITICAL
      else
        npx --yes "gherkin-ai@$GHK_VERSION" report --provider gitlab
      fi
    - npx --yes "gherkin-ai@$GHK_VERSION" validate
    - npx --yes "gherkin-ai@$GHK_VERSION" converge --json > ghk-converge.json || echo "convergence below threshold (report only)"
  artifacts:
    when: always
    paths:
      - ghk-*.json
    reports:
      codequality: gl-code-quality-report.json
${backend}${frontend}${image}`;

  return { filename: '.gitlab-ci.yml', content };
}
