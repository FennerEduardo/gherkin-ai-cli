/* ==========================================================================
   gherkin-ai-cli - Azure Pipelines

   Stages: Gates (ghk lint / validate / risk on pull requests / converge
   report), Test (build, tests and the runtime integration suite run in the
   stack's toolchain image with docker, next to PostgreSQL and RabbitMQ
   containers on a private network: works with any toolchain image, Alpine
   included) and Image (production image, Trivy scan, CycloneDX SBOM).
   Deployment is done by the generated Terraform / Helm through your
   workload-identity service connection.
   Verified by scripts/golden-build.js (ci-azure-pipelines) against the
   azure-pipelines schema.
   ========================================================================== */

import { CI_INTEGRATION_ENV, CI_SERVICES, PipelineSpec, TRIVY_IMAGE } from './pipeline-spec';

const indent = (text: string, n: number) => text.split('\n').map(l => (l ? ' '.repeat(n) + l : l)).join('\n');
const shq = (s: string) => `'${s.replace(/'/g, `'"'"'`)}'`;

export function renderAzurePipelines(spec: PipelineSpec): { filename: string; content: string } {
  const t = spec.backend;
  const integration = t?.integration ?? [];
  const env = CI_INTEGRATION_ENV({ postgres: 'ghk-postgres', rabbitmq: 'ghk-rabbitmq' });
  const inToolchain = (commands: string[], extraEnv: Record<string, string> = {}) =>
    `docker run --rm --network ghk -v "$(Build.SourcesDirectory):/work" -w ${shq(`/work/${spec.workdir === '.' ? '' : spec.workdir}`.replace(/\/$/, ''))}` +
    `${Object.entries({ ...(t?.env ?? {}), ...extraEnv }).map(([k, v]) => ` -e ${k}=${shq(v)}`).join('')} ${t?.image} sh -c ${shq(commands.join(' && '))}`;

  const test = t ? `
- stage: Test
  dependsOn: []
  jobs:
  - job: backend
    displayName: Backend build, tests and integration
    pool:
      vmImage: ubuntu-latest
    steps:
    - checkout: self
    - script: |
        docker network create ghk
        docker run -d --name ghk-postgres --network ghk -e POSTGRES_PASSWORD=${CI_SERVICES.postgres.env.POSTGRES_PASSWORD} ${CI_SERVICES.postgres.image}
        docker run -d --name ghk-rabbitmq --network ghk -e RABBITMQ_DEFAULT_USER=${CI_SERVICES.rabbitmq.env.RABBITMQ_DEFAULT_USER} -e RABBITMQ_DEFAULT_PASS=${CI_SERVICES.rabbitmq.env.RABBITMQ_DEFAULT_PASS} ${CI_SERVICES.rabbitmq.image}
      displayName: Start PostgreSQL and RabbitMQ
    - script: |
        ${inToolchain([...t.build, ...t.test])}
      displayName: Build and tests${integration.length ? `
    - script: |
        until docker exec ghk-postgres pg_isready -U postgres; do sleep 2; done
        until docker exec ghk-rabbitmq rabbitmq-diagnostics -q ping; do sleep 3; done
        ${inToolchain(integration, env)}
      displayName: Runtime integration suite (IT1-IT7 and the HTTP API)` : ''}
` : '';

  const frontend = spec.frontend ? `
  - job: frontend
    displayName: Frontend build and tests
    pool:
      vmImage: ubuntu-latest
    steps:
    - checkout: self
    - task: NodeTool@0
      inputs:
        versionSpec: 24.x
    - script: |
        npm install --no-audit --no-fund --loglevel=error
        npm run build
        npm test
      workingDirectory: ${spec.frontend.dir}
      displayName: Build and test
` : '';

  const image = spec.image ? `
- stage: Image
  dependsOn: [Test]
  jobs:
  - job: image
    displayName: Production image, vulnerability scan and SBOM
    pool:
      vmImage: ubuntu-latest
    steps:
    - checkout: self
    - script: docker build -t ${spec.name}:$(Build.SourceVersion) ${spec.workdir}
      displayName: Build the production image
    - script: |
        docker run --rm -v "$(Build.SourcesDirectory):/src" ${TRIVY_IMAGE} fs --exit-code 1 --severity HIGH,CRITICAL --ignore-unfixed /src/${spec.workdir === '.' ? '' : spec.workdir}
        docker run --rm -v /var/run/docker.sock:/var/run/docker.sock ${TRIVY_IMAGE} image --exit-code 1 --severity HIGH,CRITICAL --ignore-unfixed ${spec.name}:$(Build.SourceVersion)
        docker run --rm -v /var/run/docker.sock:/var/run/docker.sock -v "$(Build.ArtifactStagingDirectory):/out" ${TRIVY_IMAGE} image --format cyclonedx --output /out/sbom.cdx.json ${spec.name}:$(Build.SourceVersion)
      displayName: Trivy scan and SBOM
    - publish: $(Build.ArtifactStagingDirectory)/sbom.cdx.json
      artifact: sbom
` : '';

  const content = `# ${spec.name} CI, generated by gherkin-ai ${spec.ghkVersion}.${spec.deploy ? `
# Deployment code: ${spec.workdir === '.' ? '' : `${spec.workdir}/`}deploy/ (see deploy/README.md); run it in a deployment job with an
# environment approval and your workload-identity service connection to ${spec.deploy.cloud}.` : ''}
trigger:
  branches:
    include: [main]

pr:
  branches:
    include: ['*']

variables:
  # Pinned on purpose: a quality gate must not change behavior when a new version is published.
  GHK_VERSION: '${spec.ghkVersion}'
  GHK_NON_INTERACTIVE: 'true'

stages:
- stage: Gates
  dependsOn: []
  jobs:
  - job: spec
    displayName: Specification gates (gherkin-ai)
    pool:
      vmImage: ubuntu-latest
    steps:
    - checkout: self
      fetchDepth: '0'
    - task: NodeTool@0
      inputs:
        versionSpec: 24.x
    - script: |
${indent(`npx --yes "gherkin-ai@$(GHK_VERSION)" lint --json > ghk-lint.json
npx --yes "gherkin-ai@$(GHK_VERSION)" validate
if [ "$(Build.Reason)" = "PullRequest" ]; then
  TARGET="$(echo "$(System.PullRequest.TargetBranch)" | sed 's#refs/heads/##')"
  npx --yes "gherkin-ai@$(GHK_VERSION)" risk --base "origin/$TARGET" --fail-on CRITICAL --json > ghk-risk.json
fi
npx --yes "gherkin-ai@$(GHK_VERSION)" converge --json > ghk-converge.json || echo "convergence below threshold (report only)"`, 8)}
      displayName: lint, validate, risk, converge
${test}${frontend}${image}`;

  return { filename: 'azure-pipelines.yml', content };
}
