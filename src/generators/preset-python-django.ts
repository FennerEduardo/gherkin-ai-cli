/* ==========================================================================
   gherkin-ai-cli - Python Django + DRF Preset Generator  [stable]

   Django project (config/) + app package: domain kernel + pytest, DRF API
   executing the kernel commands, a Django-native transactional outbox model
   (with migration) fed from aggregate events, pytest-django tests and
   pytest-bdd bound to the feature (pending steps skip).
   Verified by scripts/golden-build.js (django).
   ========================================================================== */

import { ParsedFeature } from '../core/gherkin-parser';
import { GherkinAIConfig } from '../core/config';
import { buildDomainModel, toKebab } from './kernel/domain-model';
import { PyFile, pyModulesOf, renderPyImportSmokeTest, renderPyKernel, renderPyKernelTests, renderPytestBdd, withInitFiles } from './kernel/python';
import { PY_INTEGRATION_MARKER, pyRuntimeDependencies, renderPyRuntime } from './kernel/runtime/python';
import { PY_EVENT_BUS, pyEventBusTest, pyFeatureFile, renderPyproject } from './python/python-common';
import { renderDjangoHttpIntegration, renderDjangoRelayCommand, renderDjangoUnitTest, renderDjangoViews, renderPyAuth, renderPyWorker } from './kernel/app/python';
import { tenantClaim } from './kernel/app/shared';
import { siblingDomainModels } from './kernel/siblings';

export function generatePythonDjangoPreset(parsed: ParsedFeature, config?: GherkinAIConfig, featureFile?: string): { filename: string; content: string }[] {
  const m = buildDomainModel(parsed, { service: config?.projectName });
  const siblings = siblingDomainModels(m, config, s => `app/domain/${s.snake}.py`);

  const settings = `"""Django settings (generated by gherkin-ai). Override with environment variables in production."""
import os
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent

SECRET_KEY = os.getenv("DJANGO_SECRET_KEY", "insecure-dev-key-change-me")
DEBUG = os.getenv("DJANGO_DEBUG", "true").lower() == "true"
ALLOWED_HOSTS = os.getenv("DJANGO_ALLOWED_HOSTS", "localhost,127.0.0.1,testserver").split(",")

INSTALLED_APPS = [
    "django.contrib.contenttypes",
    "django.contrib.auth",
    "rest_framework",
    "app",
]

MIDDLEWARE = [
    "django.middleware.common.CommonMiddleware",
]

ROOT_URLCONF = "config.urls"
WSGI_APPLICATION = "config.wsgi.application"

DATABASES = {
    "default": {
        "ENGINE": "django.db.backends.sqlite3",
        "NAME": os.getenv("DJANGO_DB_PATH", str(BASE_DIR / "db.sqlite3")),
    }
}

DEFAULT_AUTO_FIELD = "django.db.models.BigAutoField"
USE_TZ = True

REST_FRAMEWORK = {
    "DEFAULT_AUTHENTICATION_CLASSES": [],
    "DEFAULT_PERMISSION_CLASSES": [],
    "UNAUTHENTICATED_USER": None,
}
`;


  const runtime = renderPyRuntime(m, 'app', siblings, { messaging: config?.stack?.messaging });
  const appFiles: PyFile[] = withInitFiles([
    { filename: 'config/settings.py', content: settings },
    {
      filename: 'config/urls.py',
      content: `from django.urls import path

from app import views

urlpatterns = [
    path("health", views.health),
${[m, ...siblings].map(f => `    path("api/v1/${f.kebab}/<str:aggregate_id>/<str:command>", views.execute, {"aggregate_type": "${f.pascal}"}),`).join('\n')}
]
`
    },
    { filename: 'config/wsgi.py', content: `import os\n\nfrom django.core.wsgi import get_wsgi_application\n\nos.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings")\napplication = get_wsgi_application()\n` },
    { filename: 'app/apps.py', content: `from django.apps import AppConfig\n\n\nclass AppConfig_(AppConfig):\n    name = "app"\n    default_auto_field = "django.db.models.BigAutoField"\n` },
    { filename: 'app/infrastructure/event_bus.py', content: PY_EVENT_BUS },
    ...renderPyKernel(m, 'app', siblings),
    // Runtime kernel: PostgreSQL + RabbitMQ + OpenTelemetry, verified by tests/integration (docs/RUNTIME-KERNEL.md).
    ...runtime.filter(f => f.filename.startsWith('app/')),
    // Application layer wired to the kernel (kernel/app/shared.ts): commands persist in the runtime tables
    // (DATABASE_URL), the tenant comes from the JWT, `manage.py outbox_relay` publishes the outbox.
    { filename: 'app/views.py', content: renderDjangoViews(m) },
    { filename: 'app/auth.py', content: renderPyAuth(tenantClaim(config)) },
    { filename: 'app/worker.py', content: renderPyWorker(m) },
    { filename: 'app/management/commands/outbox_relay.py', content: renderDjangoRelayCommand() }
  ]);

  return [
    ...appFiles,
    {
      filename: 'manage.py',
      content: `#!/usr/bin/env python
import os
import sys

if __name__ == "__main__":
    os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings")
    from django.core.management import execute_from_command_line

    execute_from_command_line(sys.argv)
`
    },
    ...renderPyKernelTests(m),
    ...runtime.filter(f => f.filename.startsWith('tests/')),
    ...renderPytestBdd(m, pyFeatureFile(m, featureFile)),
    pyEventBusTest(),
    { filename: 'tests/test_api.py', content: renderDjangoUnitTest(m) },
    { filename: 'tests/integration/test_http.py', content: renderDjangoHttpIntegration(m) },
    renderPyImportSmokeTest(pyModulesOf(appFiles.map(f => f.filename)).filter(mod => mod !== 'config.wsgi')),
    {
      filename: 'pyproject.toml',
      content: renderPyproject(
        toKebab(config?.projectName || m.kebab),
        ['django>=5.0,<6', 'djangorestframework>=3.15', ...pyRuntimeDependencies(config?.stack?.messaging)],
        ['pytest>=8.3', 'pytest-django>=4.9', 'pytest-bdd>=7.3'],
        ['DJANGO_SETTINGS_MODULE = "config.settings"', PY_INTEGRATION_MARKER]
      )
    }
  ];
}
