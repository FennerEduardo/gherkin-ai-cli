/* ==========================================================================
   gherkin-ai-cli - What a deployment target needs to know about the service

   One description of the generated backend (port, probes, broker, topology,
   secrets, relay process) shared by the Terraform modules and the Helm chart,
   so every target configures the image the same way (docs/DEPLOYMENT.md).
   ========================================================================== */

import type { GherkinAIConfig } from '../../core/config';
import { toKebab } from '../../utils/naming';
import { getStackSupport } from '../stack-support';
import { resolveAppRuntimeEnv, resolveHealth } from '../toolchains';
import { runtimeBroker, RuntimeBroker } from './broker-env';

export type DeployCloud = 'aws' | 'gcp' | 'azure';
export type DeployCompute = 'containers' | 'kubernetes' | 'both';

export interface DeployConfig {
  cloud: DeployCloud;
  compute: DeployCompute;
  environments: string[];
  region: string;
}

export const DEFAULT_ENVIRONMENTS = ['dev', 'staging', 'prod'];
const DEFAULT_REGION: Record<DeployCloud, string> = { aws: 'us-east-1', gcp: 'us-central1', azure: 'eastus2' };

/** A secret the platform injects as an environment variable (generated by the IaC unless noted). */
export interface ServiceSecret {
  name: string;
  /** How Terraform produces the value. */
  source: 'database-url' | 'amqp-url' | 'random' | 'laravel-key' | 'input';
  /** Length of a random secret. */
  length?: number;
}

export interface ServiceSpec {
  /** Kebab-case service name: resource prefix, image name, Helm release. */
  name: string;
  stackLabel: string;
  port: number;
  health: { live: string; ready: string };
  /** Broker of the runtime (Service Bus falls back to RabbitMQ where the language has no adapter). */
  broker: RuntimeBroker;
  /** Topology names the runtime uses (created by the IaC for Pub/Sub and Service Bus). */
  topology: { exchange: string; queue: string; dlx: string; dlq: string };
  /** Plain environment variables (not secret). */
  env: Record<string, string>;
  secrets: ServiceSecret[];
  /** Command of a separate outbox relay process (stacks whose relay is not in-process). */
  relayCommand?: string[];
}

export function deployConfig(config: GherkinAIConfig): DeployConfig | undefined {
  const d = config.deploy;
  if (!d?.cloud) return undefined;
  return {
    cloud: d.cloud,
    compute: d.compute ?? 'containers',
    environments: d.environments?.length ? d.environments : DEFAULT_ENVIRONMENTS,
    region: d.region ?? DEFAULT_REGION[d.cloud]
  };
}

/**
 * The managed broker each cloud uses: AWS Amazon MQ for RabbitMQ (no code change), GCP Pub/Sub (adapter in every
 * runtime), Azure Service Bus when the code has its adapter (stack.messaging "servicebus" on a language with an
 * official SDK); otherwise RabbitMQ from an input AMQP_URL (self-managed or CloudAMQP).
 */
export function cloudBroker(config: Pick<GherkinAIConfig, 'stack'>, cloud: DeployCloud): RuntimeBroker {
  if (cloud === 'gcp') return 'pubsub';
  if (cloud === 'azure') return runtimeBroker(config) === 'servicebus' ? 'servicebus' : 'rabbitmq';
  return 'rabbitmq';
}

const RELAY_COMMANDS: Record<string, string[]> = {
  'python/django': ['python', 'manage.py', 'outbox_relay'],
  'php/laravel': ['php', 'artisan', 'outbox:relay'],
  'ruby/rails': ['bin/rails', 'outbox:relay']
};

export function serviceSpec(config: GherkinAIConfig, cloud: DeployCloud): ServiceSpec {
  const name = toKebab(config.projectName || 'service');
  const support = getStackSupport(config);
  const { port } = resolveAppRuntimeEnv(config);
  const prefix = name;
  const broker = cloudBroker(config, cloud);
  const id = support.id;
  const secrets: ServiceSecret[] = [
    { name: 'DATABASE_URL', source: 'database-url' },
    { name: 'JWT_SECRET', source: 'random', length: 48 },
    ...(broker === 'rabbitmq' ? [{ name: 'AMQP_URL', source: cloud === 'aws' ? 'amqp-url' : 'input' } as ServiceSecret] : []),
    ...(id === 'php/laravel' ? [{ name: 'APP_KEY', source: 'laravel-key' } as ServiceSecret] : []),
    ...(id === 'ruby/rails' || id.startsWith('elixir/phoenix') ? [{ name: 'SECRET_KEY_BASE', source: 'random', length: 64 } as ServiceSecret] : []),
    ...(id === 'python/django' ? [{ name: 'DJANGO_SECRET_KEY', source: 'random', length: 50 } as ServiceSecret] : [])
  ];
  return {
    name,
    stackLabel: support.label,
    port,
    health: resolveHealth(config),
    broker,
    topology: { exchange: `${prefix}.events`, queue: `${prefix}.consumer`, dlx: `${prefix}.dlx`, dlq: `${prefix}.dlq` },
    env: {
      GHK_BROKER: broker,
      // Pub/Sub and Service Bus topologies are created by the IaC and the service identity can only publish and
      // consume; on RabbitMQ the application user declares its (idempotent) exchanges and queues itself.
      ...(broker === 'rabbitmq' ? {} : { GHK_DECLARE_TOPOLOGY: 'false' }),
      OTEL_SERVICE_NAME: name
    },
    secrets,
    relayCommand: RELAY_COMMANDS[id]
  };
}
