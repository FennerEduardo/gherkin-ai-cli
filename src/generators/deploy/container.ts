/* ==========================================================================
   gherkin-ai-cli - Production container image per backend

   A multi-stage Dockerfile (build in the stack's toolchain image, run in a
   smaller runtime image as a non-root user) plus .dockerignore. The image
   is configured only through environment variables (DATABASE_URL, AMQP_URL,
   JWT_SECRET, OTEL_*), so the same image runs on ECS / Cloud Run /
   Container Apps / Kubernetes. Health probes are HTTP and defined by the
   platform (toolchains.ts resolveHealth), so the image needs no curl.
   Verified by scripts/golden-build.js: docker build, run, probe.
   ========================================================================== */

import type { GherkinAIConfig } from '../../core/config';
import { getStackSupport } from '../stack-support';
import { resolveAppRuntimeEnv, resolveHealth, TOOLCHAINS } from '../toolchains';
import { rustCrateName } from '../preset-rust-axum';
import { resolveNodeProfile } from '../node-profile';
import { brokerVariables } from './broker-env';

export interface ContainerFile {
  filename: string;
  content: string;
}

const HEADER = (stack: string, port: number, health: { live: string; ready: string }, broker: string[]) => `# syntax=docker/dockerfile:1
# Production image generated by gherkin-ai (${stack}).
# Configure it with environment variables only: DATABASE_URL, ${broker.join(', ')}, JWT_SECRET, OTEL_EXPORTER_OTLP_ENDPOINT.
# Listens on ${port}; probes: liveness ${health.live}, readiness ${health.ready}.
`;

const NON_ROOT_DEBIAN = 'RUN useradd --system --uid 10001 --no-create-home app';

const IGNORE_COMMON = ['.git', '.ghe', '.env', '.env.*', '!.env.example', 'prompts', '**/*.ghk-new', 'docker-compose*.yml', 'Dockerfile', '.dockerignore', '*.md'];

function nodeDockerfile(config: GherkinAIConfig, port: number): string {
  const framework = (config.stack.framework || '').toLowerCase();
  const entry = framework === 'express' ? 'dist/src/server.js' : 'dist/src/main.js';
  const prisma = (config.stack.orm || '').toLowerCase() === 'prisma';
  const prisma7 = prisma && resolveNodeProfile(config).prisma === '7';
  return `FROM ${TOOLCHAINS['typescript/nestjs'].image} AS build
WORKDIR /app
COPY package*.json ./
RUN npm install --no-audit --no-fund --loglevel=error
COPY . .
${prisma ? `# The Prisma client is generated at build time (the URL is only read by the CLI config, not used).
RUN DATABASE_URL=\${DATABASE_URL:-postgresql://build:build@localhost:5432/build} npx prisma generate
` : ''}RUN npm run build && npm prune --omit=dev

FROM node:24-bookworm-slim
${prisma && !prisma7 ? 'RUN apt-get update && apt-get install -y --no-install-recommends openssl && rm -rf /var/lib/apt/lists/*\n' : ''}ENV NODE_ENV=production PORT=${port}
WORKDIR /app
COPY --from=build --chown=node:node /app/package.json ./
COPY --from=build --chown=node:node /app/node_modules ./node_modules
COPY --from=build --chown=node:node /app/dist ./dist
USER node
EXPOSE ${port}
CMD ["node", "${entry}"]
`;
}

function dockerfileFor(id: string, config: GherkinAIConfig, port: number): { body: string; ignore: string[] } | undefined {
  const projectName = config.projectName || 'MyProject';
  if (id.startsWith('typescript/nestjs') || id.startsWith('typescript/express')) {
    return { body: nodeDockerfile(config, port), ignore: ['node_modules', 'dist', 'coverage'] };
  }
  switch (id) {
    case 'java/spring':
      return {
        body: `FROM ${TOOLCHAINS['java/spring'].image} AS build
WORKDIR /app
COPY . .
RUN mvn -q -B -ntp -DskipTests package && cp target/*.jar /app/app.jar

FROM eclipse-temurin:17-jre
${NON_ROOT_DEBIAN}
WORKDIR /app
COPY --from=build /app/app.jar app.jar
USER 10001
ENV SERVER_PORT=${port}
EXPOSE ${port}
ENTRYPOINT ["java", "-XX:MaxRAMPercentage=75", "-jar", "/app/app.jar"]
`, ignore: ['target']
      };
    case 'kotlin/spring':
      return {
        body: `FROM ${TOOLCHAINS['kotlin/spring'].image} AS build
WORKDIR /app
COPY . .
RUN gradle -q --no-daemon bootJar && cp $(ls build/libs/*.jar | grep -v -- '-plain.jar') /app/app.jar

FROM eclipse-temurin:17-jre
${NON_ROOT_DEBIAN}
WORKDIR /app
COPY --from=build /app/app.jar app.jar
USER 10001
ENV SERVER_PORT=${port}
EXPOSE ${port}
ENTRYPOINT ["java", "-XX:MaxRAMPercentage=75", "-jar", "/app/app.jar"]
`, ignore: ['build', '.gradle']
      };
    case 'java/quarkus':
      return {
        body: `FROM ${TOOLCHAINS['java/quarkus'].image} AS build
WORKDIR /app
COPY . .
RUN mvn -q -B -ntp -DskipTests package

FROM eclipse-temurin:21-jre
${NON_ROOT_DEBIAN}
WORKDIR /app
# Quarkus fast-jar layout: dependencies change less often than the application.
COPY --from=build --chown=10001 /app/target/quarkus-app/lib/ /app/lib/
COPY --from=build --chown=10001 /app/target/quarkus-app/*.jar /app/
COPY --from=build --chown=10001 /app/target/quarkus-app/app/ /app/app/
COPY --from=build --chown=10001 /app/target/quarkus-app/quarkus/ /app/quarkus/
USER 10001
ENV SERVER_PORT=${port}
EXPOSE ${port}
ENTRYPOINT ["java", "-XX:MaxRAMPercentage=75", "-Dquarkus.http.host=0.0.0.0", "-jar", "/app/quarkus-run.jar"]
`, ignore: ['target']
      };
    case 'csharp/dotnet':
      return {
        body: `FROM ${TOOLCHAINS['csharp/dotnet'].image} AS build
WORKDIR /src
COPY . .
RUN dotnet publish ${projectName}.csproj -c Release -o /app --nologo

FROM mcr.microsoft.com/dotnet/aspnet:8.0
WORKDIR /app
COPY --from=build /app .
ENV ASPNETCORE_URLS=http://0.0.0.0:${port} DOTNET_CLI_TELEMETRY_OPTOUT=1
# The aspnet image ships a non-root "app" user.
USER app
EXPOSE ${port}
ENTRYPOINT ["dotnet", "${projectName}.dll"]
`, ignore: ['bin', 'obj', '**/bin', '**/obj', 'tests']
      };
    case 'python/fastapi':
    case 'python/django': {
      const django = id === 'python/django';
      return {
        body: `FROM ${TOOLCHAINS[id].image} AS build
WORKDIR /app
RUN python -m venv /venv
COPY . .
RUN /venv/bin/pip install -q --no-cache-dir .${django ? ' gunicorn' : ''}

FROM ${TOOLCHAINS[id].image}
${NON_ROOT_DEBIAN}
COPY --from=build /venv /venv
WORKDIR /app
COPY --from=build --chown=10001 /app /app
ENV PATH=/venv/bin:$PATH PYTHONUNBUFFERED=1 PYTHONDONTWRITEBYTECODE=1
${django ? `# Restrict DJANGO_ALLOWED_HOSTS to the service host names in each environment.
ENV DJANGO_DEBUG=false DJANGO_SETTINGS_MODULE=config.settings DJANGO_ALLOWED_HOSTS=*
` : ''}
USER 10001
EXPOSE ${port}
CMD ${django
  ? `["gunicorn", "config.wsgi:application", "--bind", "0.0.0.0:${port}", "--workers", "2"]`
  : `["uvicorn", "app.main:app", "--host", "0.0.0.0", "--port", "${port}"]`}
`, ignore: ['.venv', '**/__pycache__', '.pytest_cache', '*.egg-info']
      };
    }
    case 'go/chi':
      return {
        body: `FROM ${TOOLCHAINS['go/chi'].image} AS build
WORKDIR /src
COPY . .
RUN go mod tidy && CGO_ENABLED=0 go build -trimpath -ldflags="-s -w" -o /out/server ./cmd/server

FROM gcr.io/distroless/static-debian12:nonroot
COPY --from=build /out/server /server
USER nonroot:nonroot
ENV PORT=${port}
EXPOSE ${port}
ENTRYPOINT ["/server"]
`, ignore: []
      };
    case 'rust/axum': {
      const crate = rustCrateName(config);
      return {
        body: `FROM rust:1.99-bookworm AS build
WORKDIR /src
COPY . .
RUN cargo build --release --bin ${crate}

FROM debian:bookworm-slim
RUN apt-get update && apt-get install -y --no-install-recommends ca-certificates && rm -rf /var/lib/apt/lists/*
${NON_ROOT_DEBIAN}
COPY --from=build /src/target/release/${crate} /usr/local/bin/app
USER 10001
ENV PORT=${port}
EXPOSE ${port}
ENTRYPOINT ["/usr/local/bin/app"]
`, ignore: ['target']
      };
    }
    case 'ruby/rails':
      return {
        body: `FROM ${TOOLCHAINS['ruby/rails'].image} AS build
WORKDIR /app
ENV BUNDLE_WITHOUT=development:test
COPY Gemfile* ./
RUN bundle install --jobs 4 --quiet
COPY . .

FROM ruby:3.3-slim
RUN apt-get update && apt-get install -y --no-install-recommends libpq5 && rm -rf /var/lib/apt/lists/*
${NON_ROOT_DEBIAN}
COPY --from=build /usr/local/bundle /usr/local/bundle
WORKDIR /app
COPY --from=build --chown=10001 /app /app
RUN mkdir -p /app/tmp /app/log && chown -R 10001 /app/tmp /app/log
# SECRET_KEY_BASE must be provided by the platform (secret manager).
ENV RAILS_ENV=production RAILS_LOG_TO_STDOUT=1 BUNDLE_WITHOUT=development:test PORT=${port}
USER 10001
EXPOSE ${port}
CMD ["bin/rails", "server", "-b", "0.0.0.0", "-p", "${port}"]
`, ignore: ['log', 'tmp', 'vendor/bundle']
      };
    case 'elixir/phoenix':
      return {
        // config/config.exs reads PORT and SECRET_KEY_BASE when the server starts (mix phx.server).
        body: `FROM ${TOOLCHAINS['elixir/phoenix'].image}
ENV MIX_ENV=prod MIX_HOME=/opt/mix HEX_HOME=/opt/hex PORT=${port}
RUN mix local.hex --force && mix local.rebar --force
${NON_ROOT_DEBIAN}
WORKDIR /app
COPY mix.exs mix.lock* ./
RUN mix deps.get --only prod && mix deps.compile
COPY . .
RUN mix compile && chown -R 10001 /app
# SECRET_KEY_BASE must be provided by the platform (secret manager).
USER 10001
EXPOSE ${port}
CMD ["mix", "phx.server"]
`, ignore: ['_build', 'deps']
      };
    case 'php/laravel':
      return {
        body: `FROM ${TOOLCHAINS['php/laravel'].image} AS vendor
WORKDIR /app
COPY . .
RUN composer install --no-dev --prefer-dist --no-progress --no-interaction --optimize-autoloader --no-scripts --ignore-platform-req=ext-*

# FrankenPHP: production PHP application server (Caddy) in one process.
FROM dunglas/frankenphp:1-php8.4-alpine
RUN install-php-extensions pdo_pgsql sockets
WORKDIR /app
COPY --from=vendor /app /app
# APP_KEY must be provided by the platform (secret manager).
ENV SERVER_NAME=:${port} APP_ENV=production APP_DEBUG=false LOG_CHANNEL=stderr
RUN adduser -D -u 10001 app && mkdir -p /app/storage /app/bootstrap/cache \\
    && chown -R app:app /app/storage /app/bootstrap/cache /data/caddy /config/caddy
USER app
EXPOSE ${port}
`, ignore: ['vendor', 'storage/logs/*', 'bootstrap/cache/*.php']
      };
    default:
      return undefined;
  }
}

/** Dockerfile + .dockerignore for a backend with a preset; none for frontends and experimental stacks. */
export function renderContainerFiles(config: GherkinAIConfig): ContainerFile[] {
  const support = getStackSupport(config);
  if (support.kind !== 'backend' || support.tier === 'experimental') return [];
  const { port } = resolveAppRuntimeEnv(config);
  const spec = dockerfileFor(support.id, config, port);
  if (!spec) return [];
  return [
    { filename: 'Dockerfile', content: HEADER(support.label, port, resolveHealth(config), brokerVariables(config)) + '\n' + spec.body },
    { filename: '.dockerignore', content: [...IGNORE_COMMON, ...spec.ignore].join('\n') + '\n' }
  ];
}
