/* ==========================================================================
   gherkin-ai-cli - Deployment targets (config.deploy)

   deploy.cloud      -> deploy/terraform/<cloud>/ (managed containers)
   deploy.compute    -> containers (default) | kubernetes (Helm chart) | both
   deploy.environments -> one tfvars / backend / values file per environment
   Only backends with a production image (deploy/container.ts) get targets.
   ========================================================================== */

import type { GherkinAIConfig } from '../../core/config';
import { CLI_VERSION } from '../../version';
import { renderContainerFiles } from './container';
import { renderHelmChart } from './helm';
import { deployConfig, DeployConfig, serviceSpec, ServiceSpec } from './service-spec';
import { renderTerraformAws, TerraformFile } from './terraform-aws';
import { renderTerraformAzure } from './terraform-azure';
import { renderTerraformGcp } from './terraform-gcp';

const CLOUD_LABEL = { aws: 'AWS', gcp: 'Google Cloud', azure: 'Azure' } as const;

export function renderDeploymentTargets(config: GherkinAIConfig): TerraformFile[] {
  const deploy = deployConfig(config);
  if (!deploy || !renderContainerFiles(config).length) return [];
  const spec = serviceSpec(config, deploy.cloud);
  const files: TerraformFile[] = [];
  if (deploy.compute !== 'kubernetes') {
    const render = { aws: renderTerraformAws, gcp: renderTerraformGcp, azure: renderTerraformAzure }[deploy.cloud];
    files.push(...render(spec, deploy));
  }
  if (deploy.compute !== 'containers') files.push(...renderHelmChart(spec, deploy, CLI_VERSION));
  files.push({ filename: 'deploy/README.md', content: deployReadme(spec, deploy) });
  return files;
}

function deployReadme(spec: ServiceSpec, d: DeployConfig): string {
  const tf = d.compute !== 'kubernetes';
  const helm = d.compute !== 'containers';
  const backendExt = { aws: 's3', gcp: 'gcs', azure: 'azurerm' }[d.cloud];
  const platform = { aws: 'ECS Fargate behind an Application Load Balancer', gcp: 'Cloud Run', azure: 'Azure Container Apps' }[d.cloud];
  const db = { aws: 'RDS for PostgreSQL', gcp: 'Cloud SQL for PostgreSQL (private IP)', azure: 'Azure Database for PostgreSQL Flexible Server (VNet-integrated)' }[d.cloud];
  const broker = spec.broker === 'pubsub' ? 'Pub/Sub topics and subscriptions (least-privilege IAM)'
    : spec.broker === 'servicebus' ? 'Service Bus namespace, topics and subscriptions (Entra ID, data roles only)'
    : d.cloud === 'aws' ? 'Amazon MQ for RabbitMQ (AMQPS)' : 'external RabbitMQ (self-managed or CloudAMQP) through the `amqp_url` input: this stack has no Service Bus adapter';
  const secretsStore = { aws: 'Secrets Manager', gcp: 'Secret Manager', azure: 'Key Vault' }[d.cloud];
  return `# Deployment of ${spec.name} on ${CLOUD_LABEL[d.cloud]}

Generated by gherkin-ai ${CLI_VERSION} from \`deploy\` in \`gherkin-ai.config.json\`. The image is the generated \`Dockerfile\`; it is configured only with environment variables (docs/DEPLOYMENT.md of gherkin-ai).

| Part | Resource |
|---|---|
| Compute | ${[tf ? platform : '', helm ? `Kubernetes (Helm chart \`helm/${spec.name}\`)` : ''].filter(Boolean).join(' and ')} |
| Probes | liveness \`${spec.health.live}\`, readiness \`${spec.health.ready}\`, port ${spec.port} |
${tf ? `| Database | ${db} |
| Broker | ${broker} |
| Secrets | ${secretsStore}: ${spec.secrets.map(s => `\`${s.name}\``).join(', ')} |
` : ''}${spec.relayCommand ? `| Outbox relay | separate process: \`${spec.relayCommand.join(' ')}\` |\n` : ''}
${tf ? `## Terraform (\`terraform/${d.cloud}\`)

The network is an input (see \`variables.tf\`): the service runs in your existing VPC / virtual network. Fill \`environments/<env>.tfvars\` and \`environments/<env>.${backendExt}.tfbackend\`, then:

\`\`\`bash
cd deploy/terraform/${d.cloud}
terraform init -backend-config=environments/dev.${backendExt}.tfbackend
terraform plan -var-file=environments/dev.tfvars -var image=<image>:<git-sha> -out=dev.plan
terraform apply dev.plan
\`\`\`

- **Secrets** are generated by Terraform (random values, database and broker URLs) and stored in ${secretsStore}; they live in the Terraform state, so keep the state backend encrypted and access-controlled.
- **Production safety:** with \`environment = "prod"\`, deletion protection, longer backups${d.cloud === 'aws' ? ', Multi-AZ' : d.cloud === 'gcp' ? ', a regional database' : ', zone-redundant high availability'} and secret recovery are on.
- **Database TLS:** the service connects with \`sslmode=require\` (encrypted; the managed database's certificate is not verified, as in libpq), and \`db_require_tls\` (on by default) makes the database refuse unencrypted connections. Turn it off only for a client that cannot use TLS.
- Plans are reviewed by a human: \`deploy/**\` requires approval in the gherkin-ai agent firewall.
` : ''}${helm ? `
## Helm (\`helm/${spec.name}\`)

\`\`\`bash
helm upgrade --install ${spec.name} deploy/helm/${spec.name} -f deploy/helm/${spec.name}/values-dev.yaml --set image.repository=<registry>/${spec.name} --set image.tag=<git-sha>
\`\`\`

The chart expects a Secret \`${spec.name}-secrets\` with ${spec.secrets.map(s => `\`${s.name}\``).join(', ')}, created from the cloud secret manager by External Secrets Operator or the Secrets Store CSI driver. Set the workload identity annotation of the ServiceAccount in \`values-<env>.yaml\`.
` : ''}`;
}
