/* ==========================================================================
   gherkin-ai-cli - deploy.compute "vm": one virtual machine running the image

   For demos and small workloads (LMS P-04: EC2 + RDS + compose instead of
   ECS + ALB). The managed database, broker and secret store of each cloud
   are the same as for "containers" (their Terraform files are reused as
   they are); only the compute changes:

     aws    EC2 (Amazon Linux 2023) + Elastic IP, SSM Session Manager, no SSH
     gcp    Compute Engine (Debian 12) + static IP, the service account
     azure  Linux VM (Ubuntu 24.04) + public IP, the user-assigned identity

   cloud-init installs Docker, reads the secrets from the cloud secret store
   with the machine identity into an env file (mode 600), and runs the image
   behind Caddy (automatic HTTPS when var.domain is set, plain :80 otherwise),
   plus the outbox relay process for the stacks that have one.
   ========================================================================== */

import { hattrs, hlist, hstr } from './hcl';
import type { DeployConfig, ServiceSpec } from './service-spec';
import type { TerraformFile } from './terraform-aws';

const CADDY_IMAGE = 'caddy:2.10-alpine';

/** Drops the `variable "<name>" { ... }` blocks of a variables.tf. */
function withoutVariables(variables: string, names: string[]): string {
  return variables
    .replace(/variable "([a-z_]+)" \{[\s\S]*?\n\}\n/g, (block, name: string) => (names.includes(name) ? '' : block))
    .replace(/\n{3,}/g, '\n\n')
    .replace(/^\n+/, '');
}

const pick = (files: TerraformFile[], dir: string, names: string[]) => files.filter(f => names.some(n => f.filename === `${dir}/${n}`));

/** The cloud-init script (a Terraform template: ${...} are template variables, bash uses $VAR). */
function initScript(spec: ServiceSpec, cloud: 'aws' | 'gcp' | 'azure'): string {
  const install = cloud === 'aws'
    ? 'dnf install -y docker\nsystemctl enable --now docker'
    : 'apt-get update -y\napt-get install -y docker.io\nsystemctl enable --now docker';
  const login = {
    aws: `case "${'$'}{image}" in
  *.dkr.ecr.*) aws ecr get-login-password --region "${'$'}{region}" | docker login --username AWS --password-stdin "${'$'}{split("/", image)[0]}" ;;
esac`,
    gcp: `case "${'$'}{image}" in
  *-docker.pkg.dev/*) gcloud auth configure-docker "${'$'}{split("/", image)[0]}" --quiet ;;
esac`,
    azure: `curl -sL https://aka.ms/InstallAzureCLIDeb | bash
az login --identity --client-id "${'$'}{identity_client_id}" --output none
case "${'$'}{image}" in
  *.azurecr.io/*) az acr login --name "${'$'}{split(".", image)[0]}" ;;
esac`
  }[cloud];
  const fetch = {
    aws: `aws secretsmanager get-secret-value --region "${'$'}{region}" --secret-id "${'$'}{secret_prefix}/$name" --query SecretString --output text`,
    gcp: `gcloud secrets versions access latest --secret="${'$'}{secret_prefix}-$(echo "$name" | tr '[:upper:]_' '[:lower:]-')"`,
    azure: `az keyvault secret show --vault-name "${'$'}{vault_name}" --name "$(echo "$name" | tr '[:upper:]_' '[:lower:]-')" --query value --output tsv`
  }[cloud];
  const relay = spec.relayCommand
    ? `\ndocker run -d --name relay --restart unless-stopped --network app --env-file /opt/app/app.env "${'$'}{image}" ${spec.relayCommand.map(a => JSON.stringify(a)).join(' ')}`
    : '';
  return `#!/bin/bash
# Generated by gherkin-ai: runs ${spec.name} on this machine (deploy.compute "vm").
set -euo pipefail

${install}
${login}

# Secrets, read with the machine identity, never written to the Terraform user data.
install -d -m 700 /opt/app
umask 077
: > /opt/app/app.env
for name in ${'$'}{secret_names}; do
  printf '%s=%s\\n' "$name" "$(${fetch})" >> /opt/app/app.env
done
cat >> /opt/app/app.env <<'ENV'
${'$'}{plain_environment}
ENV

# Caddy terminates TLS (Let's Encrypt) for the domain, or serves plain HTTP on :80 without one.
cat > /opt/app/Caddyfile <<'CADDY'
${'$'}{site} {
  reverse_proxy app:${spec.port}
}
CADDY

docker network create app 2>/dev/null || true
docker rm -f app caddy relay 2>/dev/null || true
docker run -d --name app --restart unless-stopped --network app --env-file /opt/app/app.env "${'$'}{image}"${relay}
docker run -d --name caddy --restart unless-stopped --network app -p 80:80 -p 443:443 \\
  -v /opt/app/Caddyfile:/etc/caddy/Caddyfile:ro -v caddy_data:/data ${CADDY_IMAGE}
`;
}

/** Template variables shared by the three clouds (plain environment as KEY=VALUE lines). */
const templateVars = (extra: [string, string][]): string => `templatefile("\${path.module}/vm-init.sh.tftpl", {
${hattrs([
  ['image', 'var.image'],
  ['secret_names', 'join(" ", local.secret_names)'],
  // No collector sidecar on the machine: OTLP goes where var.extra_environment says, or nowhere.
  ['plain_environment', 'join("\\n", [for k, v in local.environment : "${k}=${v}" if k != "OTEL_EXPORTER_OTLP_ENDPOINT" || contains(keys(var.extra_environment), k)])'],
  ['site', 'var.domain == "" ? ":80" : var.domain'],
  ...extra
], 4)}
  })`;

const domainVariable = `variable "domain" {
  description = "Domain pointed at the machine's address: Caddy obtains its certificate. Empty: plain HTTP on port 80 (development)."
  type        = string
  default     = ""
}
`;

const allowedCidrs = `variable "allowed_cidrs" {
  description = "CIDR blocks allowed to reach ports 80 and 443."
  type        = list(string)
  default     = ["0.0.0.0/0"]
}
`;

// ---------------------------------------------------------------------------
// AWS: EC2
// ---------------------------------------------------------------------------

function awsVm(spec: ServiceSpec, deploy: DeployConfig, base: TerraformFile[]): TerraformFile[] {
  const dir = 'deploy/terraform/aws';
  const mq = spec.broker === 'rabbitmq';
  const baseVariables = base.find(f => f.filename === `${dir}/variables.tf`)!.content;
  const variables = withoutVariables(baseVariables, ['public_subnet_ids', 'allowed_cidrs', 'certificate_arn', 'cpu', 'memory', 'cpu_architecture', 'desired_count', 'max_count', 'enable_tracing', 'otel_collector_image']) + `
variable "subnet_id" {
  description = "Public subnet of the machine (with a route to an internet gateway)."
  type        = string
}

variable "instance_type" {
  description = "EC2 instance type (t3.small: 2 vCPU, 2 GiB; t4g.* needs an ARM64 image)."
  type        = string
  default     = "t3.small"
}

variable "root_volume_gb" {
  description = "Encrypted root volume (GiB): images and logs."
  type        = number
  default     = 30
}

${allowedCidrs}
${domainVariable}`;

  const main = `locals {
  name = "\${var.service_name}-\${var.environment}"
  prod = var.environment == "prod"

  tags = merge({
    service     = var.service_name
    environment = var.environment
    managed-by  = "terraform"
  }, var.tags)

  # Plain configuration of the container (the secrets are in secrets.tf).
  environment = merge(${Object.keys(spec.env).length ? `{\n${hattrs(Object.entries(spec.env).map(([k, v]) => [k, hstr(v)]), 4)}\n  }` : '{}'}, var.extra_environment)
}

data "aws_caller_identity" "current" {}

data "aws_ssm_parameter" "al2023" {
  name = "/aws/service/ami-amazon-linux-latest/al2023-ami-kernel-default-x86_64"
}
`;

  const network = `resource "aws_security_group" "service" {
  name        = "\${local.name}-vm"
  description = "Machine of \${local.name}"
  vpc_id      = var.vpc_id

  ingress {
    description = "HTTP"
    from_port   = 80
    to_port     = 80
    protocol    = "tcp"
    cidr_blocks = var.allowed_cidrs
  }

  ingress {
    description = "HTTPS"
    from_port   = 443
    to_port     = 443
    protocol    = "tcp"
    cidr_blocks = var.allowed_cidrs
  }

  egress {
    from_port   = 0
    to_port     = 0
    protocol    = "-1"
    cidr_blocks = ["0.0.0.0/0"]
  }
}

resource "aws_security_group" "database" {
  name        = "\${local.name}-database"
  description = "PostgreSQL of \${local.name}"
  vpc_id      = var.vpc_id

  ingress {
    description     = "PostgreSQL from the machine"
    from_port       = 5432
    to_port         = 5432
    protocol        = "tcp"
    security_groups = [aws_security_group.service.id]
  }
}
${mq ? `
resource "aws_security_group" "broker" {
  name        = "\${local.name}-broker"
  description = "Amazon MQ of \${local.name}"
  vpc_id      = var.vpc_id

  ingress {
    description     = "AMQPS from the machine"
    from_port       = 5671
    to_port         = 5671
    protocol        = "tcp"
    security_groups = [aws_security_group.service.id]
  }
}
` : ''}`;

  const iam = `data "aws_iam_policy_document" "ec2_assume" {
  statement {
    actions = ["sts:AssumeRole"]

    principals {
      type        = "Service"
      identifiers = ["ec2.amazonaws.com"]
    }
  }
}

resource "aws_iam_role" "instance" {
  name               = "\${local.name}-vm"
  assume_role_policy = data.aws_iam_policy_document.ec2_assume.json
}

# Session Manager instead of SSH (no key pair, no port 22).
resource "aws_iam_role_policy_attachment" "ssm_core" {
  role       = aws_iam_role.instance.name
  policy_arn = "arn:aws:iam::aws:policy/AmazonSSMManagedInstanceCore"
}

resource "aws_iam_role_policy_attachment" "ecr_read" {
  role       = aws_iam_role.instance.name
  policy_arn = "arn:aws:iam::aws:policy/AmazonEC2ContainerRegistryReadOnly"
}

resource "aws_iam_role_policy" "secrets" {
  name = "read-secrets"
  role = aws_iam_role.instance.id

  policy = jsonencode({
    Version = "2012-10-17"
    Statement = [{
      Effect   = "Allow"
      Action   = ["secretsmanager:GetSecretValue"]
      Resource = [for s in aws_secretsmanager_secret.this : s.arn]
    }]
  })
}

resource "aws_iam_instance_profile" "instance" {
  name = "\${local.name}-vm"
  role = aws_iam_role.instance.name
}
`;

  const service = `resource "aws_instance" "app" {
${hattrs([
    ['ami', 'data.aws_ssm_parameter.al2023.value'],
    ['instance_type', 'var.instance_type'],
    ['subnet_id', 'var.subnet_id'],
    ['vpc_security_group_ids', '[aws_security_group.service.id]'],
    ['iam_instance_profile', 'aws_iam_instance_profile.instance.name'],
    ['user_data_replace_on_change', 'true']
  ], 2)}

  user_data = ${templateVars([['region', 'var.region'], ['secret_prefix', 'local.name']])}

  # IMDSv2 only.
  metadata_options {
    http_tokens   = "required"
    http_endpoint = "enabled"
  }

  root_block_device {
    volume_size = var.root_volume_gb
    volume_type = "gp3"
    encrypted   = true
  }

  # The secrets exist before the machine reads them at boot.
  depends_on = [aws_secretsmanager_secret_version.this]

  tags = { Name = local.name }
}

resource "aws_eip" "app" {
  instance = aws_instance.app.id
  domain   = "vpc"
}
`;

  const outputs = `output "url" {
  description = "Address of the service (point var.domain's DNS record at public_ip for HTTPS)."
  value       = var.domain == "" ? "http://\${aws_eip.app.public_ip}" : "https://\${var.domain}"
}

output "public_ip" {
  description = "Elastic IP of the machine."
  value       = aws_eip.app.public_ip
}

output "instance_id" {
  description = "Connect with: aws ssm start-session --target <instance_id>."
  value       = aws_instance.app.id
}

output "database_endpoint" {
  value = aws_db_instance.this.address
}
`;

  const tfvars = deploy.environments.flatMap(env => {
    const prod = env === 'prod';
    return [{
      filename: `${dir}/environments/${env}.tfvars`,
      content: `${hattrs([
        ['environment', hstr(env)],
        ['region', hstr(deploy.region)],
        ['image', hstr(`<account>.dkr.ecr.${deploy.region}.amazonaws.com/${spec.name}:<tag>`)],
        ['vpc_id', hstr('vpc-<id>')],
        ['subnet_id', hstr('subnet-<public>')],
        ['private_subnet_ids', hlist(['subnet-<private-a>', 'subnet-<private-b>'])],
        ['instance_type', hstr(prod ? 't3.medium' : 't3.small')],
        ['db_instance_class', hstr(prod ? 'db.t4g.small' : 'db.t4g.micro')],
        ...(mq ? [['mq_instance_type', hstr('mq.t3.micro')], ['mq_deployment_mode', hstr('SINGLE_INSTANCE')]] as [string, string][] : []),
        ['domain', hstr(prod ? `${spec.name}.example.com` : '')]
      ], 0)}\n`
    }];
  });

  return [
    ...pick(base, dir, ['versions.tf', 'database.tf', 'broker.tf', 'secrets.tf']),
    ...base.filter(f => f.filename.startsWith(`${dir}/environments/`) && f.filename.endsWith('.tfbackend')),
    ...tfvars,
    { filename: `${dir}/variables.tf`, content: variables },
    { filename: `${dir}/main.tf`, content: main },
    { filename: `${dir}/network.tf`, content: network },
    { filename: `${dir}/iam.tf`, content: iam },
    { filename: `${dir}/service.tf`, content: service },
    { filename: `${dir}/outputs.tf`, content: outputs },
    { filename: `${dir}/vm-init.sh.tftpl`, content: initScript(spec, 'aws') }
  ];
}

// ---------------------------------------------------------------------------
// GCP: Compute Engine
// ---------------------------------------------------------------------------

function gcpVm(spec: ServiceSpec, deploy: DeployConfig, base: TerraformFile[]): TerraformFile[] {
  const dir = 'deploy/terraform/gcp';
  const baseVariables = base.find(f => f.filename === `${dir}/variables.tf`)!.content;
  const variables = withoutVariables(baseVariables, ['allow_unauthenticated', 'cpu', 'memory', 'min_instances', 'max_instances']) + `
variable "zone" {
  description = "Zone of the machine (in var.region)."
  type        = string
  default     = ${hstr(`${deploy.region}-a`)}
}

variable "machine_type" {
  description = "Compute Engine machine type."
  type        = string
  default     = "e2-small"
}

${allowedCidrs}
${domainVariable}`;

  const service = `resource "google_project_iam_member" "artifact_reader" {
  project = var.project_id
  role    = "roles/artifactregistry.reader"
  member  = google_service_account.service.member
}

resource "google_compute_address" "app" {
  name   = local.name
  region = var.region
}

resource "google_compute_firewall" "web" {
  name          = "\${local.name}-web"
  network       = var.network
  source_ranges = var.allowed_cidrs
  target_tags   = [local.name]

  allow {
    protocol = "tcp"
    ports    = ["80", "443"]
  }
}

resource "google_compute_instance" "app" {
  name         = local.name
  machine_type = var.machine_type
  zone         = var.zone
  tags         = [local.name]
  labels       = local.labels

  boot_disk {
    initialize_params {
      image = "debian-cloud/debian-12"
      size  = 30
    }
  }

  network_interface {
    subnetwork = var.subnetwork

    access_config {
      nat_ip = google_compute_address.app.address
    }
  }

  service_account {
    email  = google_service_account.service.email
    scopes = ["cloud-platform"]
  }

  shielded_instance_config {
    enable_secure_boot = true
  }

  metadata = {
    enable-oslogin = "TRUE"
  }

  metadata_startup_script = ${templateVars([['secret_prefix', 'local.name']])}

  depends_on = [google_secret_manager_secret_version.this, google_secret_manager_secret_iam_member.service]
}
`;

  const outputs = `output "url" {
  description = "Address of the service (point var.domain's DNS record at public_ip for HTTPS)."
  value       = var.domain == "" ? "http://\${google_compute_address.app.address}" : "https://\${var.domain}"
}

output "public_ip" {
  value = google_compute_address.app.address
}

output "instance" {
  description = "Connect with: gcloud compute ssh <instance> --zone <zone> (OS Login)."
  value       = google_compute_instance.app.name
}
`;

  return [
    ...pick(base, dir, ['versions.tf', 'main.tf', 'database.tf', 'pubsub.tf', 'secrets.tf']),
    ...base.filter(f => f.filename.startsWith(`${dir}/environments/`)),
    { filename: `${dir}/variables.tf`, content: variables },
    { filename: `${dir}/service.tf`, content: service },
    { filename: `${dir}/outputs.tf`, content: outputs },
    { filename: `${dir}/vm-init.sh.tftpl`, content: initScript(spec, 'gcp') }
  ];
}

// ---------------------------------------------------------------------------
// Azure: Linux virtual machine
// ---------------------------------------------------------------------------

function azureVm(spec: ServiceSpec, deploy: DeployConfig, base: TerraformFile[]): TerraformFile[] {
  const dir = 'deploy/terraform/azure';
  const baseVariables = base.find(f => f.filename === `${dir}/variables.tf`)!.content;
  const variables = withoutVariables(baseVariables, ['container_apps_subnet_id', 'cpu', 'memory', 'min_replicas', 'max_replicas']) + `
variable "vm_subnet_id" {
  description = "Subnet of the machine's network interface."
  type        = string
}

variable "vm_size" {
  description = "Virtual machine size."
  type        = string
  default     = "Standard_B2s"
}

variable "admin_ssh_public_key" {
  description = "SSH public key of the admin user (required by Azure; port 22 stays closed, use Azure Bastion or Run Command)."
  type        = string
}

${allowedCidrs}
${domainVariable}`;

  const service = `resource "azurerm_public_ip" "app" {
  name                = "pip-\${local.name}"
  location            = azurerm_resource_group.this.location
  resource_group_name = azurerm_resource_group.this.name
  allocation_method   = "Static"
  sku                 = "Standard"
  tags                = local.tags
}

resource "azurerm_network_security_group" "app" {
  name                = "nsg-\${local.name}"
  location            = azurerm_resource_group.this.location
  resource_group_name = azurerm_resource_group.this.name
  tags                = local.tags

  security_rule {
    name                       = "web"
    priority                   = 100
    direction                  = "Inbound"
    access                     = "Allow"
    protocol                   = "Tcp"
    source_port_range          = "*"
    destination_port_ranges    = ["80", "443"]
    source_address_prefixes    = var.allowed_cidrs
    destination_address_prefix = "*"
  }
}

resource "azurerm_network_interface" "app" {
  name                = "nic-\${local.name}"
  location            = azurerm_resource_group.this.location
  resource_group_name = azurerm_resource_group.this.name
  tags                = local.tags

  ip_configuration {
    name                          = "primary"
    subnet_id                     = var.vm_subnet_id
    private_ip_address_allocation = "Dynamic"
    public_ip_address_id          = azurerm_public_ip.app.id
  }
}

resource "azurerm_network_interface_security_group_association" "app" {
  network_interface_id      = azurerm_network_interface.app.id
  network_security_group_id = azurerm_network_security_group.app.id
}

resource "azurerm_linux_virtual_machine" "app" {
  name                  = "vm-\${local.name}"
  location              = azurerm_resource_group.this.location
  resource_group_name   = azurerm_resource_group.this.name
  size                  = var.vm_size
  admin_username        = "azureuser"
  network_interface_ids = [azurerm_network_interface.app.id]
  tags                  = local.tags

  custom_data = base64encode(${templateVars([['identity_client_id', 'azurerm_user_assigned_identity.app.client_id'], ['vault_name', 'azurerm_key_vault.this.name']])})

  admin_ssh_key {
    username   = "azureuser"
    public_key = var.admin_ssh_public_key
  }

  identity {
    type         = "UserAssigned"
    identity_ids = [azurerm_user_assigned_identity.app.id]
  }

  os_disk {
    caching              = "ReadWrite"
    storage_account_type = "StandardSSD_LRS"
  }

  source_image_reference {
    publisher = "Canonical"
    offer     = "ubuntu-24_04-lts"
    sku       = "server"
    version   = "latest"
  }

  depends_on = [azurerm_key_vault_secret.this, azurerm_role_assignment.app_secrets]
}
`;

  const outputs = `output "url" {
  description = "Address of the service (point var.domain's DNS record at public_ip for HTTPS)."
  value       = var.domain == "" ? "http://\${azurerm_public_ip.app.ip_address}" : "https://\${var.domain}"
}

output "public_ip" {
  value = azurerm_public_ip.app.ip_address
}
`;

  return [
    ...pick(base, dir, ['versions.tf', 'main.tf', 'database.tf', 'servicebus.tf', 'secrets.tf']),
    ...base.filter(f => f.filename.startsWith(`${dir}/environments/`)),
    { filename: `${dir}/variables.tf`, content: variables },
    { filename: `${dir}/service.tf`, content: service },
    { filename: `${dir}/outputs.tf`, content: outputs },
    { filename: `${dir}/vm-init.sh.tftpl`, content: initScript(spec, 'azure') }
  ];
}

/** The "vm" variant of a cloud's Terraform module, built from its "containers" module (`base`). */
export function renderTerraformVm(spec: ServiceSpec, deploy: DeployConfig, base: TerraformFile[]): TerraformFile[] {
  return { aws: awsVm, gcp: gcpVm, azure: azureVm }[deploy.cloud](spec, deploy, base);
}
