/* ==========================================================================
   gherkin-ai-cli - Helm chart for Kubernetes (EKS, GKE, AKS)

   Deployment with the generated probes, Service, HPA, PodDisruptionBudget,
   optional Ingress, ServiceAccount annotated for the cloud's workload
   identity, and the separate outbox relay where the stack needs one.
   Secrets come from an existing Kubernetes Secret (External Secrets Operator
   or the Secrets Store CSI driver, fed by the cloud secret manager), never
   from values files. Verified by scripts/golden-build.js (helm): lint and
   template for every environment.
   ========================================================================== */

import type { DeployConfig, ServiceSpec } from './service-spec';
import type { TerraformFile } from './terraform-aws';

const yamlStr = (s: string) => JSON.stringify(s);

const WORKLOAD_IDENTITY: Record<DeployConfig['cloud'], { annotation: string; example: string; podLabels?: Record<string, string> }> = {
  aws: { annotation: 'eks.amazonaws.com/role-arn', example: 'arn:aws:iam::<account>:role/<service>-<env>' },
  gcp: { annotation: 'iam.gke.io/gcp-service-account', example: '<service>-<env>@<project>.iam.gserviceaccount.com' },
  azure: { annotation: 'azure.workload.identity/client-id', example: '<user-assigned-identity-client-id>', podLabels: { 'azure.workload.identity/use': 'true' } }
};

export function renderHelmChart(spec: ServiceSpec, deploy: DeployConfig, cliVersion: string): TerraformFile[] {
  const dir = `deploy/helm/${spec.name}`;
  const wi = WORKLOAD_IDENTITY[deploy.cloud];
  const relay = spec.relayCommand;

  const chart = `apiVersion: v2
name: ${spec.name}
description: ${spec.name} (${spec.stackLabel}) generated by gherkin-ai ${cliVersion}
type: application
version: 0.1.0
appVersion: "0.1.0"
`;

  const values = `# Default values of ${spec.name}. Override per environment with values-<env>.yaml.

image:
  repository: ${yamlStr(`<registry>/${spec.name}`)}
  # Defaults to the chart appVersion; deploy an immutable tag (the git SHA).
  tag: ""
  pullPolicy: IfNotPresent

replicaCount: 2

# Plain configuration of the container.
env:
${Object.entries(spec.env).map(([k, v]) => `  ${k}: ${yamlStr(v)}`).join('\n')}
  # Traces over OTLP/HTTP to the cluster's OpenTelemetry collector (agent DaemonSet or gateway):
  # OTEL_EXPORTER_OTLP_ENDPOINT: "http://otel-collector.observability:4318"

# Existing Secret with ${spec.secrets.map(s => s.name).join(', ')}.
# Create it with External Secrets Operator or the Secrets Store CSI driver from the cloud secret manager.
existingSecret: ${yamlStr(`${spec.name}-secrets`)}
secretKeys:
${spec.secrets.map(s => `  - ${s.name}`).join('\n')}

containerPort: ${spec.port}

probes:
  liveness: ${yamlStr(spec.health.live)}
  readiness: ${yamlStr(spec.health.ready)}

service:
  type: ClusterIP
  port: 80

serviceAccount:
  create: true
  name: ""
  # Workload identity (${deploy.cloud}): ${wi.annotation}: ${wi.example}
  annotations: {}

podLabels: {}

resources:
  requests:
    cpu: 250m
    memory: 512Mi
  limits:
    memory: 1Gi

autoscaling:
  enabled: true
  minReplicas: 2
  maxReplicas: 10
  targetCPUUtilizationPercentage: 70

podDisruptionBudget:
  enabled: true
  minAvailable: 1

ingress:
  enabled: false
  className: ""
  annotations: {}
  host: ""
  tlsSecretName: ""

podSecurityContext:
  runAsNonRoot: true
  seccompProfile:
    type: RuntimeDefault

securityContext:
  allowPrivilegeEscalation: false
  capabilities:
    drop: ["ALL"]
${relay ? `
# The outbox relay of this stack is a separate process.
relay:
  enabled: true
  command: [${relay.map(yamlStr).join(', ')}]
  resources:
    requests:
      cpu: 100m
      memory: 256Mi
    limits:
      memory: 512Mi
` : ''}`;

  const envValues = (env: string) => {
    const prod = env === 'prod';
    return `# ${env}: kubectl context of the ${env} cluster; helm upgrade --install ${spec.name} . -f values-${env}.yaml --set image.tag=<git-sha>
replicaCount: ${prod ? 3 : 1}

env:
  OTEL_RESOURCE_ATTRIBUTES: ${yamlStr(`deployment.environment.name=${env}`)}

serviceAccount:
  annotations:
    ${wi.annotation}: ${yamlStr(wi.example.replace('<env>', env))}
${wi.podLabels ? `
podLabels:
${Object.entries(wi.podLabels).map(([k, v]) => `  ${k}: ${yamlStr(v)}`).join('\n')}
` : ''}
autoscaling:
  enabled: ${prod ? 'true' : 'false'}
  minReplicas: ${prod ? 3 : 1}
  maxReplicas: ${prod ? 20 : 3}

podDisruptionBudget:
  enabled: ${prod ? 'true' : 'false'}
`;
  };

  const helpers = `{{- define "app.fullname" -}}
{{- if contains .Chart.Name .Release.Name -}}
{{- .Release.Name | trunc 63 | trimSuffix "-" -}}
{{- else -}}
{{- printf "%s-%s" .Release.Name .Chart.Name | trunc 63 | trimSuffix "-" -}}
{{- end -}}
{{- end -}}

{{- define "app.labels" -}}
app.kubernetes.io/name: {{ .Chart.Name }}
app.kubernetes.io/instance: {{ .Release.Name }}
app.kubernetes.io/version: {{ .Chart.AppVersion | quote }}
app.kubernetes.io/managed-by: {{ .Release.Service }}
helm.sh/chart: {{ printf "%s-%s" .Chart.Name .Chart.Version }}
{{- end -}}

{{- define "app.selectorLabels" -}}
app.kubernetes.io/name: {{ .Chart.Name }}
app.kubernetes.io/instance: {{ .Release.Name }}
{{- end -}}

{{- define "app.serviceAccountName" -}}
{{- if .Values.serviceAccount.create -}}
{{- default (include "app.fullname" .) .Values.serviceAccount.name -}}
{{- else -}}
{{- default "default" .Values.serviceAccount.name -}}
{{- end -}}
{{- end -}}

{{/* Environment of every container: plain values, then the keys of the existing Secret. */}}
{{- define "app.env" -}}
{{- range $name, $value := .Values.env }}
- name: {{ $name }}
  value: {{ $value | quote }}
{{- end }}
{{- range .Values.secretKeys }}
- name: {{ . }}
  valueFrom:
    secretKeyRef:
      name: {{ $.Values.existingSecret }}
      key: {{ . }}
{{- end }}
{{- end -}}
`;

  const deployment = `apiVersion: apps/v1
kind: Deployment
metadata:
  name: {{ include "app.fullname" . }}
  labels:
    {{- include "app.labels" . | nindent 4 }}
spec:
  {{- if not .Values.autoscaling.enabled }}
  replicas: {{ .Values.replicaCount }}
  {{- end }}
  selector:
    matchLabels:
      {{- include "app.selectorLabels" . | nindent 6 }}
  template:
    metadata:
      labels:
        {{- include "app.selectorLabels" . | nindent 8 }}
        {{- with .Values.podLabels }}
        {{- toYaml . | nindent 8 }}
        {{- end }}
    spec:
      serviceAccountName: {{ include "app.serviceAccountName" . }}
      securityContext:
        {{- toYaml .Values.podSecurityContext | nindent 8 }}
      containers:
        - name: app
          image: "{{ .Values.image.repository }}:{{ .Values.image.tag | default .Chart.AppVersion }}"
          imagePullPolicy: {{ .Values.image.pullPolicy }}
          securityContext:
            {{- toYaml .Values.securityContext | nindent 12 }}
          ports:
            - name: http
              containerPort: {{ .Values.containerPort }}
              protocol: TCP
          env:
            {{- include "app.env" . | nindent 12 }}
          startupProbe:
            httpGet:
              path: {{ .Values.probes.readiness }}
              port: http
            periodSeconds: 5
            failureThreshold: 36
          livenessProbe:
            httpGet:
              path: {{ .Values.probes.liveness }}
              port: http
            periodSeconds: 10
          readinessProbe:
            httpGet:
              path: {{ .Values.probes.readiness }}
              port: http
            periodSeconds: 5
          resources:
            {{- toYaml .Values.resources | nindent 12 }}
`;

  const relayTemplate = `{{- if and .Values.relay .Values.relay.enabled }}
apiVersion: apps/v1
kind: Deployment
metadata:
  name: {{ include "app.fullname" . }}-relay
  labels:
    {{- include "app.labels" . | nindent 4 }}
    app.kubernetes.io/component: outbox-relay
spec:
  # One publisher: the relay claims rows with FOR UPDATE SKIP LOCKED, more replicas only add throughput.
  replicas: 1
  selector:
    matchLabels:
      {{- include "app.selectorLabels" . | nindent 6 }}
      app.kubernetes.io/component: outbox-relay
  template:
    metadata:
      labels:
        {{- include "app.selectorLabels" . | nindent 8 }}
        app.kubernetes.io/component: outbox-relay
        {{- with .Values.podLabels }}
        {{- toYaml . | nindent 8 }}
        {{- end }}
    spec:
      serviceAccountName: {{ include "app.serviceAccountName" . }}
      securityContext:
        {{- toYaml .Values.podSecurityContext | nindent 8 }}
      containers:
        - name: relay
          image: "{{ .Values.image.repository }}:{{ .Values.image.tag | default .Chart.AppVersion }}"
          imagePullPolicy: {{ .Values.image.pullPolicy }}
          command:
            {{- toYaml .Values.relay.command | nindent 12 }}
          securityContext:
            {{- toYaml .Values.securityContext | nindent 12 }}
          env:
            {{- include "app.env" . | nindent 12 }}
          resources:
            {{- toYaml .Values.relay.resources | nindent 12 }}
{{- end }}
`;

  const serviceYaml = `apiVersion: v1
kind: Service
metadata:
  name: {{ include "app.fullname" . }}
  labels:
    {{- include "app.labels" . | nindent 4 }}
spec:
  type: {{ .Values.service.type }}
  ports:
    - port: {{ .Values.service.port }}
      targetPort: http
      protocol: TCP
      name: http
  selector:
    {{- include "app.selectorLabels" . | nindent 4 }}
`;

  const serviceAccount = `{{- if .Values.serviceAccount.create }}
apiVersion: v1
kind: ServiceAccount
metadata:
  name: {{ include "app.serviceAccountName" . }}
  labels:
    {{- include "app.labels" . | nindent 4 }}
  {{- with .Values.serviceAccount.annotations }}
  annotations:
    {{- toYaml . | nindent 4 }}
  {{- end }}
{{- end }}
`;

  const hpa = `{{- if .Values.autoscaling.enabled }}
apiVersion: autoscaling/v2
kind: HorizontalPodAutoscaler
metadata:
  name: {{ include "app.fullname" . }}
  labels:
    {{- include "app.labels" . | nindent 4 }}
spec:
  scaleTargetRef:
    apiVersion: apps/v1
    kind: Deployment
    name: {{ include "app.fullname" . }}
  minReplicas: {{ .Values.autoscaling.minReplicas }}
  maxReplicas: {{ .Values.autoscaling.maxReplicas }}
  metrics:
    - type: Resource
      resource:
        name: cpu
        target:
          type: Utilization
          averageUtilization: {{ .Values.autoscaling.targetCPUUtilizationPercentage }}
{{- end }}
`;

  const pdb = `{{- if .Values.podDisruptionBudget.enabled }}
apiVersion: policy/v1
kind: PodDisruptionBudget
metadata:
  name: {{ include "app.fullname" . }}
  labels:
    {{- include "app.labels" . | nindent 4 }}
spec:
  minAvailable: {{ .Values.podDisruptionBudget.minAvailable }}
  selector:
    matchLabels:
      {{- include "app.selectorLabels" . | nindent 6 }}
{{- end }}
`;

  const ingress = `{{- if .Values.ingress.enabled }}
apiVersion: networking.k8s.io/v1
kind: Ingress
metadata:
  name: {{ include "app.fullname" . }}
  labels:
    {{- include "app.labels" . | nindent 4 }}
  {{- with .Values.ingress.annotations }}
  annotations:
    {{- toYaml . | nindent 4 }}
  {{- end }}
spec:
  {{- with .Values.ingress.className }}
  ingressClassName: {{ . }}
  {{- end }}
  {{- if .Values.ingress.tlsSecretName }}
  tls:
    - hosts: [{{ .Values.ingress.host | quote }}]
      secretName: {{ .Values.ingress.tlsSecretName }}
  {{- end }}
  rules:
    - host: {{ .Values.ingress.host | quote }}
      http:
        paths:
          - path: /
            pathType: Prefix
            backend:
              service:
                name: {{ include "app.fullname" . }}
                port:
                  name: http
{{- end }}
`;

  const notes = `{{ include "app.fullname" . }} is deployed.

  kubectl get pods -l app.kubernetes.io/instance={{ .Release.Name }}
  kubectl port-forward svc/{{ include "app.fullname" . }} 8080:{{ .Values.service.port }}
  curl -f http://localhost:8080{{ .Values.probes.readiness }}

The Secret {{ .Values.existingSecret }} must exist with: {{ join ", " .Values.secretKeys }}.
`;

  return [
    { filename: `${dir}/Chart.yaml`, content: chart },
    { filename: `${dir}/values.yaml`, content: values },
    ...deploy.environments.map(env => ({ filename: `${dir}/values-${env}.yaml`, content: envValues(env) })),
    { filename: `${dir}/.helmignore`, content: '.git/\n*.tgz\n.DS_Store\n' },
    { filename: `${dir}/templates/_helpers.tpl`, content: helpers },
    { filename: `${dir}/templates/deployment.yaml`, content: deployment },
    ...(relay ? [{ filename: `${dir}/templates/relay-deployment.yaml`, content: relayTemplate }] : []),
    { filename: `${dir}/templates/service.yaml`, content: serviceYaml },
    { filename: `${dir}/templates/serviceaccount.yaml`, content: serviceAccount },
    { filename: `${dir}/templates/hpa.yaml`, content: hpa },
    { filename: `${dir}/templates/pdb.yaml`, content: pdb },
    { filename: `${dir}/templates/ingress.yaml`, content: ingress },
    { filename: `${dir}/templates/NOTES.txt`, content: notes }
  ];
}
