import { DomainModel, cucumberExpression } from './domain-model';
import { JVM_VERSIONS } from '../versions';

export interface JavaFile {
  filename: string;
  content: string;
}

const js = (s: string) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const toJavaMethod = (id: string) => id.replace(/_([a-z0-9])/g, (_m, c: string) => c.toUpperCase());

export function javaPackagePath(pkg: string): string {
  return pkg.replace(/\./g, '/');
}

export function renderJavaKernel(m: DomainModel, pkg: string): JavaFile[] {
  const dir = `src/main/java/${javaPackagePath(pkg)}/domain`;
  const p = `package ${pkg}.domain;\n\n`;
  return [
    {
      filename: `${dir}/DomainValidationException.java`,
      content: `${p}public class DomainValidationException extends RuntimeException {
    public DomainValidationException(String message) {
        super(message);
    }
}
`
    },
    {
      filename: `${dir}/${m.pascal}State.java`,
      content: `${p}public enum ${m.pascal}State {
    ${m.states.join(',\n    ')}
}
`
    },
    {
      filename: `${dir}/${m.pascal}EventType.java`,
      content: `${p}public enum ${m.pascal}EventType {
    ${m.events.join(',\n    ')}
}
`
    },
    {
      filename: `${dir}/${m.pascal}Command.java`,
      content: `${p}import java.util.Map;

public record ${m.pascal}Command(String id, Map<String, Object> payload) {
    public ${m.pascal}Command(String id) {
        this(id, Map.of());
    }
}
`
    },
    {
      filename: `${dir}/${m.pascal}DomainEvent.java`,
      content: `${p}import java.time.Instant;
import java.util.Map;

public record ${m.pascal}DomainEvent(${m.pascal}EventType type, String aggregateId, long version, Instant occurredOn, Map<String, Object> payload) {
}
`
    },
    {
      filename: `${dir}/${m.pascal}Aggregate.java`,
      content: `${p}import java.time.Instant;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Map;

/**
 * Domain kernel for "${m.feature}" (generated by gherkin-ai).
 * Pure domain logic: no framework, no I/O. Extend the command handlers with your business rules.
 */
public class ${m.pascal}Aggregate {
    private final String id;
    private ${m.pascal}State state = ${m.pascal}State.${m.initialState};
    private long version;
    private final List<${m.pascal}DomainEvent> pendingEvents = new ArrayList<>();

    public ${m.pascal}Aggregate(String id) {
        if (id == null || id.isBlank()) throw new DomainValidationException("${m.pascal} id is required");
        this.id = id;
    }

    /** Rebuilds an aggregate from persisted state; no events are recorded. */
    public static ${m.pascal}Aggregate restore(String id, ${m.pascal}State state, long version) {
        var aggregate = new ${m.pascal}Aggregate(id);
        aggregate.state = state;
        aggregate.version = version;
        return aggregate;
    }

    public String getId() { return id; }
    public ${m.pascal}State getState() { return state; }
    public long getVersion() { return version; }

    /** Events recorded since the aggregate was loaded (to be saved via the outbox). */
    public List<${m.pascal}DomainEvent> getPendingEvents() { return Collections.unmodifiableList(pendingEvents); }
${m.commands.map(c => `
    public ${m.pascal}DomainEvent ${c.method}(${m.pascal}Command command) {
        assertValid(command);
        return record(${m.pascal}EventType.${c.event}, command.payload());
    }`).join('\n')}

    private void assertValid(${m.pascal}Command command) {
        if (command == null || command.id() == null || command.id().isBlank()) throw new DomainValidationException("Command id is required");
        if (!command.id().equals(id)) throw new DomainValidationException("Command targets " + command.id() + ", not " + id);
    }

    private ${m.pascal}DomainEvent record(${m.pascal}EventType type, Map<String, Object> payload) {
        version += 1;
        var event = new ${m.pascal}DomainEvent(type, id, version, Instant.now(), payload == null ? Map.of() : payload);
        pendingEvents.add(event);
        return event;
    }
}
`
    }
  ];
}

export function renderJavaKernelTests(m: DomainModel, pkg: string): JavaFile[] {
  const base = `src/test/java/${javaPackagePath(pkg)}`;
  return [
    {
      filename: `${base}/domain/${m.pascal}AggregateTest.java`,
      content: `package ${pkg}.domain;

import static org.junit.jupiter.api.Assertions.*;

import org.junit.jupiter.api.Test;

class ${m.pascal}AggregateTest {

    @Test
    void startsInTheInitialStateWithNoEvents() {
        var aggregate = new ${m.pascal}Aggregate("agg-1");
        assertEquals(${m.pascal}State.${m.initialState}, aggregate.getState());
        assertEquals(0, aggregate.getVersion());
        assertTrue(aggregate.getPendingEvents().isEmpty());
    }

    @Test
    void rejectsAnAggregateWithoutId() {
        assertThrows(DomainValidationException.class, () -> new ${m.pascal}Aggregate(""));
    }
${m.commands.map(c => `
    @Test
    void ${c.method}Records${c.event}AndBumpsTheVersion() {
        var aggregate = new ${m.pascal}Aggregate("agg-1");
        var event = aggregate.${c.method}(new ${m.pascal}Command("agg-1"));
        assertEquals(${m.pascal}EventType.${c.event}, event.type());
        assertEquals(1, event.version());
        assertEquals(1, aggregate.getVersion());
        assertEquals(1, aggregate.getPendingEvents().size());
    }

    @Test
    void ${c.method}RejectsACommandWithoutId() {
        var aggregate = new ${m.pascal}Aggregate("agg-1");
        assertThrows(DomainValidationException.class, () -> aggregate.${c.method}(new ${m.pascal}Command("")));
        assertTrue(aggregate.getPendingEvents().isEmpty());
    }`).join('\n')}
}
`
    },
    {
      filename: `${base}/bdd/RunCucumberTest.java`,
      content: `package ${pkg}.bdd;

import static io.cucumber.junit.platform.engine.Constants.GLUE_PROPERTY_NAME;
import static io.cucumber.junit.platform.engine.Constants.PLUGIN_PROPERTY_NAME;

import org.junit.platform.suite.api.ConfigurationParameter;
import org.junit.platform.suite.api.IncludeEngines;
import org.junit.platform.suite.api.SelectClasspathResource;
import org.junit.platform.suite.api.Suite;

/** Runs the feature files (copied from ./features as test resources). Pending steps are reported as skipped. */
@Suite(failIfNoTests = false) // the runtime integration run (tag "integration") selects no scenarios
@IncludeEngines("cucumber")
@SelectClasspathResource("features")
@ConfigurationParameter(key = GLUE_PROPERTY_NAME, value = "${pkg}.bdd")
@ConfigurationParameter(key = PLUGIN_PROPERTY_NAME, value = "pretty")
public class RunCucumberTest {
}
`
    },
    {
      filename: `${base}/bdd/${m.pascal}Steps.java`,
      content: `package ${pkg}.bdd;

import ${pkg}.domain.${m.pascal}Aggregate;
import io.cucumber.java.Before;
import org.opentest4j.TestAbortedException;
import io.cucumber.java.en.Given;
import io.cucumber.java.en.Then;
import io.cucumber.java.en.When;

/** Step definitions for "${m.feature}" (generated by gherkin-ai): wired to the feature, pending until implemented.
 *  Pending steps abort (reported as skipped) instead of failing the build. */
public class ${m.pascal}Steps {
    private ${m.pascal}Aggregate aggregate;

    @Before
    public void resetAggregate() {
        aggregate = new ${m.pascal}Aggregate("scenario-aggregate");
    }
${m.steps.map(s => `
    @${s.keyword}(${js(cucumberExpression(s.text))})
    public void ${toJavaMethod(s.id)}() {
        // Pending: drive the aggregate (or the HTTP API) and assert the outcome.
        throw new TestAbortedException("Pending step: implement it, then remove this line");
    }`).join('\n')}
}
`
    }
  ];
}

export function renderSpringApplication(pkg: string): JavaFile {
  return {
    filename: `src/main/java/${javaPackagePath(pkg)}/Application.java`,
    content: `package ${pkg};

import org.springframework.boot.SpringApplication;
import org.springframework.boot.autoconfigure.SpringBootApplication;
import org.springframework.scheduling.annotation.EnableScheduling;

@SpringBootApplication
@EnableScheduling
public class Application {
    public static void main(String[] args) {
        SpringApplication.run(Application.class, args);
    }
}
`
  };
}

/** Azure SDK BOM, imported when the Service Bus adapter is generated (stack.messaging "servicebus"). */
const AZURE_BOM = `
      <dependency>
        <groupId>com.azure</groupId>
        <artifactId>azure-sdk-bom</artifactId>
        <version>${JVM_VERSIONS.azureSdkBom}</version>
        <type>pom</type>
        <scope>import</scope>
      </dependency>`;

/**
 * Service Bus client and Entra ID credentials. The Netty HTTP transport is swapped for the JDK one so the SDK
 * does not depend on the Netty / Reactor Netty versions the framework BOM pins.
 */
/** Kafka client of the Kafka adapter (stack.messaging "kafka"); its version comes from the framework BOM. */
const KAFKA_DEPS = `
    <dependency>
      <groupId>org.apache.kafka</groupId>
      <artifactId>kafka-clients</artifactId>
    </dependency>`;

const AZURE_DEPS = ['azure-messaging-servicebus', 'azure-identity'].map(a => `
    <dependency>
      <groupId>com.azure</groupId>
      <artifactId>${a}</artifactId>
      <exclusions>
        <exclusion>
          <groupId>com.azure</groupId>
          <artifactId>azure-core-http-netty</artifactId>
        </exclusion>
      </exclusions>
    </dependency>`).join('') + `
    <dependency>
      <groupId>com.azure</groupId>
      <artifactId>azure-core-http-jdk-httpclient</artifactId>
    </dependency>`;

/**
 * Maven build of a Quarkus service: the runtime kernel (plain JDBC + amqp-client + OpenTelemetry SDK) on
 * Agroal, Quarkus REST and the scheduler. OpenTelemetry is imported before the Quarkus BOM so the kernel
 * gets the API version it is written against; the quarkus-opentelemetry extension is not used (one SDK).
 */
export function renderQuarkusPom(artifactId: string, groupId = 'com.example', { serviceBus = false, kafka = false } = {}): string {
  const dep = (g: string, a: string, extra = '') => `    <dependency>\n      <groupId>${g}</groupId>\n      <artifactId>${a}</artifactId>${extra}\n    </dependency>`;
  const test = '\n      <scope>test</scope>';
  return `<?xml version="1.0" encoding="UTF-8"?>
<project xmlns="http://maven.apache.org/POM/4.0.0" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
  xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 https://maven.apache.org/xsd/maven-4.0.0.xsd">
  <modelVersion>4.0.0</modelVersion>

  <groupId>${groupId}</groupId>
  <artifactId>${artifactId}</artifactId>
  <version>0.0.1-SNAPSHOT</version>

  <properties>
    <maven.compiler.release>${JVM_VERSIONS.quarkusJava}</maven.compiler.release>
    <project.build.sourceEncoding>UTF-8</project.build.sourceEncoding>
    <quarkus.platform.version>${JVM_VERSIONS.quarkus}</quarkus.platform.version>
    <cucumber.version>${JVM_VERSIONS.cucumber}</cucumber.version>
    <opentelemetry.version>${JVM_VERSIONS.openTelemetry}</opentelemetry.version>
    <!-- Runtime integration tests (tag "integration") need DATABASE_URL / AMQP_URL: mvn test -Pintegration -->
    <test.groups></test.groups>
    <test.excludedGroups>integration</test.excludedGroups>
  </properties>

  <dependencyManagement>
    <dependencies>
      <dependency>
        <groupId>io.opentelemetry</groupId>
        <artifactId>opentelemetry-bom</artifactId>
        <version>\${opentelemetry.version}</version>
        <type>pom</type>
        <scope>import</scope>
      </dependency>
      <!-- Incubator artifacts (pulled by quarkus-scheduler) must match the API version too. -->
      <dependency>
        <groupId>io.opentelemetry</groupId>
        <artifactId>opentelemetry-bom-alpha</artifactId>
        <version>\${opentelemetry.version}-alpha</version>
        <type>pom</type>
        <scope>import</scope>
      </dependency>
      <dependency>
        <groupId>io.quarkus.platform</groupId>
        <artifactId>quarkus-bom</artifactId>
        <version>\${quarkus.platform.version}</version>
        <type>pom</type>
        <scope>import</scope>
      </dependency>
      <dependency>
        <groupId>io.cucumber</groupId>
        <artifactId>cucumber-bom</artifactId>
        <version>\${cucumber.version}</version>
        <type>pom</type>
        <scope>import</scope>
      </dependency>${serviceBus ? AZURE_BOM : ''}
    </dependencies>
  </dependencyManagement>

  <dependencies>
${dep('io.quarkus', 'quarkus-arc')}
${dep('io.quarkus', 'quarkus-rest')}
${dep('io.quarkus', 'quarkus-rest-jackson')}
${dep('io.quarkus', 'quarkus-agroal')}
${dep('io.quarkus', 'quarkus-jdbc-postgresql')}
${dep('io.quarkus', 'quarkus-scheduler')}
${dep('io.quarkus', 'quarkus-smallrye-health')}
${dep('io.opentelemetry', 'opentelemetry-api')}
${dep('io.opentelemetry', 'opentelemetry-sdk')}
${dep('io.opentelemetry', 'opentelemetry-exporter-otlp', `
      <exclusions>
        <exclusion>
          <groupId>io.opentelemetry</groupId>
          <artifactId>opentelemetry-exporter-sender-okhttp</artifactId>
        </exclusion>
      </exclusions>`)}
${dep('io.opentelemetry', 'opentelemetry-exporter-sender-jdk')}
${dep('com.rabbitmq', 'amqp-client', `\n      <version>${JVM_VERSIONS.amqpClient}</version>`)}${serviceBus ? AZURE_DEPS : ''}${kafka ? KAFKA_DEPS : ''}

${dep('io.quarkus', 'quarkus-junit5', test)}
${dep('io.opentelemetry', 'opentelemetry-sdk-testing', test)}
${dep('io.cucumber', 'cucumber-java', test)}
${dep('io.cucumber', 'cucumber-junit-platform-engine', test)}
${dep('org.junit.platform', 'junit-platform-suite', test)}
  </dependencies>

  <build>
    <testResources>
      <testResource>
        <directory>src/test/resources</directory>
      </testResource>
      <!-- The Gherkin specification is the single source of truth: run it from ./features. -->
      <testResource>
        <directory>features</directory>
        <targetPath>features</targetPath>
      </testResource>
    </testResources>
    <plugins>
      <plugin>
        <groupId>io.quarkus.platform</groupId>
        <artifactId>quarkus-maven-plugin</artifactId>
        <version>\${quarkus.platform.version}</version>
        <extensions>true</extensions>
        <executions>
          <execution>
            <goals>
              <goal>build</goal>
              <goal>generate-code</goal>
              <goal>generate-code-tests</goal>
            </goals>
          </execution>
        </executions>
      </plugin>
      <plugin>
        <groupId>org.apache.maven.plugins</groupId>
        <artifactId>maven-compiler-plugin</artifactId>
        <version>${JVM_VERSIONS.mavenCompilerPlugin}</version>
        <configuration>
          <parameters>true</parameters>
        </configuration>
      </plugin>
      <plugin>
        <groupId>org.apache.maven.plugins</groupId>
        <artifactId>maven-surefire-plugin</artifactId>
        <version>${JVM_VERSIONS.mavenSurefirePlugin}</version>
        <configuration>
          <groups>\${test.groups}</groups>
          <excludedGroups>\${test.excludedGroups}</excludedGroups>
          <systemPropertyVariables>
            <java.util.logging.manager>org.jboss.logmanager.LogManager</java.util.logging.manager>
            <maven.home>\${maven.home}</maven.home>
          </systemPropertyVariables>
        </configuration>
      </plugin>
    </plugins>
  </build>

  <profiles>
    <profile>
      <id>integration</id>
      <properties>
        <test.groups>integration</test.groups>
        <test.excludedGroups></test.excludedGroups>
      </properties>
    </profile>
  </profiles>
</project>
`;
}

