/* ==========================================================================
   gherkin-ai-cli - CLI commands: generation (init, stacks, generate, add, detect, upgrade)
   ========================================================================== */

import type { Command } from 'commander';
import { logger } from '../utils/logger';
import { emitJson } from '../utils/output';

export function registerGenerationCommands(program: Command): void {
  program
    .command('upgrade')
    .description('Assisted upgrade of a project generated by an older version: checks config, CI scripts and MCP clients, then regenerates on a new git branch')
    .option('--apply', 'Apply the automatic changes (default: report only; asks interactively)')
    .option('--check', 'Report only, and exit with code 4 when required changes are pending (for CI)')
    .option('-c, --config <file>', 'Path to project gherkin-ai.config.json')
    .option('--branch <name>', 'Branch to create for the upgrade (default: ghk-upgrade-v<version>)')
    .option('--no-git', 'Apply in the working tree without creating a branch')
    .option('--commit', 'Commit the result on the upgrade branch')
    .option('--no-regenerate', 'Only fix the configuration; do not regenerate')
    .option('--prune', 'Also delete previously generated files that are no longer generated but cannot be proven unedited')
    .option('--cli', 'Also check the npm registry for a newer CLI version')
    .option('--force', 'Allow uncommitted changes in the working tree')
    .option('--json', 'Output the report as JSON')
    .option('--kernel', 'Only refresh the runtime kernel: unedited kernel files are replaced, edited ones get <file>.ghk-new')
    .option('--all', 'With --kernel: every gherkin-ai project under the current directory')
    .option('--dry-run', 'With --kernel: report what would change without writing')
    .action(async (options) => {
      const upgrade = await import('../commands/upgrade');
      if (options.kernel) {
        await upgrade.handleKernelRefresh({ all: options.all, dryRun: options.dryRun, json: options.json });
        return;
      }
      await upgrade.handleUpgradeCommand({ ...options, yes: program.opts().yes || program.opts().nonInteractive });
    });

  program
    .command('stacks')
    .description('List supported stacks and their support tier (stable / beta / experimental)')
    .option('--json', 'Output as JSON')
    .action(async (options) => {
      const { STACK_SUPPORT } = await import('../generators/stack-support');
      if (options.json) {
        emitJson(STACK_SUPPORT);
        return;
      }
      for (const s of STACK_SUPPORT) logger.info(`${s.kind.padEnd(10)} ${s.tier.padEnd(13)} ${(s.maintenance ?? 'core').padEnd(10)} ${s.label}${s.notes ? `  — ${s.notes}` : ''}`);
    });

  program
    .command('init')

    .alias('i')
    .description('Initialize interactive gherkin-ai project configuration (gherkin-ai.config.json)')
    .option('--enterprise', 'Initialize with enterprise constitution guardrails')
    .option('-p, --projectName <name>', 'Project name')
    .option('-a, --architecture <arch>', 'Primary software architecture')
    .option('--industry <id>', 'Industry reference standard: banking, telecom, manufacturing, health, supply-chain, insurance, aviation, automotive, education, generic')
    .option('-l, --language <lang>', 'Programming language / runtime')
    .option('-f, --framework <framework>', 'Primary framework')
    .option('--frameworkVersion <major>', 'Framework major to generate for (NestJS: 11 default, 12 = ES modules)')
    .option('-o, --orm <orm>', 'Database ORM / persistence')
    .option('--ormVersion <major>', 'ORM major to generate for (Prisma: 6 default, 7)')
    .option('-d, --database <db>', 'Database engine')
    .option('-v, --validation <lib>', 'Validation library')
    .option('-m, --messaging <broker>', 'Event broker / messaging')
    .option('-t, --testing <testing>', 'Testing framework')
    .option('--frontendFramework <framework>', 'Frontend Framework / Library')
    .option('--frontendLanguage <lang>', 'Frontend Language')
    .option('--frontendBundler <bundler>', 'Frontend Bundler')
    .option('--frontendUnitTesting <testing>', 'Frontend Unit Testing Framework')
    .option('--frontendE2eTesting <testing>', 'Frontend E2E Testing Framework')
    .option('--outputDir <dir>', 'Output directory for generated contracts')
    .option('--force', 'Replace an existing gherkin-ai.config.json and .ghkgovernance.yaml')
    .action(async (options) => {
      await (await import('../commands/init')).handleInitCommand(options);
    });

  program
    .command('detect')
    .alias('d')
    .description('Auto-detect tech stack & architecture of an existing project and save it as gherkin-ai.config.json (Brownfield mode)')
    .option('--json', 'Report the detected stack as JSON without saving a configuration')
    .action(async (options) => {
      await (await import('../commands/detect')).handleDetectCommand(options);
    });

  program
    .command('add')
    .alias('a')
    .description('Inject contracts & AI agent prompts into an existing project module (Brownfield mode)')
    .option('-f, --feature <file>', 'Path to Gherkin .feature file')
    .option('-t, --target <directory>', 'Target directory inside existing project')
    .option('-c, --config <file>', 'Path to custom gherkin-ai.config.json file')
    .action(async (options) => {
      await (await import('../commands/add')).handleAddCommand(options);
    });

  program
    .command('generate')
    .alias('g')
    .description('Generate TypeScript contracts, DTO schemas, test fixtures, docker-compose, and agent prompts from Gherkin feature spec')
    .option('-f, --feature <file>', 'Path to Gherkin .feature file')
    .option('-c, --config <file>', 'Path to custom gherkin-ai.config.json file')
    .option('--force', 'Overwrite files even if they were edited since generation or are protected')
    .option('--dry-run', 'Show what would be created, updated or kept, without writing')
    .option('--review', 'Review the <file>.ghk-new versions next to edited files: take the generated version or keep yours')
    .option('--accept-new', 'With --review: take every generated version')
    .option('--keep-mine', 'With --review: keep every edited file (those generated versions are not offered again)')
    .option('--include-scaffold', 'In a project marked .ghk-implemented, also create controllers, wiring and tests (only the kernel and contracts by default)')
    .option('--contracts-only', 'Write only the contracts (OpenAPI, AsyncAPI, gRPC, GraphQL, ADR) and skip everything else')
    .option('--json', 'Output the write plan as JSON (with --review: the pending versions)')
    .action(async (options) => {
      const json = options.json || program.opts().json;
      if (options.review) {
        await (await import('../commands/review')).handleGenerateReview({ ...options, json });
        return;
      }
      await (await import('../commands/generate')).handleGenerateCommand({ ...options, json });
    });
}
