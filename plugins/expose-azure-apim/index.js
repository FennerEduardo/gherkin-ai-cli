'use strict';
/* ==========================================================================
   @gherkin-ai/expose-azure-apim — gateway provider `azure-apim` for ghk expose
   (plugin API 2, experimental; PLAN-3.3.0-reverse-plus EX-12).

   An API on an existing Azure API Management instance, in front of the MCP
   runtime generated by `ghk expose generate` (hosted on Container Apps,
   AKS or App Service): one POST /mcp operation, and an APIM policy that
   validates the caller's JWT (validate-jwt), limits the rate per caller
   (rate-limit-by-key) and keeps traceparent. Everything else stays in the
   runtime, which authorizes every call again.

   Experimental: validated with `terraform validate` only, never applied by
   gherkin-ai. The full provider (APIM's own MCP server support, private
   networking) is planned for 3.4.
   ========================================================================== */

const CAPABILITIES = {
  'inbound-auth': 'native',
  'per-tool-authz': 'runtime',
  'tenant-isolation': 'runtime',
  'outbound-credentials': 'runtime',
  'rate-limit': 'native',
  'human-approval': 'runtime',
  audit: 'runtime',
  'private-network': 'unsupported',
  'tool-discovery': 'unsupported'
};

const q = s => JSON.stringify(s);
const kebab = s => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || 'service';
const approved = m => m.capabilities.filter(c => c.status === 'approved');
const xml = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function policy(options) {
  const audiences = (options.audiences || []).map(a => `          <audience>${xml(a)}</audience>`).join('\n');
  return `<policies>
  <inbound>
    <base />
    <!-- First boundary: the caller's token. The runtime validates it again. -->
    <validate-jwt header-name="Authorization" failed-validation-httpcode="401" require-scheme="Bearer" output-token-variable-name="jwt">
      <openid-config url="\${var.discovery_url}" />
      <audiences>
${audiences || '          <audience>${var.audience}</audience>'}
      </audiences>
    </validate-jwt>
    <rate-limit-by-key calls="\${var.calls_per_minute}" renewal-period="60" counter-key="@(((Jwt)context.Variables[&quot;jwt&quot;]).Subject)" />
    <set-header name="traceparent" exists-action="skip">
      <value>@(context.Request.Headers.GetValueOrDefault("traceparent", ""))</value>
    </set-header>
  </inbound>
  <backend>
    <forward-request timeout="60" />
  </backend>
  <outbound>
    <base />
  </outbound>
  <on-error>
    <base />
  </on-error>
</policies>`;
}

function mainTf(manifest, options) {
  const name = kebab(manifest.service);
  const tools = approved(manifest).map(c => c.name).join(', ');
  return `# Generated by @gherkin-ai/expose-azure-apim (experimental) from .ghk/capabilities.yaml: ${tools || 'no tool'}.
terraform {
  required_version = ">= 1.10"

  required_providers {
    azurerm = {
      source  = "hashicorp/azurerm"
      version = "~> 5.10"
    }
  }
}

provider "azurerm" {
  features {}
}

variable "resource_group_name" {
  description = "Resource group of the existing API Management instance."
  type        = string
}

variable "api_management_name" {
  description = "Name of the existing API Management instance."
  type        = string
}

variable "runtime_url" {
  description = "HTTPS base URL of the generated MCP runtime (its /mcp path is appended)."
  type        = string
}

variable "discovery_url" {
  description = "OIDC discovery URL of the callers' identity provider."
  type        = string
  default     = ${q(options.discoveryUrl || '')}
}

variable "audience" {
  description = "Accepted audience when none was given to ghk expose generate."
  type        = string
  default     = ${q((options.audiences || [])[0] || '')}
}

variable "calls_per_minute" {
  description = "Calls per minute and caller, enforced by APIM."
  type        = number
  default     = 60
}

data "azurerm_api_management" "apim" {
  name                = var.api_management_name
  resource_group_name = var.resource_group_name
}

resource "azurerm_api_management_api" "mcp" {
  name                  = ${q(`${name}-mcp`)}
  resource_group_name   = var.resource_group_name
  api_management_name   = data.azurerm_api_management.apim.name
  revision              = "1"
  display_name          = ${q(`${manifest.service} MCP (${options.environment})`)}
  path                  = ${q(`${name}`)}
  protocols             = ["https"]
  service_url           = var.runtime_url
  subscription_required = false
}

resource "azurerm_api_management_api_operation" "mcp" {
  operation_id        = "mcp"
  api_name            = azurerm_api_management_api.mcp.name
  api_management_name = data.azurerm_api_management.apim.name
  resource_group_name = var.resource_group_name
  display_name        = "MCP (Streamable HTTP)"
  method              = "POST"
  url_template        = "/mcp"
}

resource "azurerm_api_management_api_policy" "mcp" {
  api_name            = azurerm_api_management_api.mcp.name
  api_management_name = data.azurerm_api_management.apim.name
  resource_group_name = var.resource_group_name
  xml_content         = <<-XML
${policy(options).split('\n').map(l => `    ${l}`).join('\n')}
  XML
}

output "mcp_url" {
  description = "MCP endpoint agents connect to."
  value       = "\${data.azurerm_api_management.apim.gateway_url}/${name}/mcp"
}
`;
}

module.exports = {
  name: '@gherkin-ai/expose-azure-apim',
  version: '0.1.0',
  apiVersion: 2,
  engines: { 'gherkin-ai': '^3.3' },
  gatewayProviders: () => [{
    id: 'azure-apim',
    label: 'Azure API Management in front of the MCP runtime (Terraform, experimental)',
    tier: 'community',
    maturity: 'experimental',
    capabilities: () => ({ ...CAPABILITIES }),
    plan: (manifest, options) => ({
      provider: 'azure-apim',
      tools: approved(manifest).map(c => ({ tool: c.name, effect: c.effect, scopes: c.authorization.scopes, approval: c.execution.approval, controls: { ...CAPABILITIES } })),
      resources: [
        `azurerm_api_management_api: ${manifest.service} MCP on an existing API Management instance (${options.environment})`,
        'azurerm_api_management_api_operation: POST /mcp',
        'azurerm_api_management_api_policy: validate-jwt, rate-limit-by-key per subject, traceparent'
      ],
      warnings: [
        'Experimental: validated with terraform validate only; never applied by gherkin-ai.',
        'The MCP runtime is not hosted by this provider: deploy expose/mcp-runtime on Container Apps, AKS or App Service and pass its URL.',
        'Per-tool authorization, tenants and approvals are enforced by the runtime; APIM sees one /mcp operation.',
        'Private networking and tool search are not configured.'
      ]
    }),
    emit: (manifest, options) => [{ path: 'main.tf', content: mainTf(manifest, options) }],
    validateCommand: ['sh', '-c', 'terraform init -backend=false -input=false -no-color && terraform validate -no-color'],
    applyCommands: [['terraform', 'init', '-input=false'], ['terraform', 'apply', '-input=false']],
    tradeOffs: ['Reuses an API Management instance an organization already runs (its policies, analytics and keys); the agent-facing layer is one passthrough API, so per-tool controls stay in the runtime.']
  }]
};
