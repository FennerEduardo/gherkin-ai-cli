'use strict';
/* ==========================================================================
   @gherkin-ai/expose-gcp — gateway provider `gcp-apigateway` for ghk expose
   (plugin API 2, experimental; PLAN-3.3.0-reverse-plus EX-12).

   Google Cloud API Gateway in front of the MCP runtime generated by
   `ghk expose generate` (hosted on Cloud Run): an API config whose OpenAPI
   document routes POST /mcp to the runtime and validates the caller's JWT
   (x-google-issuer, x-google-jwks_uri, x-google-audiences). The document is
   annotated with the approved tools (x-ghk-tools), for review. Everything
   else stays in the runtime, which authorizes every call again.

   Experimental: validated with `terraform validate` only, never applied by
   gherkin-ai. The full provider is planned for 3.4.
   ========================================================================== */

const CAPABILITIES = {
  'inbound-auth': 'native',
  'per-tool-authz': 'runtime',
  'tenant-isolation': 'runtime',
  'outbound-credentials': 'runtime',
  'rate-limit': 'runtime',
  'human-approval': 'runtime',
  audit: 'runtime',
  'private-network': 'unsupported',
  'tool-discovery': 'unsupported'
};

const q = s => JSON.stringify(s);
const kebab = s => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 40) || 'service';
const approved = m => m.capabilities.filter(c => c.status === 'approved');

function mainTf(manifest, options) {
  const name = kebab(manifest.service);
  const tools = approved(manifest).map(c => ({ name: c.name, effect: c.effect, scopes: c.authorization.scopes, approval: c.execution.approval }));
  return `# Generated by @gherkin-ai/expose-gcp (experimental) from .ghk/capabilities.yaml.
terraform {
  required_version = ">= 1.10"

  required_providers {
    google-beta = {
      source  = "hashicorp/google-beta"
      version = "~> 8.7"
    }
  }
}

provider "google-beta" {
  project = var.project_id
  region  = var.region
}

variable "project_id" {
  description = "Google Cloud project."
  type        = string
}

variable "region" {
  description = "Region of the gateway."
  type        = string
  default     = ${q(options.region || 'us-central1')}
}

variable "runtime_url" {
  description = "HTTPS URL of the generated MCP runtime on Cloud Run."
  type        = string
}

variable "issuer" {
  description = "Issuer of the callers' tokens."
  type        = string
  default     = ${q((options.discoveryUrl || '').replace(/\/\.well-known\/openid-configuration$/, ''))}
}

variable "jwks_uri" {
  description = "JWKS URL of the issuer."
  type        = string
}

variable "audiences" {
  description = "Accepted audiences."
  type        = list(string)
  default     = [${(options.audiences || []).map(q).join(', ')}]
}

locals {
  # OpenAPI 2.0 (API Gateway): POST /mcp to the runtime, JWT validated at the gateway.
  openapi = yamlencode({
    swagger = "2.0"
    info = {
      title   = ${q(`${manifest.service} MCP`)}
      version = "1.0.0"
    }
    schemes            = ["https"]
    produces           = ["application/json"]
    "x-google-backend" = { address = var.runtime_url, path_translation = "APPEND_PATH_TO_ADDRESS", deadline = 60 }
    "x-ghk-tools"      = jsondecode(${q(JSON.stringify(tools))})
    securityDefinitions = {
      oidc = {
        authorizationUrl     = ""
        flow                 = "implicit"
        type                 = "oauth2"
        "x-google-issuer"    = var.issuer
        "x-google-jwks_uri"  = var.jwks_uri
        "x-google-audiences" = join(",", var.audiences)
      }
    }
    security = [{ oidc = [] }]
    paths = {
      "/mcp" = {
        post = {
          operationId = "mcp"
          summary     = ${q(`MCP (Streamable HTTP) of ${manifest.service} (${options.environment})`)}
          responses   = { "200" = { description = "JSON-RPC answer" } }
        }
      }
    }
  })
}

resource "google_api_gateway_api" "mcp" {
  provider = google-beta
  api_id   = ${q(`${name}-mcp`)}
}

resource "google_api_gateway_api_config" "mcp" {
  provider      = google-beta
  api           = google_api_gateway_api.mcp.api_id
  api_config_id = ${q(`${name}-mcp-v1`)}

  openapi_documents {
    document {
      path     = "openapi.yaml"
      contents = base64encode(local.openapi)
    }
  }

  lifecycle {
    create_before_destroy = true
  }
}

resource "google_api_gateway_gateway" "mcp" {
  provider   = google-beta
  gateway_id = ${q(`${name}-mcp`)}
  api_config = google_api_gateway_api_config.mcp.id
  region     = var.region
}

output "mcp_url" {
  description = "MCP endpoint agents connect to."
  value       = "https://\${google_api_gateway_gateway.mcp.default_hostname}/mcp"
}
`;
}

module.exports = {
  name: '@gherkin-ai/expose-gcp',
  version: '0.1.0',
  apiVersion: 2,
  engines: { 'gherkin-ai': '^3.3' },
  gatewayProviders: () => [{
    id: 'gcp-apigateway',
    label: 'Google Cloud API Gateway in front of the MCP runtime (Terraform, experimental)',
    tier: 'community',
    maturity: 'experimental',
    capabilities: () => ({ ...CAPABILITIES }),
    plan: (manifest, options) => ({
      provider: 'gcp-apigateway',
      tools: approved(manifest).map(c => ({ tool: c.name, effect: c.effect, scopes: c.authorization.scopes, approval: c.execution.approval, controls: { ...CAPABILITIES } })),
      resources: [
        `google_api_gateway_api, _api_config and _gateway: ${manifest.service} MCP (${options.environment})`,
        'OpenAPI 2.0 config: POST /mcp to the runtime, JWT validated by the gateway, approved tools annotated (x-ghk-tools)'
      ],
      warnings: [
        'Experimental: validated with terraform validate only; never applied by gherkin-ai.',
        'The MCP runtime is not hosted by this provider: deploy expose/mcp-runtime on Cloud Run and pass its URL.',
        'Rate limits, per-tool authorization, tenants and approvals are enforced by the runtime.',
        'Private networking and tool search are not configured.'
      ]
    }),
    emit: (manifest, options) => [{ path: 'main.tf', content: mainTf(manifest, options) }],
    validateCommand: ['sh', '-c', 'terraform init -backend=false -input=false -no-color && terraform validate -no-color'],
    applyCommands: [['terraform', 'init', '-input=false'], ['terraform', 'apply', '-input=false']],
    tradeOffs: ['A managed, pay-per-call gateway with JWT validation in front of Cloud Run; one passthrough route, so per-tool controls stay in the runtime.']
  }]
};
